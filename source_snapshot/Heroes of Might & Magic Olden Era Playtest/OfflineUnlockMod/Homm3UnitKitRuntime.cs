/// <summary>
/// Unit-kit mechanics that Core data cannot express, for the unit design tables
/// (custom_factions/unit_designs/*.json, plan docs/unit_rebalance_plan_20261120.md). The rules are keyed by unit
/// SID, never by a faction or hero skill, so a unit behaves the same in any army. The full rule contract, with every
/// kind and parameter, is docs/unit_ability_pass_20261121/RUNTIME_CONTRACT.md.
///
/// Table: Homm3UnitKitRules.g.cs, generated by tools/release_port/build_unit_kit_runtime_table.py.
///
/// This class owns the damage step and the buff-add rewrites:
/// - holder deals damage: damage_vs_buff, grudge, loss_fury, death_toll, turn_state, counter_state, adjacency, crowd,
///   hit_this_round, first_hit (attacker), damage_vs_hp, bounty, retribution, same_target_streak, stored_fury, quarry,
///   wall_slam. Filters: Rule.Attack (any / melee / ranged) and Rule.AbilityOnly read the holder's committed ability.
/// - holder takes damage: adjacent_ally_ward, hit_cap, first_hit (defender), bodyguard (the share is taken off here;
///   <see cref="Homm3UnitKitBattleHooks"/> deals it to the guard).
/// - free attacks the hooks queued (guard_strike, zone_shot, spell_echo) deal Rule.Percent of a normal hit.
/// - buff swaps (<see cref="SwapAddedBuff"/>): rotate (Master Genie "Wish"), escalate to / unless (Ice Elemental
///   "Frostbite" into Frozen), escalate chain (stacking by distinct SIDs), scale_by_caster (Ignite tiers), and the
///   quarry mark bookkeeping.
/// - covering_fire: the reaction shot lives in <see cref="Homm3RampartAvengerStrikeRuntime"/>; this class only names
///   the armed buff.
///
/// Battle facts (who acted, moved, waited, countered, which ability a unit committed, the grid) come from
/// <see cref="Homm3UnitKitBattleHooks"/>. The damage rules contribute a percent to the single committed-damage owner
/// (<see cref="Homm3CounterattackDoctrineMutationRuntime"/>), like Fortress Predator Instinct. The in-game damage
/// forecast and the AI do not include them. Every path fails closed to no bonus; a rule kind that throws is disabled
/// for the session and logged once.
/// Proof tier: build only; runtime unproven.
/// </summary>
internal static class Homm3UnitKitRuntime
{
	private static readonly object Gate = new();
	/// <summary>Grudge holder unit key → keys of the stacks that have damaged it this battle.</summary>
	private static readonly Dictionary<long, HashSet<long>> GrudgeByHolder = new();
	/// <summary>Unit key → its rules (null when the unit has none); filled lazily, cleared with the battle.</summary>
	private static readonly Dictionary<long, Homm3UnitKitRules.Rule[]> RulesByUnit = new();

	/// <summary>Unit key → the largest stack health seen this battle (its "full health").</summary>
	private static readonly Dictionary<long, int> FullHealthByHolder = new();

	/// <summary>Stacks destroyed this battle (death_toll), by unit key.</summary>
	private static readonly HashSet<long> FallenStacks = new();
	/// <summary>Rotation position per (caster key, rotating buff SID).</summary>
	private static readonly Dictionary<(long, string), int> RotationByCaster = new();
	/// <summary>first_hit attacker: holder key → commit serial of its first attack this round.</summary>
	private static readonly Dictionary<long, long> FirstAttackSerial = new();
	/// <summary>first_hit defender: holder key → (attacker key, commit serial) of the first attack on it this round.</summary>
	private static readonly Dictionary<long, (long, long)> FirstAttackTaken = new();
	/// <summary>same_target_streak: holder key → (last target key, last serial, streak).</summary>
	private static readonly Dictionary<long, (long Target, long Serial, int Streak)> Streaks = new();
	/// <summary>stored_fury: holder key → stored percent.</summary>
	private static readonly Dictionary<long, int> StoredFury = new();
	/// <summary>stored_fury: holder key → (serial that spent the fury, percent it gets).</summary>
	private static readonly Dictionary<long, (long Serial, int Percent)> SpentFury = new();
	/// <summary>stored_fury: holder key → (attacker key, serial) of the last attack that charged it.</summary>
	private static readonly Dictionary<long, (long, long)> FuryCharge = new();
	/// <summary>quarry: holder key → key of the stack it most recently marked.</summary>
	private static readonly Dictionary<long, long> QuarryByHolder = new();
	private static readonly HashSet<Kind> Disabled = new();

	/// <summary>The last swap decision: the game may route one application through more than one add method.</summary>
	private static IntPtr _lastSwapManager;
	private static string _lastSwapFrom;
	private static string _lastSwapTo;
	private static long _lastSwapTicks;
	private const long SwapRepeatWindowTicks = 100 * TimeSpan.TicksPerMillisecond;

	private static readonly HashSet<Kind> KindsInTable = CollectKinds();
	private static readonly HashSet<string> QuarryBuffs = CollectQuarryBuffs();

	internal static string CoveringFireBuffSid => Homm3UnitKitRules.CoveringFireBuffSid;

	/// <summary>True when some unit row or Artificing graft has a rule of this kind.</summary>
	internal static bool TableHas(Kind kind) => KindsInTable.Contains(kind);

	internal static bool HasQuarryRules => QuarryBuffs.Count > 0;

	/// <summary>Battle scope ended or changed: forget every grudge and cached rule.</summary>
	internal static void ClearForBattle()
	{
		lock (Gate)
		{
			GrudgeByHolder.Clear();
			FullHealthByHolder.Clear();
			RulesByUnit.Clear();
			FallenStacks.Clear();
			RotationByCaster.Clear();
			FirstAttackSerial.Clear();
			FirstAttackTaken.Clear();
			Streaks.Clear();
			StoredFury.Clear();
			SpentFury.Clear();
			FuryCharge.Clear();
			QuarryByHolder.Clear();
			_lastSwapManager = IntPtr.Zero;
			_lastSwapFrom = _lastSwapTo = null;
		}
		Homm3UnitKitBattleHooks.ClearForBattle();
	}

	/// <summary>A unit (re)initialised under this key: its old grudges and cached rules no longer apply.</summary>
	internal static void ForgetUnit(long unitKey)
	{
		if (unitKey == 0)
			return;
		lock (Gate)
		{
			GrudgeByHolder.Remove(unitKey);
			FullHealthByHolder.Remove(unitKey);
			RulesByUnit.Remove(unitKey);
			FallenStacks.Remove(unitKey);
			Streaks.Remove(unitKey);
			StoredFury.Remove(unitKey);
			SpentFury.Remove(unitKey);
			FuryCharge.Remove(unitKey);
			QuarryByHolder.Remove(unitKey);
			foreach (var set in GrudgeByHolder.Values)
				set.Remove(unitKey);
		}
	}

	/// <summary>A new round: per-round first-hit marks reset.</summary>
	internal static void OnRoundStarted()
	{
		lock (Gate)
		{
			FirstAttackSerial.Clear();
			FirstAttackTaken.Clear();
		}
	}

	/// <summary>A rule kind threw: off for the rest of the session, logged once.</summary>
	internal static void DisableKind(Kind kind, Exception ex)
	{
		bool first;
		lock (Gate)
			first = Disabled.Add(kind);
		if (first)
			Homm3UnitKitBattleHooks.LogWarning("rule " + kind + " disabled for this session after an error: " + ex.GetBaseException().Message);
	}

	internal static bool IsDisabled(Kind kind)
	{
		lock (Gate)
			return Disabled.Contains(kind);
	}

	/// <summary>
	/// Percent contribution for one committed hit of <paramref name="caster"/> on <paramref name="receiver"/>, and the
	/// grudge bookkeeping for that hit (the receiver remembers who damaged it). Call once per damaging hit.
	/// </summary>
	internal static int DamagePercent(object caster, object receiver, out string detail)
	{
		detail = null;
		if (Homm3UnitKitRules.Rules.Count == 0 || receiver == null)
			return 0;
		// A splash, feedback or bodyguard share is already sized: no rule touches it again.
		if (Homm3UnitKitBattleHooks.InNestedDamage)
			return 0;
		try
		{
			var receiverKey = Homm3DirectStateIdentity.ResolveKeyOrZero(receiver);
			if (receiverKey == 0)
				return 0;
			var receiverRules = RulesFor(receiver, receiverKey);
			var receiverUnit = AsUnit(receiver);
			var percent = 0;
			var casterKey = caster == null ? 0 : Homm3DirectStateIdentity.ResolveKeyOrZero(caster);
			var casterUnit = AsUnit(caster);
			Homm3UnitKitBattleHooks.CommitInfo commit = default;
			var hasCommit = casterKey != 0 && Homm3UnitKitBattleHooks.TryGetCommit(casterKey, out commit);
			var unitAttack = casterKey != 0 && casterKey != receiverKey && hasCommit && commit.IsAttack;
			if (TableHas(Kind.DamageVsHp))
				TrackFullHealth(receiver, receiverKey, out _, out _);

			// Receiver-side rules apply to every damage source unless they say otherwise (a hero spell has no unit caster).
			if (receiverRules != null)
			{
				foreach (var rule in receiverRules)
				{
					if (IsDisabled(rule.Kind))
						continue;
					try
					{
						switch (rule.Kind)
						{
							case Kind.AdjacentAllyWard:
							{
								var allies = receiverUnit == null ? -1 : Homm3RampartAvengerStrikeRuntime.CountAdjacentAllies(receiverUnit);
								if (allies <= 0)
									break;
								var ward = Math.Min(rule.Cap, rule.Percent * allies);
								percent -= ward;
								detail = Append(detail, rule.Name + " -" + ward + "% (" + allies + " adjacent allies)");
								break;
							}
							case Kind.LossFury:
								// loss_fury measures from the largest health seen: note it before this hit lands.
								TrackFullHealth(receiver, receiverKey, out _, out _);
								break;
							case Kind.FirstHit when rule.Choice == Homm3UnitKitRules.SideDefender && unitAttack:
							{
								bool first;
								lock (Gate)
								{
									if (!FirstAttackTaken.TryGetValue(receiverKey, out var mark))
										FirstAttackTaken[receiverKey] = mark = (casterKey, commit.Serial);
									first = mark == (casterKey, commit.Serial);
								}
								if (first)
								{
									percent -= rule.Percent;
									detail = Append(detail, rule.Name + " -" + rule.Percent + "% (first attack on it this round)");
								}
								break;
							}
						}
					}
					catch (Exception ex)
					{
						DisableKind(rule.Kind, ex);
					}
				}
			}
			// bodyguard: an adjacent friendly guard takes a share of a unit attack on this stack.
			if (unitAttack && receiverUnit != null && TableHas(Kind.Bodyguard) && !IsDisabled(Kind.Bodyguard))
			{
				try
				{
					if (Homm3UnitKitBattleHooks.TryClaimBodyguard(receiverUnit, receiverKey, out var guardRule, out var guardName))
					{
						percent -= guardRule.Percent;
						detail = Append(detail, guardRule.Name + " -" + guardRule.Percent + "% (taken by " + guardName + ")");
					}
				}
				catch (Exception ex)
				{
					DisableKind(Kind.Bodyguard, ex);
				}
			}
			if (casterKey == 0 || casterKey == receiverKey)
				return percent;

			// Free attacks queued by guard_strike / zone_shot / spell_echo deal their rule's percent of a normal hit.
			var scaled = Homm3UnitKitBattleHooks.ScaledStrikePercent(casterKey, out var scaledName);
			if (scaled > 0 && scaled != 100)
			{
				percent += scaled - 100;
				detail = Append(detail, scaledName + " strike at " + scaled + "%");
			}

			var casterRules = RulesFor(caster, casterKey);
			if (casterRules != null)
			{
				var context = new HitContext(casterUnit, casterKey, receiverUnit, receiver, receiverKey, hasCommit, commit);
				foreach (var rule in casterRules)
				{
					if (IsDisabled(rule.Kind) || !PassesFilters(rule, context))
						continue;
					try
					{
						var bonus = CasterBonus(rule, context, out var why);
						if (bonus == 0)
							continue;
						percent += bonus;
						detail = Append(detail, rule.Name + " " + bonus.ToString("+0;-0") + "%" + (why == null ? "" : " (" + why + ")"));
					}
					catch (Exception ex)
					{
						DisableKind(rule.Kind, ex);
					}
				}
			}
			if (receiverRules != null)
			{
				foreach (var rule in receiverRules)
				{
					if (rule.Kind != Kind.Grudge)
						continue;
					lock (Gate)
					{
						if (!GrudgeByHolder.TryGetValue(receiverKey, out var set))
							GrudgeByHolder[receiverKey] = set = new HashSet<long>();
						set.Add(casterKey);
					}
					break;
				}
			}
			return percent;
		}
		catch
		{
			detail = null;
			return 0;
		}
	}

	private readonly struct HitContext
	{
		internal readonly Unit Caster;
		internal readonly long CasterKey;
		internal readonly Unit Receiver;
		internal readonly object ReceiverObject;
		internal readonly long ReceiverKey;
		internal readonly bool HasCommit;
		internal readonly Homm3UnitKitBattleHooks.CommitInfo Commit;

		internal HitContext(Unit caster, long casterKey, Unit receiver, object receiverObject, long receiverKey, bool hasCommit, Homm3UnitKitBattleHooks.CommitInfo commit)
		{
			Caster = caster;
			CasterKey = casterKey;
			Receiver = receiver;
			ReceiverObject = receiverObject;
			ReceiverKey = receiverKey;
			HasCommit = hasCommit;
			Commit = commit;
		}
	}

	/// <summary>Rule.Attack and Rule.AbilityOnly against the holder's committed ability; unknown fails closed.</summary>
	private static bool PassesFilters(Homm3UnitKitRules.Rule rule, in HitContext hit)
	{
		if (rule.AbilityOnly && !(hit.HasCommit && hit.Commit.Type == EAbilityType.Ability))
			return false;
		if (rule.Attack == Homm3UnitKitRules.AttackAny)
			return true;
		bool ranged;
		if (hit.HasCommit && hit.Commit.IsAttack)
			ranged = hit.Commit.Ranged;
		else if (hit.Caster != null)
			ranged = Homm3FortressPredatorInstinctRuntime.IsRanged(hit.Caster);
		else
			return false;
		return rule.Attack == Homm3UnitKitRules.AttackRanged ? ranged : !ranged;
	}

	private static int CasterBonus(Homm3UnitKitRules.Rule rule, in HitContext hit, out string why)
	{
		why = null;
		switch (rule.Kind)
		{
			case Kind.DamageVsBuff:
				if (Homm3BuffDebuffNativeAdapter.TryQueryAnyBuffSidFromReceiver(hit.ReceiverObject, rule.BuffSids, out var info, out _) && info.HasSid)
				{
					why = "vs " + info.Sid;
					return rule.Percent;
				}
				return 0;
			case Kind.Grudge:
				lock (Gate)
				{
					if (GrudgeByHolder.TryGetValue(hit.CasterKey, out var set) && set.Contains(hit.ReceiverKey))
					{
						why = "vs a stack that damaged it";
						return rule.Percent;
					}
				}
				return 0;
			case Kind.LossFury:
			{
				if (hit.Caster == null || !TrackFullHealth(hit.Caster, hit.CasterKey, out var health, out var full) || full <= 0 || health >= full)
					return 0;
				var fury = (int)Math.Min(rule.Cap, (long)rule.Percent * (full - health) / full);
				why = health + " of " + full + " health left";
				return Math.Max(0, fury);
			}
			case Kind.DeathToll:
			{
				int fallen;
				lock (Gate)
					fallen = FallenStacks.Count;
				why = fallen + " stacks fallen";
				return Math.Min(rule.Cap, rule.Percent * fallen);
			}
			case Kind.TurnState:
				if (hit.Caster == null || !Homm3UnitKitBattleHooks.TurnFact(rule.Choice, hit.Caster, hit.CasterKey, hit.ReceiverKey, out why))
					return 0;
				return rule.Percent;
			case Kind.CounterState:
				if (hit.Receiver == null || !Homm3UnitKitBattleHooks.CounterFact(rule.Choice, hit.Receiver, hit.ReceiverKey, out why))
					return 0;
				return rule.Percent;
			case Kind.Adjacency:
			{
				if (hit.Caster == null || hit.Receiver == null
				    || !Homm3UnitKitBattleHooks.TryNeighbourhood(hit.Caster, hit.Receiver, out var flank, out var targetAllies, out _))
					return 0;
				if (rule.Choice == Homm3UnitKitRules.AdjacencyFlank ? flank > 0 : targetAllies == 0)
				{
					why = rule.Choice == Homm3UnitKitRules.AdjacencyFlank ? flank + " flanking all(ies)" : "target isolated";
					return rule.Percent;
				}
				return 0;
			}
			case Kind.Crowd:
			{
				if (hit.Caster == null || hit.Receiver == null
				    || !Homm3UnitKitBattleHooks.TryNeighbourhood(hit.Caster, hit.Receiver, out _, out _, out var enemies) || enemies <= 1)
					return 0;
				why = enemies + " adjacent enemies";
				return Math.Min(rule.Cap, rule.Percent * (enemies - 1));
			}
			case Kind.HitThisRound:
			{
				var others = hit.Caster == null ? 0 : Homm3UnitKitBattleHooks.OtherAlliesHitThisRound(hit.ReceiverKey, hit.Caster, hit.CasterKey);
				if (others <= 0)
					return 0;
				why = others + " other all(ies) hit it this round";
				return Math.Min(rule.Cap, rule.Percent * others);
			}
			case Kind.FirstHit:
			{
				if (rule.Choice != Homm3UnitKitRules.SideAttacker || !hit.HasCommit || !hit.Commit.IsAttack)
					return 0;
				bool first;
				lock (Gate)
				{
					if (!FirstAttackSerial.TryGetValue(hit.CasterKey, out var serial))
						FirstAttackSerial[hit.CasterKey] = serial = hit.Commit.Serial;
					first = serial == hit.Commit.Serial;
				}
				if (!first)
					return 0;
				why = "first attack this round";
				return rule.Percent;
			}
			case Kind.DamageVsHp:
			{
				if (!TrackFullHealth(hit.ReceiverObject, hit.ReceiverKey, out var health, out var full) || full <= 0)
					return 0;
				if ((long)health * 100 >= (long)rule.Below * full)
					return 0;
				why = health + " of " + full + " health";
				return rule.Percent;
			}
			case Kind.Bounty:
				if (hit.Receiver == null || !Homm3UnitKitBattleHooks.IsHealthiestOfItsSide(hit.Receiver))
					return 0;
				why = "healthiest enemy stack";
				return rule.Percent;
			case Kind.Retribution:
				if (hit.Caster == null || !Homm3UnitKitBattleHooks.DamagedSideThisRound(hit.Caster, hit.ReceiverKey))
					return 0;
				why = "it struck this side this round";
				return rule.Percent;
			case Kind.SameTargetStreak:
			{
				if (!hit.HasCommit || !hit.Commit.IsAttack)
					return 0;
				int streak;
				lock (Gate)
				{
					Streaks.TryGetValue(hit.CasterKey, out var state);
					if (state.Serial != hit.Commit.Serial)
					{
						state = (hit.ReceiverKey, hit.Commit.Serial, state.Target == hit.ReceiverKey && state.Serial != 0 ? state.Streak + 1 : 0);
						Streaks[hit.CasterKey] = state;
					}
					streak = state.Streak;
				}
				if (streak <= 0)
					return 0;
				why = streak + " attack(s) in a row on it";
				return Math.Min(rule.Cap, rule.Percent * streak);
			}
			case Kind.StoredFury:
			{
				if (!hit.HasCommit || !hit.Commit.IsAttack)
					return 0;
				int spent;
				lock (Gate)
				{
					if (SpentFury.TryGetValue(hit.CasterKey, out var used) && used.Serial == hit.Commit.Serial)
						spent = used.Percent;
					else
					{
						StoredFury.TryGetValue(hit.CasterKey, out spent);
						StoredFury[hit.CasterKey] = 0;
						SpentFury[hit.CasterKey] = (hit.Commit.Serial, spent);
					}
				}
				if (spent <= 0)
					return 0;
				why = "stored from attacks taken";
				return spent;
			}
			case Kind.Quarry:
			{
				bool marked;
				lock (Gate)
					marked = QuarryByHolder.TryGetValue(hit.CasterKey, out var quarry) && quarry == hit.ReceiverKey;
				if (!marked)
					return 0;
				why = "its quarry";
				return rule.Percent;
			}
			case Kind.WallSlam:
				if (hit.Caster == null || hit.Receiver == null || !Homm3UnitKitBattleHooks.IsBehindBlocked(hit.Caster, hit.Receiver, out why))
					return 0;
				return rule.Percent;
			default:
				return 0;
		}
	}

	/// <summary>stored_fury: the holder took a unit attack (one charge per attack, not per hit).</summary>
	internal static void NoteAttackTaken(object receiver, long receiverKey, long attackerKey, long serial)
	{
		if (!TableHas(Kind.StoredFury) || IsDisabled(Kind.StoredFury) || receiverKey == 0 || attackerKey == 0)
			return;
		try
		{
			var rules = RulesFor(receiver, receiverKey);
			if (rules == null)
				return;
			foreach (var rule in rules)
			{
				if (rule.Kind != Kind.StoredFury)
					continue;
				lock (Gate)
				{
					if (FuryCharge.TryGetValue(receiverKey, out var last) && last == (attackerKey, serial))
						return;
					FuryCharge[receiverKey] = (attackerKey, serial);
					StoredFury.TryGetValue(receiverKey, out var stored);
					StoredFury[receiverKey] = Math.Min(rule.Cap, stored + rule.Percent);
				}
				return;
			}
		}
		catch (Exception ex)
		{
			DisableKind(Kind.StoredFury, ex);
		}
	}

	/// <summary>
	/// Per-hit damage cap of the receiver (hit_cap), applied to the final committed damage after every percent
	/// rule. Also tracks the receiver's full health. Returns <paramref name="damage"/> unchanged when no cap
	/// applies or anything cannot be read.
	/// </summary>
	internal static int CapDamage(object receiver, int damage, out string detail)
	{
		detail = null;
		if (Homm3UnitKitRules.Rules.Count == 0 || receiver == null || damage <= 0)
			return damage;
		try
		{
			var receiverKey = Homm3DirectStateIdentity.ResolveKeyOrZero(receiver);
			if (receiverKey == 0)
				return damage;
			var rules = RulesFor(receiver, receiverKey);
			if (rules == null)
				return damage;
			foreach (var rule in rules)
			{
				if (rule.Kind != Kind.HitCap)
					continue;
				if (!TrackFullHealth(receiver, receiverKey, out _, out var full))
					return damage;
				var cap = (int)Math.Max(1L, (long)full * rule.Percent / 100L);
				if (damage <= cap)
					return damage;
				detail = rule.Name + " caps the hit at " + cap + " (" + rule.Percent + "% of " + full + " health)";
				return cap;
			}
			return damage;
		}
		catch
		{
			detail = null;
			return damage;
		}
	}

	/// <summary>
	/// The committed damage of one hit, after every rule: a hit that is at least the receiver's remaining health
	/// destroys the stack (death_toll). Call once per damaging hit, before the damage lands.
	/// </summary>
	internal static void NoteCommittedDamage(object receiver, int damage)
	{
		if (Homm3UnitKitRules.Rules.Count == 0 || receiver == null || damage <= 0)
			return;
		try
		{
			var receiverKey = Homm3DirectStateIdentity.ResolveKeyOrZero(receiver);
			if (receiverKey == 0 || !DamageKillMapping.TryReadStackHealth(receiver, out var health) || health <= 0 || damage < health)
				return;
			lock (Gate)
				FallenStacks.Add(receiverKey);
		}
		catch
		{
		}
	}

	/// <summary>
	/// Buff-add prefix (<see cref="Homm3UnitKitBuffSwapHook"/>): the SID the add should use instead, or null to leave
	/// it alone. <paramref name="buffManager"/> is the receiver's buff manager. Also records quarry marks.
	/// </summary>
	internal static string SwapAddedBuff(object buffManager, string sid, object caster, out string detail)
	{
		detail = null;
		if (sid == null || buffManager == null)
			return null;
		if (QuarryBuffs.Contains(sid))
			NoteQuarryMark(buffManager, sid, caster);
		var rotates = Homm3UnitKitRules.BuffRotations.TryGetValue(sid, out var rotation) && rotation.Length > 0;
		Homm3UnitKitRules.BuffEscalations.TryGetValue(sid, out var escalation);
		Homm3UnitKitRules.BuffChains.TryGetValue(sid, out var chain);
		var scales = Homm3UnitKitRules.BuffScales.TryGetValue(sid, out var scale);
		if (!rotates && escalation == null && chain == null && !scales)
			return null;
		var manager = buffManager is Il2CppObjectBase proxy ? proxy.Pointer : IntPtr.Zero;
		var now = DateTime.UtcNow.Ticks;
		lock (Gate)
		{
			if (manager != IntPtr.Zero && manager == _lastSwapManager && _lastSwapFrom == sid && now - _lastSwapTicks < SwapRepeatWindowTicks)
				return _lastSwapTo; // the same application through a second add method
		}
		string to = null;
		if (rotates)
		{
			var casterKey = caster == null ? 0 : Homm3DirectStateIdentity.ResolveKeyOrZero(caster);
			int index;
			lock (Gate)
			{
				RotationByCaster.TryGetValue((casterKey, sid), out index);
				RotationByCaster[(casterKey, sid)] = index + 1;
			}
			to = rotation[index % rotation.Length];
			detail = "use " + (index + 1) + " of " + sid + " grants " + to;
		}
		else if (escalation != null)
		{
			if (Homm3BuffDebuffNativeAdapter.TryQueryBuffSid(buffManager, sid, out var held, out _) && held.HasSid)
			{
				var blocked = !string.IsNullOrEmpty(escalation[1])
				              && Homm3BuffDebuffNativeAdapter.TryQueryBuffSid(buffManager, escalation[1], out var guard, out _) && guard.HasSid;
				if (!blocked)
				{
					to = escalation[0];
					detail = "repeat " + sid + " becomes " + to;
				}
			}
		}
		else if (chain != null)
		{
			if (Homm3BuffDebuffNativeAdapter.TryQueryBuffSid(buffManager, sid, out var held, out _) && held.HasSid)
			{
				to = chain[chain.Length - 1];
				for (var i = 0; i < chain.Length; i++)
				{
					if (Homm3BuffDebuffNativeAdapter.TryQueryBuffSid(buffManager, chain[i], out var link, out _) && !link.HasSid)
					{
						to = chain[i];
						break;
					}
				}
				detail = "repeat " + sid + " stacks as " + to;
			}
		}
		else if (TryCasterBasicDamage(caster, out var basic))
		{
			var value = basic * scale.Percent / 100L;
			var pick = 0;
			for (var i = 0; i < scale.Damage.Length; i++)
			{
				if (scale.Damage[i] <= value)
					pick = i;
			}
			to = scale.Sids[pick];
			detail = sid + " scales to " + to + " (" + scale.Percent + "% of " + basic + " basic damage = " + value + ")";
		}
		lock (Gate)
		{
			_lastSwapManager = manager;
			_lastSwapFrom = sid;
			_lastSwapTo = to;
			_lastSwapTicks = now;
		}
		return to;
	}

	/// <summary>The caster's basic attack damage: stack count x average of damageMin and damageMax.</summary>
	internal static bool TryCasterBasicDamage(object caster, out long damage)
	{
		damage = 0;
		if (caster == null)
			return false;
		if (!Homm3TrainingDamageLawRuntime.TryReadBattleStackCount(caster, out var count, out _) || count <= 0)
			return false;
		if (!Homm3BuffDebuffNativeAdapter.TryAdjustUnitIntStat(caster, "damageMin", 0, out var min, out _, out _)
		    || !Homm3BuffDebuffNativeAdapter.TryAdjustUnitIntStat(caster, "damageMax", 0, out var max, out _, out _))
			return false;
		damage = (long)count * (min + max) / 2;
		return damage > 0;
	}

	private static void NoteQuarryMark(object buffManager, string sid, object caster)
	{
		if (IsDisabled(Kind.Quarry))
			return;
		try
		{
			var casterKey = caster == null ? 0 : Homm3DirectStateIdentity.ResolveKeyOrZero(caster);
			if (casterKey == 0)
				return;
			var rules = RulesFor(caster, casterKey);
			if (rules == null)
				return;
			foreach (var rule in rules)
			{
				if (rule.Kind != Kind.Quarry || rule.Buff != sid)
					continue;
				if (!Homm3BuffDebuffNativeAdapter.TryQueryBuffSid(buffManager, sid, out var info, out _) || info.Receiver == null)
					return;
				var targetKey = Homm3DirectStateIdentity.ResolveKeyOrZero(info.Receiver);
				if (targetKey == 0 || targetKey == casterKey)
					return;
				lock (Gate)
					QuarryByHolder[casterKey] = targetKey;
				Homm3UnitKitBattleHooks.LogEvent(rule.Name + ": quarry set");
				return;
			}
		}
		catch (Exception ex)
		{
			DisableKind(Kind.Quarry, ex);
		}
	}

	/// <summary>Reads the stack's health and keeps the largest total seen this battle as its full health.</summary>
	private static bool TrackFullHealth(object unit, long key, out int health, out int full)
	{
		full = 0;
		if (!DamageKillMapping.TryReadStackHealth(unit, out health))
			return false;
		lock (Gate)
		{
			if (!FullHealthByHolder.TryGetValue(key, out full) || health > full)
				FullHealthByHolder[key] = full = health;
		}
		return true;
	}

	/// <summary>The unit's own rules (by unit SID) plus any it holds through a Tower Artificing graft.</summary>
	internal static IReadOnlyList<Homm3UnitKitRules.Rule> RulesFor(object unit, long key)
	{
		if (unit == null || key == 0)
			return null;
		var own = OwnRulesFor(unit, key);
		var grafted = Homm3TowerArtificingRuntime.KitRulesForCarrier(unit, key);
		if (grafted == null)
			return own;
		if (own != null)
			grafted.AddRange(own);
		return grafted;
	}

	/// <summary>The first rule of <paramref name="kind"/> the unit holds, or null.</summary>
	internal static Homm3UnitKitRules.Rule FindRule(object unit, long key, Kind kind)
	{
		if (!TableHas(kind) || IsDisabled(kind))
			return null;
		var rules = RulesFor(unit, key);
		if (rules == null)
			return null;
		foreach (var rule in rules)
		{
			if (rule.Kind == kind)
				return rule;
		}
		return null;
	}

	private static Homm3UnitKitRules.Rule[] OwnRulesFor(object unit, long key)
	{
		lock (Gate)
		{
			if (RulesByUnit.TryGetValue(key, out var cached))
				return cached;
		}
		Homm3UnitKitRules.Rule[] rules = null;
		if (Homm3BattleEventNativeAdapter.TryResolveUnitSid(unit, out var sid) && sid != null)
			Homm3UnitKitRules.Rules.TryGetValue(sid, out rules);
		else
			return null; // SID not known yet: do not cache a miss
		if (Homm3UnitKitRules.LawRules.Length > 0)
		{
			if (!TryAddLawRules(unit, sid, ref rules))
				return rules; // law owner not resolved yet: do not cache
		}
		lock (Gate)
			RulesByUnit[key] = rules;
		return rules;
	}

	/// <summary>
	/// Adds the rules faction laws switch on (law pass 2026-11-21) at the owner's law rank.
	/// False when the unit's side cannot be resolved yet (the caller then skips caching).
	/// </summary>
	private static bool TryAddLawRules(object unit, string sid, ref Homm3UnitKitRules.Rule[] rules)
	{
		object dataSide;
		try
		{
			if (!Homm3BattleUnitLawOwnerRegistry.TryResolveDataSide(unit, out dataSide) || dataSide == null)
				return false;
		}
		catch
		{
			return false;
		}
		List<Homm3UnitKitRules.Rule> added = null;
		foreach (var lawRule in Homm3UnitKitRules.LawRules)
		{
			if (lawRule.Units != null && !lawRule.Units.Contains(sid))
				continue;
			var rank = Homm3CustomFactionLawRuntime.CustomLawRank(dataSide, lawRule.LawIndex, lawRule.FactionSid);
			if (rank <= 0 || lawRule.ByLevel.Length == 0)
				continue;
			added ??= new List<Homm3UnitKitRules.Rule>();
			added.Add(lawRule.ByLevel[Math.Min(rank, lawRule.ByLevel.Length) - 1]);
		}
		if (added != null)
		{
			if (rules != null)
				added.InsertRange(0, rules);
			rules = added.ToArray();
		}
		return true;
	}

	internal static Unit AsUnit(object value)
	{
		if (value is Unit unit)
			return unit;
		if (value is not Il2CppObjectBase obj || obj.Pointer == IntPtr.Zero)
			return null;
		try
		{
			return obj.TryCast<Unit>();
		}
		catch
		{
			return null;
		}
	}

	private static HashSet<Kind> CollectKinds()
	{
		var kinds = new HashSet<Kind>();
		foreach (var rules in Homm3UnitKitRules.Rules.Values)
		{
			foreach (var rule in rules)
				kinds.Add(rule.Kind);
		}
		foreach (var lawRule in Homm3UnitKitRules.LawRules)
		{
			foreach (var rule in lawRule.ByLevel)
				kinds.Add(rule.Kind);
		}
		// Tower Artificing grafts carry kit rules onto other units.
		foreach (var rule in Homm3TowerArtificingCatalog.KitRuleBySchematic.Values)
			kinds.Add(rule.Kind);
		return kinds;
	}

	private static HashSet<string> CollectQuarryBuffs()
	{
		var buffs = new HashSet<string>(StringComparer.Ordinal);
		foreach (var rules in Homm3UnitKitRules.Rules.Values)
		{
			foreach (var rule in rules)
			{
				if (rule.Kind == Kind.Quarry && !string.IsNullOrEmpty(rule.Buff))
					buffs.Add(rule.Buff);
			}
		}
		return buffs;
	}

	private static string Append(string detail, string part) => detail == null ? part : detail + "; " + part;
