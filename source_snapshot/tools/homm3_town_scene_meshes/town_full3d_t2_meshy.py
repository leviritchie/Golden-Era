def _plate_mask(lid: str) -> np.ndarray:
    """The layer plate's own opaque non-shadow px (layer_mask's `opaque`, native px): the sprite_fill mask. Not the
    building mask: native_mask drops painting-equal px, so the snow ledge a building stands on was filled with its
    nearest wall colour and read as stepped grey slabs over the painted snow at rest (Bulwark castle foot,
    2026-09-29)."""
    a = np.asarray(SC.sprite(SC.layers()[lid])).astype(int)
    r, g, b_, al = (a[..., i] for i in range(4))
    return (al > 128) & ~((r > 120) & (b_ > 120) & (g < 0.62 * np.minimum(r, b_)))


def painted_front(sc, lid: str, b: dict) -> dict:
    """Split the baked body (town_full3d_t2_paint.painted_front): faces the rest camera sees (>= VISIBLE_MIN of their
    SUPER px owned, or centroid / any corner at the rest surface) become Mesh_Body_<lid>, textured by the painting in
    screen space (uv = their rest px in a SUPER crop of the plate), de-lit per px by the Hex/Lit irradiance of the
    smooth camera-facing normal (which the bin carries, so bake and game shade alike); every other face is
    Mesh_Body_<lid>_meshy with the Meshy atlas (colour-matched, sun-bent normals) from bake. Both two-sided.
    This lane's by-design values: faces are split when drawn at frame px (seen_super 1); the sprite_fill mask is
    _plate_mask; the painting is looked up with scipy's bilinear; fewer than 50 front faces is a failed fit; the
    remainder keeps bake's own atlas (meshy_albedo, no gain)."""
    import town_full3d_t2_paint as TP
    L = SC.layers()[lid]
    P, N, uv, F, sub = TP.subdivide_screen(sc.cam, b["P"], b["N"], b["uv"], b["F"], seen_super=1)
    res = TP.painted_front(sc, lid, L, _plate_mask(lid), P, N, F, uv, None, sampler="scipy", min_front_tris=50,
                           meshy_albedo=b["atlas"])
    st = res["rep"]
    out = {"sub": sub, "stats": {k: st[k] for k in ("frontTris", "meshyTris", "frontPxShare", "paintTex", "paintedPx",
                                                    "texelsPerPx", "delitClippedShare")},
           "front": res["front"]}
    if res["meshy"] is not None:
        out["meshy"] = res["meshy"]
    return out


def trim_pads(cam, P, F, N, uv, tgt):
    """Drop the Meshy ground pad where it leaves the sprite. Low triangles (centroid in the model's lowest PAD_FRAC of
    height) are first split 1-to-4 until their rest projection is at most PAD_SPLIT_PX per edge (a pad is a few large
    triangles whose centroids sit inside the sprite while their rims run far outside it), then every low triangle
    whose rest centroid lies inside the painted rect but outside the sprite mask (grown PAD_GROW_PX) is dropped. They
    would otherwise show a Meshy slab on the painted ground at rest and at the sweeps."""
    import cv2
    import stronghold_full3d_terrain as T
    ymin = P[:, 1].min()
    h = P[:, 1].max() - ymin
    split = 0
    for _ in range(PAD_SPLIT_ITERS):
        px, py, _ = T.project(cam, P)
        low = P[F][:, :, 1].mean(1) < ymin + PAD_FRAC * h
        q = np.stack([px, py], 1)[F]
        edge = np.linalg.norm(q - q[:, [1, 2, 0]], axis=2).max(1)
        big = low & (edge > PAD_SPLIT_PX)
        if not big.any():
            break
        split += int(big.sum())
        B = F[big]
        m = [(B[:, a], B[:, b]) for a, b in ((0, 1), (1, 2), (2, 0))]
        base = len(P)
        P = np.concatenate([P] + [(P[a] + P[b]) / 2 for a, b in m])
        Nm = [N[a] + N[b] for a, b in m]
        N = np.concatenate([N] + [n / np.maximum(np.linalg.norm(n, axis=1, keepdims=True), 1e-9) for n in Nm])
        uv = np.concatenate([uv] + [(uv[a] + uv[b]) / 2 for a, b in m])
        k = len(B)
        m01, m12, m20 = base + np.arange(k), base + k + np.arange(k), base + 2 * k + np.arange(k)
        v0, v1, v2 = B[:, 0], B[:, 1], B[:, 2]
        sub = np.concatenate([np.stack(t, 1) for t in ((v0, m01, m20), (m01, v1, m12), (m20, m12, v2),
                                                       (m01, m12, m20))])
        F = np.concatenate([F[~big], sub.astype(F.dtype)])
    px, py, _ = T.project(cam, P)
    low = P[F][:, :, 1].mean(1) < ymin + PAD_FRAC * h
    cx, cy = px[F].mean(1), py[F].mean(1)
    k = 2 * PAD_GROW_PX + 1
    dil = cv2.dilate(tgt.astype(np.uint8), np.ones((k, k), np.uint8)).astype(bool)
    inr = (cx >= 0) & (cx < SC.TW) & (cy >= 0) & (cy < SC.TH)
    out = inr & ~dil[np.clip(cy.astype(int), 0, SC.H - 1), np.clip(cx.astype(int), 0, SC.W - 1)]
    drop = low & out
    # the part of the pad buried under the painted terrain at rest: it pokes through the terrain as dark shards once
    # the camera moves (hall_3's mound, the tavern's rubble skirt)
    cam_and_ground()
    pz = T.project(cam, P)[2][F].mean(1)
    zg = _CACHE["z"][np.clip(cy.astype(int), 0, SC.H - 1), np.clip(cx.astype(int), 0, SC.W - 1)]
    buried = low & inr & (pz > zg * (1 + PAD_BURIED)) & ~drop
    drop |= buried
    # the painting frame clips the building: a sprite truncated by the painted rect must not grow a Meshy
    # continuation outside it (the framing gate holds every building inside the visible region at rest)
    offv = ~((px >= 0) & (px < SC.TW) & (py >= 0) & (py < SC.TH))
    clip = offv[F].any(1) & ~drop
    drop |= clip
    return P, F[~drop], N, uv, {"droppedTris": int(drop.sum()), "frameClipTris": int(clip.sum()), "buriedTris": int(buried.sum()),
                                "splitTris": split, "padFrac": PAD_FRAC, "growPx": PAD_GROW_PX,
                                "splitPx": PAD_SPLIT_PX}


def cloud_bin(sc, lid: str, stage_dir: Path) -> dict:
    """tbncspec: the storm cloud keeps the solid mesh's flat card (the triangles whose rest centroid lies in the flat,
    DEF-changed region), as its own bin with the solid mesh's own atlas."""
    import shutil
    import cv2
    import stronghold_full3d_buildings as BL
    import stronghold_full3d_scene as SS
    import stronghold_full3d_terrain as T
    keep = stage_dir / f"_solid_Mesh_Body_{lid}.bytes"
    if not keep.is_file():
        shutil.copy2(stage_dir / f"Mesh_Body_{lid}.bytes", keep)
        shutil.copy2(stage_dir / f"Mesh_Body_{lid}_albedo.png", stage_dir / f"_solid_Mesh_Body_{lid}_albedo.png")
    v, n, uv, subs = SS.read_bin(keep)
    Pw = sc.cpos + (v.astype(np.float64) / sc.scale) @ sc.C.T
    tris = np.concatenate(subs)
    L = SC.layers()[lid]
    flat, _ = BL.flat_region(lid, L, BL.native_mask(L), SC.FP.RELIEF_TUNE[lid])
    fm = cv2.dilate(_to_frame(flat, L).astype(np.uint8), np.ones((5, 5), np.uint8)).astype(bool)
    px, py, _ = T.project(sc.cam, Pw[tris].mean(1))
    ok = fm[np.clip(py.astype(int), 0, SC.H - 1), np.clip(px.astype(int), 0, SC.W - 1)]
    name = f"Mesh_Body_{lid}_cloud"
    SS.write_bin(stage_dir / f"{name}.bytes", v, n, uv, [tris[ok]])
    shutil.copy2(stage_dir / f"_solid_Mesh_Body_{lid}_albedo.png", stage_dir / f"{name}_albedo.png")
    return {"name": name, "row": {"name": name, "mesh": f"{SC.FP.ASSET_ROOT}/{stage_dir.name}/{name}.bytes",
                                  "texture": f"{SC.FP.ASSET_ROOT}/{stage_dir.name}/{name}_albedo.png", "kind": "lit",
                                  "maxSize": 4096},
            "tris": int(ok.sum()), "of": int(len(tris))}


def skirt_bin(sc, lid: str, stage_dir: Path, before: str, sil: np.ndarray, tgt: np.ndarray) -> dict | None:
    """The hybrid's skirt: the installed relief's triangles (candidate `before`) whose rest centroid lies on a sprite
    px the Meshy body leaves uncovered at rest (sil dilated SKIRT_GROW_PX), as their own bin with the relief's own
    atlas. At rest the painting is back on those px; at the sweeps they are relief fragments (they may smear)."""
    import shutil
    import cv2
    import stronghold_full3d_scene as SS
    import stronghold_full3d_terrain as T
    src = SC.DATA / "candidates" / before / "unity_project" / Path(SS.ASSET_ROOT) / stage_dir.name
    rb = src / f"Mesh_Body_{lid}.bytes"
    if not rb.is_file():
        raise SystemExit(f"skirt: {rb} missing (the before candidate's relief body)")
    v, n, uv, subs = SS.read_bin(rb)
    Pw = sc.cpos + (v.astype(np.float64) / sc.scale) @ sc.C.T
    tris = np.concatenate(subs)
    k = 2 * SKIRT_GROW_PX + 1
    unc = tgt & ~cv2.dilate(sil.astype(np.uint8), np.ones((k, k), np.uint8)).astype(bool)
    px, py, _ = T.project(sc.cam, Pw[tris].mean(1))
    ok = unc[np.clip(py.astype(int), 0, SC.H - 1), np.clip(px.astype(int), 0, SC.W - 1)]
    if not ok.any():
        return None
    name = f"Mesh_Body_{lid}_skirt"
    SS.write_bin(stage_dir / f"{name}.bytes", v, n, uv, [tris[ok]])
    shutil.copy2(src / f"Mesh_Body_{lid}_albedo.png", stage_dir / f"{name}_albedo.png")
    return {"name": name, "row": {"name": name, "mesh": f"{SC.FP.ASSET_ROOT}/{stage_dir.name}/{name}.bytes",
                                  "texture": f"{SC.FP.ASSET_ROOT}/{stage_dir.name}/{name}_albedo.png", "kind": "lit",
                                  "maxSize": 4096},
            "tris": int(ok.sum()), "of": int(len(tris)), "uncoveredPx": int(unc.sum())}


def stage_body(sc, lid: str, b: dict) -> dict:
    """painted_front of the baked body, staged as Mesh_Body_<lid> (painted) + Mesh_Body_<lid>_meshy (the rest)."""
    import stronghold_full3d_scene as SS
    pref = SS.PREFIX + lid
    pf = painted_front(sc, lid, b)
    fP, fN, fuv, fF, falb = pf["front"]
    sc.add_bin(pref, f"Mesh_Body_{lid}", fP, fN, fuv, fF, falb, max_size=4096)
    mesh_bin = SS.STAGE / pref / f"Mesh_Body_{lid}_meshy.bytes"
    if "meshy" in pf:
        mP, mN, muv, mF, matl = pf["meshy"]
        sc.add_bin(pref, f"Mesh_Body_{lid}_meshy", mP, mN, muv, mF, matl, max_size=ATLAS)
    elif mesh_bin.is_file():
        raise SystemExit(f"stage: {mesh_bin} is left from an earlier run and this run makes none for {lid}")
    return pf


def stage(layers: list[str], attempt: str, attempt_of: dict, before: str = "wall_v2", skirt: bool = False) -> dict:
    """Replace each layer's Mesh_Body bin in the candidate by the placed Meshy model; rows, stage report, catalog,
    offline preview and the see-through gate as the lane's own building stage does."""
    import stronghold_full3d_scene as SS
    sc = SS.Scene()
    rep = {}
    for lid in layers:
        att = attempt_of.get(lid, attempt)
        b = bake(lid, att, sc)
        pref = SS.PREFIX + lid
        if lid in SC.FP.RELIEF_TUNE and "flat" in SC.FP.RELIEF_TUNE[lid]:
            cb = cloud_bin(sc, lid, SS.STAGE / pref)     # before the solid body is overwritten
        else:
            cb = None
        pf = stage_body(sc, lid, b)
        fP, fN, fuv, fF, falb = pf["front"]
        b["stats"]["paintedFront"] = pf["stats"]
        b["stats"]["subdivide"] = pf["sub"]
        rep[lid] = {"method": "meshy_t2 painted front", "attempt": att, "kind": "building",
                    "texelsPerPx": pf["stats"]["texelsPerPx"],
                    "tris": int(len(fF) + (len(pf["meshy"][3]) if "meshy" in pf else 0)),
                    "verts": int(len(fP) + (len(pf["meshy"][0]) if "meshy" in pf else 0)),
                    "texSize": [ATLAS, ATLAS], "frontTex": pf["stats"]["paintTex"],
                    "fit": {k: (round(v, 4) if isinstance(v, float) else v) for k, v in b["fit"].items()},
                    "bake": b["stats"],
                    "meshy": {"taskId": task_id(lid, att), "credits": 0 if lid in REUSE else PRICE,
                              "reusedFrom": REUSE.get(lid),
                              "glb": (model_dir(lid, att) / "model.glb").relative_to(SC.ROOT).as_posix()}}
        if cb:
            sc.pieces.setdefault(pref, []).append(cb["row"])
            rep[lid]["cloudCard"] = {"bin": cb["name"], "tris": cb["tris"], "ofSolidTris": cb["of"]}
        sk = skirt_bin(sc, lid, SS.STAGE / pref, before, b["sil"], b["tgt"]) if skirt else None
        stale = SS.STAGE / pref / f"Mesh_Body_{lid}_skirt.bytes"
        if sk:
            sc.pieces.setdefault(pref, []).append(sk["row"])
            rep[lid]["skirt"] = {"bin": sk["name"], "tris": sk["tris"], "ofReliefTris": sk["of"],
                                 "uncoveredPx": sk["uncoveredPx"], "from": before}
        elif stale.is_file():
            raise SystemExit(f"stage: {stale} is left from an earlier run and this run makes no skirt for {lid}")
        print(lid, json.dumps(rep[lid]["bake"])[:400], flush=True)
    SS.save_rows(sc)
    rp = SS.WORK / "stage_report.json"
    old = json.loads(rp.read_text(encoding="utf-8"))
    old["buildings"].update(rep)
    old["meshyT2"] = {"faction": FACTION, "layers": sorted(set(old.get("meshyT2", {}).get("layers", [])) | set(layers)),
                      "skipped": SKIP, "ledger": LEDGER.relative_to(SC.ROOT).as_posix()}
    rp.write_text(json.dumps(old, indent=1), encoding="utf-8")
    wf = SS.WORK / "closing_walls.npz"
    if wf.is_file():
        edges = dict(np.load(wf))
        for lid in layers:
            edges.pop(lid, None)     # a Meshy body has no closing walls
