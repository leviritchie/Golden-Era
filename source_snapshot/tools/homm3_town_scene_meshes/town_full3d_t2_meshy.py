def cam_and_ground():
    """The rest camera (painting world) and a frame camera-depth map of the painted terrain (sky / extension filled
    from the nearest painted ground), for fit_mesh_to_sprite's contact point."""
    if "cam" not in _CACHE:
        from scipy.ndimage import distance_transform_edt
        import stronghold_full3d_terrain as T
        cam = T.camera()
        rd = T.rect_depth(cam)
        z = np.full((SC.H, SC.W), np.nan)
        z[:SC.TH, :SC.TW] = rd["zc"]
        ok = np.isfinite(z)
        _, (iy, ix) = distance_transform_edt(~ok, return_indices=True)
        _CACHE.update(cam=cam, z=z[iy, ix], rd=rd)
    return _CACHE["cam"], _CACHE["z"]


def frame_mask(lid: str) -> np.ndarray:
    """The layer mask in the 1920x1080 frame (x1.8, top-left registration)."""
    import cv2
    L = SC.layers()[lid]
    _, m, _ = layer_mask(lid)
    return _to_frame(m, L)


def _to_frame(m: np.ndarray, L: dict) -> np.ndarray:
    import cv2
    big = cv2.resize(m.astype(np.float32), (round(m.shape[1] * SC.SCALE), round(m.shape[0] * SC.SCALE)),
                     interpolation=cv2.INTER_LINEAR) > 0.5
    out = np.zeros((SC.H, SC.W), bool)
    x0, y0 = round(L["x"] * SC.SCALE), round(L["y"] * SC.SCALE)
    sx, sy = max(0, -x0), max(0, -y0)
    h, w = big.shape
    out[y0 + sy:min(SC.H, y0 + h), x0 + sx:min(SC.W, x0 + w)] = big[sy:min(h, SC.H - y0), sx:min(w, SC.W - x0)]
    return out


def load_glb(path: Path):
    """Meshy glb as Unity-frame arrays (x negated as glTFast does): v, f, vertex normals, uv (v up), texture RGB."""
    import trimesh
    sc_ = trimesh.load(str(path), force="scene")
    if len(sc_.geometry) != 1:
        raise SystemExit(f"{path}: {len(sc_.geometry)} geometries (expected Meshy's single mesh)")
    g = list(sc_.geometry.values())[0].copy()
    g.apply_transform(sc_.graph.get(sc_.graph.nodes_geometry[0])[0])
    v = np.asarray(g.vertices, np.float64).copy()
    n = np.asarray(g.vertex_normals, np.float64).copy()
    v[:, 0] *= -1
    n[:, 0] *= -1
    uv = np.asarray(g.visual.uv, np.float64)
    tex = np.asarray(g.visual.material.baseColorTexture.convert("RGB"))
    return v, np.asarray(g.faces, np.int64), n, uv, tex


def rect_fitter(*a, **k):
    """fit_mesh_to_sprite.Fitter scored inside the painted rect only: a sprite the painting's frame cuts (x = 0,
    y = 0, the bottom row) has no pixels past the cut, so the model may continue past it instead of shrinking."""
    import fit_mesh_to_sprite as FM

    class _F(FM.Fitter):
        def silhouette(self, w, full=False):
            s = super().silhouette(w, full)
            valid = np.zeros(self.target.shape, bool)
            valid[:SC.TH // self.down, :SC.TW // self.down] = True
            if not full:
                valid = valid[self.win[1]:self.win[3], self.win[0]:self.win[2]]
            return s & valid
    return _F(*a, **k)


def facing_yaw(cam) -> float:
    """The yaw (fit_mesh_to_sprite convention) that turns the model's +Z front toward the rest camera."""
    import fit_mesh_to_sprite as FM
    back = -np.asarray(cam["fwd"], np.float64)
    back[1] = 0
    back /= np.linalg.norm(back)
    yaws = np.arange(0, 360, 0.5)
    return float(yaws[int(np.argmax([(FM.yaw_matrix(y) @ [0.0, 0.0, 1.0]) @ back for y in yaws]))])


def fit_one(lid: str, attempt: str) -> dict:
    cam, z = cam_and_ground()
    d = fit_dir(lid, attempt)
    v, f, _, _, _ = load_glb(model_dir(lid, attempt) / "model.glb")
    tgt = frame_mask(lid)
    if lid in TRIM:
        L = SC.layers()[lid]
        keep = np.zeros(tgt.shape, bool)
        x0, y0, x1, y1 = TRIM[lid]
        keep[round((L["y"] + y0) * SC.SCALE):round((L["y"] + y1) * SC.SCALE),
             round((L["x"] + x0) * SC.SCALE):round((L["x"] + x1) * SC.SCALE)] = True
        tgt = tgt & keep
    F = rect_fitter(cam, z, (SC.W, SC.H), tgt, v, f, down=2)
    ys, xs = np.nonzero(tgt)
    if YAW_WINDOW is None:
        base = F.fit((xs.min(), ys.min(), xs.max(), ys.max()))
    else:
        y0 = facing_yaw(cam)
        base = F.fit((xs.min(), ys.min(), xs.max(), ys.max()),
                     yaws=[(y0 + dy) % 360 for dy in range(-YAW_WINDOW, YAW_WINDOW + 1, 7)])
    st = F.refine_stretch(base, lo=0.8, hi=1.25, top_weight=0.5)
    best = st if st["iou"] > base["iou"] + 0.005 else base
    sil = best["silhouette"]
    for r in (base, st):
        r.pop("silhouette", None)
    t2 = tgt[::2, ::2]
    viz = np.zeros(t2.shape + (3,), np.uint8)
    viz[t2 & sil] = (200, 200, 200)
    viz[t2 & ~sil] = (0, 200, 0)     # sprite px the model misses
    viz[~t2 & sil] = (220, 0, 0)     # model px outside the sprite
    ys2, xs2 = np.nonzero(t2 | sil)
    Image.fromarray(viz[max(0, ys2.min() - 10):ys2.max() + 10, max(0, xs2.min() - 10):xs2.max() + 10]).save(
        d / "fit_viz.png")
    out = {"layer": lid, "attempt": attempt, "chosen": "stretch" if best is st else "base", "fit": best,
           "base": {k: base[k] for k in ("iou", "precision", "recall", "yaw")},
           "stretch": {k: st[k] for k in ("iou", "precision", "recall", "stretchY")},
           "method": "fit_mesh_to_sprite.Fitter (F0.5 silhouette, yaw " + ("0-345/15" if YAW_WINDOW is None else
                     f"camera-facing +-{YAW_WINDOW}/7") + " + refine, contact on the painted ground depth) scored "
                     "inside the painted rect; refine_stretch 0.8-1.25 kept if IoU +0.005"}
    (d / "fit.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    return {"layer": lid, "iou": round(best["iou"], 3), "precision": round(best["precision"], 3),
            "recall": round(best["recall"], 3), "yaw": best["yaw"], "stretchY": round(best["stretchY"], 3)}


