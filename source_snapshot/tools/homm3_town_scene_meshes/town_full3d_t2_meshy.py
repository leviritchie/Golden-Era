def revert(layers: list[str], before: str, reasons: dict) -> None:
    """Put a genuinely broken Meshy layer (fragments, flat slab, main feature missing - judged by eye at the sweeps,
    user rule 2026-09-29) back to the `before` candidate's relief: its prefab's staged files and rows are copied from
    `before`, its _meshy bin is dropped, its stage-report entry and closing walls come back, and the reason is recorded.
    Then catalog, preview and the see-through gate run as in stage."""
    import shutil
    import stronghold_full3d_scene as SS
    bstage = SC.DATA / "candidates" / before / "unity_project" / Path(SS.ASSET_ROOT)
    bwork = SC.DATA / "candidates" / before / "work"
    rows = json.loads(SS.ROWS.read_text(encoding="utf-8"))
    brows = json.loads((bstage / "rows.json").read_text(encoding="utf-8"))
    rp = SS.WORK / "stage_report.json"
    rep = json.loads(rp.read_text(encoding="utf-8"))
    brep = json.loads((bwork / "stage_report.json").read_text(encoding="utf-8"))
    bw = bwork / "closing_walls.npz"
    wf = SS.WORK / "closing_walls.npz"
    edges = dict(np.load(wf)) if wf.is_file() else {}
    bedges = dict(np.load(bw)) if bw.is_file() else {}
    for lid in layers:
        if not reasons.get(lid):
            raise SystemExit(f"revert: {lid} needs a reason (--reason {lid}=...)")
        pref = SS.PREFIX + lid
        src, dst = bstage / pref, SS.STAGE / pref
        if pref not in brows or not src.is_dir():
            raise SystemExit(f"revert: {before} has no staged prefab {pref}")
        for f in dst.glob(f"Mesh_Body_{lid}_meshy*"):
            f.unlink()
        for f in src.iterdir():
            if f.is_file():
                shutil.copy2(f, dst / f.name)
        rows[pref] = brows[pref]
        rep["buildings"][lid] = brep["buildings"].get(lid, {"method": f"relief ({before})"})
        rep["buildings"][lid]["revertedFromMeshy"] = reasons[lid]
        if lid in bedges:
            edges[lid] = bedges[lid]
    SS.ROWS.write_text(json.dumps(rows, indent=1), encoding="utf-8")
    if edges:
        np.savez(wf, **edges)
    m = rep.setdefault("meshyT2", {})
    m["layers"] = sorted(set(m.get("layers", [])) - set(layers))
    m.setdefault("reverted", {}).update({l: reasons[l] for l in layers})
    rp.write_text(json.dumps(rep, indent=1), encoding="utf-8")
    sc = SS.Scene()
    SS.write_catalog(sc, carry="previous")
    SS.load_staged_preview(sc)
    print(SS.preview(sc, SS.WORK / "preview", {"default": sc.cam, **SS.pan_cams(sc)}))
    st = SS.see_through_report(sc)
    (SS.WORK / "see_through.json").write_text(json.dumps(st, indent=1), encoding="utf-8")
    rep = json.loads(rp.read_text(encoding="utf-8"))
    rep["seeThrough"] = {k: st[k] for k in ("metric", "totalPx", "mode", "baseline", "worse")}
    rp.write_text(json.dumps(rep, indent=1), encoding="utf-8")
    print(json.dumps({"seeThrough": rep["seeThrough"]}))
    SS.cull_gate_or_exit(st)


