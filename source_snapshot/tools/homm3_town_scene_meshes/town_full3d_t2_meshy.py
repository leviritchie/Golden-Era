def _gl_uv_raster(uv, attrs, size):
    """Rasterise the mesh (unindexed triangle list) in UV space: per texel the interpolated attrs and coverage."""
    import moderngl
    ctx = moderngl.create_standalone_context()
    try:
        vs = ("#version 330\nin vec2 in_uv; in vec4 in_a; out vec4 v_a;\n"
              "void main(){ gl_Position = vec4(in_uv * 2.0 - 1.0, 0.0, 1.0); v_a = in_a; }")
        fs = "#version 330\nin vec4 v_a; out vec4 o; void main(){ o = v_a; }"
        prog = ctx.program(vertex_shader=vs, fragment_shader=fs)
        outs = []
        for c0 in range(0, attrs.shape[1], 3):
            a4 = np.ones((len(uv), 4), np.float32)
            chunk = attrs[:, c0:c0 + 3].astype(np.float32)
            a4[:, :chunk.shape[1]] = chunk
            vb = np.concatenate([uv.astype(np.float32), a4], 1)
            vao = ctx.vertex_array(prog, [(ctx.buffer(vb.tobytes()), "2f 4f", "in_uv", "in_a")])
            fbo = ctx.framebuffer(color_attachments=[ctx.texture((size, size), 4, dtype="f4")])
            fbo.use()
            ctx.clear(0, 0, 0, 0)
            vao.render()
            outs.append(np.frombuffer(fbo.read(components=4, dtype="f4"), np.float32).reshape(size, size, 4)[::-1])
        cov = outs[0][..., 3] > 0.5
        return np.concatenate([o[..., :3] for o in outs], -1)[..., :attrs.shape[1]], cov
    finally:
        ctx.release()


def _rest_depth(cam, P, F):
    """Camera depth (zc) of the nearest surface per frame pixel at the rest pose (no culling); inf where empty."""
    import moderngl
    import stronghold_full3d_preview as PV
    ctx = moderngl.create_standalone_context()
    try:
        vs = ("#version 330\nuniform mat4 mvp; uniform vec3 cp; uniform vec3 cf; in vec3 in_pos; out float zc;\n"
              "void main(){ gl_Position = mvp * vec4(in_pos, 1.0); zc = dot(in_pos - cp, cf); }")
        fs = "#version 330\nin float zc; out vec4 o; void main(){ o = vec4(zc, 0, 0, 1); }"
        prog = ctx.program(vertex_shader=vs, fragment_shader=fs)
        mvp = PV.perspective(cam["fov"], SC.W / SC.H, 1.0, 5000.0) @ PV.view(cam["pos"], cam["fwd"], cam["up"],
                                                                                cam["right"])
        prog["mvp"].write(mvp.T.astype(np.float32).tobytes())
        prog["cp"].value = tuple(float(x) for x in cam["pos"])
        prog["cf"].value = tuple(float(x) for x in cam["fwd"])
        vao = ctx.vertex_array(prog, [(ctx.buffer(np.asarray(P, np.float32).tobytes()), "3f", "in_pos")],
                               ctx.buffer(np.asarray(F, np.int32).tobytes()))
        fbo = ctx.framebuffer(color_attachments=[ctx.texture((SC.W, SC.H), 4, dtype="f4")],
                              depth_attachment=ctx.depth_texture((SC.W, SC.H)))
        fbo.use()
        ctx.clear(0, 0, 0, 0, depth=1.0)
        ctx.enable(moderngl.DEPTH_TEST)
        vao.render()
        img = np.frombuffer(fbo.read(components=4, dtype="f4"), np.float32).reshape(SC.H, SC.W, 4)[::-1]
        return np.where(img[..., 3] > 0.5, img[..., 0], np.inf)
    finally:
        ctx.release()


def placed(lid: str, attempt: str):
    """The fitted model in the painting world: P, F (wound outward, the lane's sgn = 1), N, uv, Meshy texture."""
    import fit_mesh_to_sprite as FM
    import stronghold_full3d_buildings as BL
    fit = json.loads((fit_dir(lid, attempt) / "fit.json").read_text(encoding="utf-8"))["fit"]
    v, f, n, uv, tex = load_glb(model_dir(lid, attempt) / "model.glb")
    lo, hi = v.min(0), v.max(0)
    v0 = v - np.array([(lo[0] + hi[0]) / 2, lo[1], (lo[2] + hi[2]) / 2])
    k = fit["stretchY"]
    R = FM.yaw_matrix(fit["yaw"])
    P = ((v0 * np.array([1.0, k, 1.0])) @ R.T) * fit["scale"] + np.asarray(fit["position"])
    N = (n * np.array([1.0, 1.0 / k, 1.0])) @ R.T
    N /= np.linalg.norm(N, axis=1, keepdims=True) + 1e-12
    F = BL.orient(P, f, N[f].mean(1), 1.0)
    return P, F.astype(np.int32), N, uv, tex, fit


def bake(lid: str, attempt: str, sc) -> dict:
    """The atlas (linear albedo, Meshy UVs): rest-visible faces take the sprite's own texels by rest-camera
    projection, de-lit by the Hex/Lit irradiance of the mesh normal; faces hidden at rest take the Meshy texture,
    colour-matched (per channel mean / std, linear) to the de-lit sprite on the texels where both exist."""
    import cv2
    from scipy.ndimage import distance_transform_edt
    import conflux_full3d_env as E
    import stronghold_full3d_terrain as T
    import stronghold_full3d_ground as G
    import stronghold_full3d_buildings as BL
    cam = sc.cam
    P, F, N, uv, tex, fit = placed(lid, attempt)
    tgt_full = frame_mask(lid)
    P, F, N, uv, trim = trim_pads(cam, P, F, N, uv, tgt_full)
    zbuf = _rest_depth(cam, P, F)
    zb = np.where(np.isfinite(zbuf), zbuf, 0).astype(np.float32)
    # a 3x3 max of the depth buffer guards the test against a point landing a pixel off its own triangle's raster
    zmax = cv2.dilate(zb, np.ones((3, 3), np.uint8))
    sf = SC.sprite_frame(SC.layers()[lid]).astype(np.float32) / 255
    from scipy.ndimage import map_coordinates

    def sample(px, py):
        return np.stack([map_coordinates(sf[..., c], [py - 0.5, px - 0.5], order=1, mode="nearest")
                         for c in range(3)], -1)

    def visible(Q):
        px, py, zc = T.project(cam, Q)
        ix, iy = np.clip(np.floor(px).astype(int), 0, SC.W - 1), np.clip(np.floor(py).astype(int), 0, SC.H - 1)
        inside = (px >= 0) & (px < SC.W) & (py >= 0) & (py < SC.H)
        return px, py, ix, iy, inside & (zc <= zmax[iy, ix] * (1 + VIS_TOL)), inside
    # Shading-normal bend (the relief lane's NORMAL_VIEW_LEAN, here toward the key light): the rig's sun is strong and
    # its ambient near zero, so a true normal facing away from the sun cannot reproduce the painted texel under any
    # albedo <= 1. A rest-visible vertex whose painting colour needs more light takes the smallest bend in BEND_LADDER
    # toward the sun that makes it reachable (albedo <= ALB_MAX); hidden vertices keep the model's own normals.
    pxv, pyv, ixv, iyv, visv, _ = visible(P)
    # Meshy's normals point inward on some parts (the tavern's right block): a rest-visible vertex whose normal faces
    # away from the camera is flipped and its triangles rewound by the new normals, so the face the rest camera sees
    # is the front face under Unity's Cull Back, takes the painting, and is bent toward the sun on its seen side (its
    # two-sided twin would otherwise show the painting lit by a normal bent away from the sun: black).
    vdv = cam["pos"] - P
    vdv /= np.linalg.norm(vdv, axis=1, keepdims=True)
    _, _, zcv = T.project(cam, P)
    strict = visv & (zcv <= zb[iyv, ixv] * (1 + VIS_TOL))     # own pixel, no 3x3 guard: not a far-side silhouette vertex
    inward = strict & ((N * vdv).sum(-1) < -INWARD_DOT)
    N = np.where(inward[:, None], -N, N)
    F = BL.orient(P, F, N[F].mean(1), 1.0)
    dil = cv2.dilate(tgt_full.astype(np.uint8), np.ones((5, 5), np.uint8)).astype(bool)
    visv &= dil[iyv, ixv]
    need = G.SC_srgb_to_lin(sample(pxv, pyv))
    to_sun = -np.asarray(sc.sun, np.float64)
    N2, bend = N.copy(), np.zeros(len(P))
    # a hidden vertex only needs the irradiance floor HIDDEN_FLOOR (the rig's horizontal ambient is ~0.01: a wall
    # facing away from the sun renders black under the pans otherwise)

    def short(Nq):
        Lq = E.light(Nq.astype(np.float32), sc.rig, sc.sun)
        return np.where(visv, ~(need <= ALB_MAX * Lq).all(-1), Lq.mean(-1) < HIDDEN_FLOOR)
    todo = short(N2)
    for bb in BEND_LADDER:
        if not todo.any():
            break
        nb = N[todo] + bb * to_sun
        N2[todo] = nb / np.linalg.norm(nb, axis=1, keepdims=True)
        bend[todo] = bb
        todo &= short(N2)
    attrs, cov = _gl_uv_raster(uv[F].reshape(-1, 2), np.concatenate([P[F].reshape(-1, 3), N2[F].reshape(-1, 3),
                                                                      N[F].reshape(-1, 3)], 1), ATLAS)
    Pt, Nt, Ng = (attrs[..., k:k + 3].astype(np.float64)[cov] for k in (0, 3, 6))
    Nt /= np.linalg.norm(Nt, axis=-1, keepdims=True) + 1e-12
    Ng /= np.linalg.norm(Ng, axis=-1, keepdims=True) + 1e-12
    px, py, ix, iy, vis, inside = visible(Pt)
    vdir = cam["pos"] - Pt
    vdir /= np.linalg.norm(vdir, axis=-1, keepdims=True)
    dotv = (Ng * vdir).sum(-1)
    wf = T.smoothstep(FACE_LO, FACE_HI, dotv)       # facing by the model's own normal
    # the Meshy ground pad under a sprite that paints its own ground (tbncblak's stained earth) is a flat decal seen at
    # a grazing angle: it takes the painting wherever it faces the camera at all, not the dark Meshy pad texture
    lowt = Pt[:, 1] < P[:, 1].min() + PAD_FRAC * (P[:, 1].max() - P[:, 1].min())
    wf = np.where(lowt & (dotv > 0.0), 1.0, wf)
    tgt = cv2.erode(tgt_full.astype(np.uint8), np.ones((3, 3), np.uint8)).astype(bool)
    w = (vis * wf * (tgt[iy, ix] & inside)).astype(np.float32)
    rgb = sample(px, py)
    Lr = E.light(Nt.astype(np.float32), sc.rig, sc.sun)
    raw = G.SC_srgb_to_lin(rgb) / np.maximum(Lr, 0.03)
    proj = np.clip(raw, 0, 1)
    mt = G.SC_srgb_to_lin(cv2.resize(tex, (ATLAS, ATLAS), interpolation=cv2.INTER_AREA).astype(np.float32) / 255)[cov]
    sel = w > 0.9
    if sel.sum() < 200:
        raise SystemExit(f"{lid}: only {int(sel.sum())} texels take the painting at rest (fit or projection failed)")
    # colour match of the Meshy texture to the de-lit painting on the texels where both exist: per channel, in log
    # space (mean and a clamped spread ratio)
    lp, lm = np.log(proj[sel] + 1e-3), np.log(mt[sel] + 1e-3)
    mp, mm = lp.mean(0), lm.mean(0)
    a = np.clip(lp.std(0) / np.maximum(lm.std(0), 1e-4), 0.6, 1.6)
    hidden = np.clip(np.exp((np.log(mt + 1e-3) - mm) * a + mp) - 1e-3, 0, 1)
    # the rig's light is strongly tinted off the sun side (blue sky ambient + blue fill): the Meshy texels are
    # white-balanced against their own irradiance so a shaded wall reads as grey stone, not lavender
    tint = np.clip(Lr.mean(-1, keepdims=True) / np.maximum(Lr, 1e-3), TINT_CLAMP[0], TINT_CLAMP[1])
    hidden = np.clip(hidden * tint, 0, 1)
    atlas = np.zeros((ATLAS, ATLAS, 3), np.float32)
    atlas[cov] = w[:, None] * proj + (1 - w[:, None]) * hidden
    _, (jy, jx) = distance_transform_edt(~cov, return_indices=True)   # pad the UV islands (bilinear / mip bleed)
    atlas = atlas[jy, jx]
    npx = len(np.unique(iy[sel] * SC.W + ix[sel]))
    # rest silhouette of the trimmed model against the sprite mask (frame px, inside the painted rect)
    sil = np.isfinite(zbuf)
    rect = np.zeros_like(sil)
    rect[:SC.TH, :SC.TW] = True
    inter = (sil & tgt_full & rect).sum()
    stats = {"coveredTexels": int(cov.sum()), "paintingTexels": int(sel.sum()),
             "blendTexels": int(((w > 0.02) & (w <= 0.9)).sum()), "meshyTexels": int((w <= 0.02).sum()),
             "paintedPxCovered": npx, "texelsPerPx": round(float(np.sqrt(sel.sum() / max(npx, 1))), 2),
             "restSilhouette": {"iou": round(float(inter / max(((sil | tgt_full) & rect).sum(), 1)), 4),
                                "spritePxCovered": round(float(inter / max((tgt_full & rect).sum(), 1)), 4),
                                "modelPxInSprite": round(float(inter / max((sil & rect).sum(), 1)), 4)},
             "normalBend": {"visibleVerts": int(visv.sum()), "inwardFlipped": int(inward.sum()), "bent": int((bend > 0).sum()),
                            "unreachable": int(todo.sum()), "hiddenFloor": HIDDEN_FLOOR, "ladder": list(BEND_LADDER)},
             "padTrim": trim,
             "colourMatch": {"space": "log", "gain": [round(float(x), 3) for x in a],
                             "meshyLogMean": [round(float(x), 3) for x in mm], "paintingLogMean": [round(float(x), 3) for x in mp]},
             "delitClippedShare": round(float((raw > 1).any(-1)[sel].mean()), 4)}
    # drop the vertices no triangle uses any more (the trimmed pads): the framing gate bounds a building by its bin's
    # vertices, referenced or not
    used = np.zeros(len(P), bool)
    used[F.ravel()] = True
    remap = np.cumsum(used) - 1
    stats["orphanVertsDropped"] = int((~used).sum())
    P, F, N2, uv = P[used], remap[F].astype(F.dtype), N2[used], uv[used].astype(np.float32)
    return {"P": P, "F": F, "N": N2, "uv": uv, "atlas": atlas, "fit": fit, "stats": stats, "sil": sil,
            "tgt": tgt_full}


