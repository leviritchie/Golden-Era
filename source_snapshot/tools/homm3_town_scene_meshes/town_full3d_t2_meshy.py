def layer_mask(lid: str):
    """(native-px sprite RGBA, building mask, note): the mask the Meshy input, the fit target and the projection use."""
    import cv2
    import stronghold_full3d_buildings as BL
    L = SC.layers()[lid]
    spr = np.asarray(SC.sprite(L)).copy()
    m = BL.native_mask(L)
    # native_mask drops painting-equal px, which leaves the ground skirts speckled; the Meshy input gets the mask
    # closed (5 px) and median-smoothed, inside the sprite's own opaque non-shadow alpha
    r, g, b, a_ = (spr[..., i].astype(int) for i in range(4))
    opaque = (a_ > 128) & ~((r > 120) & (b > 120) & (g < 0.62 * np.minimum(r, b)))
    m = cv2.morphologyEx(m.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))
    m = (cv2.medianBlur(m * 255, 3) > 0) & opaque
    note = "native_mask closed 5 px + median 3, inside the opaque non-shadow alpha"
    if lid in SC.FP.RELIEF_TUNE and "flat" in SC.FP.RELIEF_TUNE[lid]:
        flat, _ = BL.flat_region(lid, L, BL.native_mask(L), SC.FP.RELIEF_TUNE[lid])
        m = m & ~flat
        n, lab, st, _ = cv2.connectedComponentsWithStats(m.astype(np.uint8), connectivity=8)
        big = 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))
        m = lab == big
        note += " minus the flat (DEF-changed) cloud; largest component"
    return spr, m, note


def prep_one(lid: str) -> dict:
    spr, m, note = layer_mask(lid)
    ys, xs = np.nonzero(m)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    rgba = spr[y0:y1, x0:x1].copy()
    rgba[..., 3] = np.where(m[y0:y1, x0:x1], 255, 0)
    img = Image.fromarray(rgba, "RGBA")
    k = 900 / max(img.size)
    img = img.resize((max(1, round(img.width * k)), max(1, round(img.height * k))), Image.LANCZOS)
    can = Image.new("RGBA", (1024, 1024), (255, 255, 255, 255))
    can.alpha_composite(img, ((1024 - img.width) // 2, (1024 - img.height) // 2))
    d = OUTD / lid
    d.mkdir(parents=True, exist_ok=True)
    can.convert("RGB").save(d / "input.png")
    return {"layer": lid, "bbox": [int(x0), int(y0), int(x1), int(y1)], "scale": round(k, 3), "mask": note}


def ledger_spent() -> int:
    tot = 0
    for line in LEDGER.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            if r.get("faction") == FACTION and r.get("kind") != "claim":
                tot += int(r.get("credits", 0))
    return tot


def cap() -> int:
    return int(json.loads(BUDGET.read_text(encoding="utf-8"))["townCaps"][FACTION])


def generate_one(lid: str, attempt: str, lock, purpose: str) -> dict:
    if FAC != "necropolis":
        raise SystemExit(f"generate: {FAC}'s models were generated by its own script; this tool does not bill them")
    import meshy_client as MC
    key = MC.load_api_key(SC.ROOT / ".env")
    d = OUTD / lid / attempt
    if (d / "model.glb").is_file():
        return {"layer": lid, "skipped": "model.glb exists"}
    d.mkdir(parents=True, exist_ok=True)
    with lock:
        spent = ledger_spent()
        if spent + PRICE > cap():
            return {"layer": lid, "refused": f"cap: spent {spent} + {PRICE} > {cap()}"}
        tid = MC.create_image_to_3d(key, image_path=OUTD / lid / "input.png", should_texture=True,
                                    target_polycount=8000, model_type="smart-topology", ai_model="meshy-t2")
        row = {"ts": datetime.datetime.now().isoformat(timespec="seconds"), "faction": FACTION, "layer": lid,
               "kind": "image-to-3d meshy-t2 textured", "credits": PRICE, "taskId": tid, "purpose": purpose}
        with open(LEDGER, "a", encoding="utf-8") as f:
            f.write(json.dumps(row) + "\n")
    (d / "task.json").write_text(json.dumps({"taskId": tid, "created": row["ts"]}), encoding="utf-8")
    t = MC.poll_task(key, "image-to-3d", tid, timeout_s=1800, interval_s=15)
    (d / "task.json").write_text(json.dumps({"taskId": tid, "created": row["ts"], "status": t.get("status"),
                                             "result": {k: t.get(k) for k in ("model_urls", "thumbnail_url")}},
                                            indent=1), encoding="utf-8")
    if t.get("status") != "SUCCEEDED":
        return {"layer": lid, "taskId": tid, "failed": MC.task_error_message(t)}
    MC.download_url(t["model_urls"]["glb"], d / "model.glb")
    if t.get("thumbnail_url"):
        MC.download_url(t["thumbnail_url"], d / "thumb.png")
    return {"layer": lid, "taskId": tid, "ok": True}


