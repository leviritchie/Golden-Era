def _load_stage(sc, stage_dir: Path, prefabs: set) -> list:
    import stronghold_full3d_scene as SS
    rows = json.loads((stage_dir / "rows.json").read_text(encoding="utf-8"))
    out = []
    for pref in sorted(prefabs):
        for b in rows.get(pref, {}).get("bins", []):
            mb = stage_dir / pref / f"{b['name']}.bytes"
            tex = stage_dir / pref / f"{b['name']}_albedo.png"
            if not tex.is_file() or b["name"].startswith("Sky_Drift"):
                continue
            v, n, uv, subs = SS.read_bin(mb)
            P = sc.cpos + (v.astype(np.float64) / sc.scale) @ sc.C.T
            out.append((f"{pref}/{b['name']}", P.astype(np.float32), (n.astype(np.float64) @ sc.C.T).astype(np.float32),
                        uv, np.concatenate(subs), np.asarray(Image.open(tex)), b["name"].startswith("Sky_")))
    return out


def sheet(layers: list[str], before: str, after: str) -> list[str]:
    """Per-building zooms (offline moderngl preview, the lane's Hex/Lit model): painting | before | after at rest and
    before | after at sweep_left / sweep_right / sweep_high. Environment + that one layer per tile."""
    from PIL import ImageDraw
    import stronghold_full3d_scene as SS
    import stronghold_full3d_preview as PV
    import stronghold_full3d_terrain as T
    sc = SS.Scene()
    cams = {"default": sc.cam, **{k: v for k, v in SS.pan_cams(sc).items() if k in POSES}}
    cand = SC.DATA / "candidates"
    sub = Path(SS.ASSET_ROOT)
    prefs = {SS.ENV_KEY} | {SS.PREFIX + l for l in layers}
    # one standalone GL context at a time (a second one becomes current on Windows and the first renderer's draws
    # land in it): every tile of one stage is rendered before the next stage's renderer is made
    geo: dict = {}
    shots: dict = {}
    for tag, cname in (("before", before), ("after", after)):
        R = PV.Renderer(sc.rig, sc.sun, SC.W, SC.H)
        for name, P, n, uv, tris, img, unlit in _load_stage(sc, cand / cname / "unity_project" / sub, prefs):
            R.add(name, P, n, uv, tris, img, unlit=unlit)
            pref = name.split("/")[0]
            if pref != SS.ENV_KEY and "Fx_" not in name:
                geo.setdefault(pref, []).append(P)
        for lid in layers:
            for pose in POSES:
                shots[(tag, lid, pose)] = R.render(cams[pose], near=2.0, far=T.DOME_R * 1.2,
                                                   only=[SS.ENV_KEY + "/", SS.PREFIX + lid + "/"])
        R.ctx.release()
    # rest dE76 (CIELAB, offline Hex/Lit preview) of each stage against the painting inside the sprite mask: the
    # per-layer rest-fidelity measure that decides which layers ship the Meshy body and which keep the relief
    def lab(a):
        return cv2.cvtColor(np.asarray(a, np.float32) / 255, cv2.COLOR_RGB2LAB)
    import cv2
    rest_de = {}
    for lid in layers:
        m = frame_mask(lid)
        m[SC.TH:, :] = False
        m[:, SC.TW:] = False
        ref = lab(np.asarray(SS.homm3_reference([lid])))
        rest_de[lid] = {tag: round(float(np.linalg.norm(lab(shots[(tag, lid, "default")]) - ref, axis=-1)[m].mean()), 2)
                        for tag in ("before", "after")}
        rest_de[lid]["px"] = int(m.sum())
    old_de = {}
    if (OUTD / "rest_de.json").is_file():
        old_de = json.loads((OUTD / "rest_de.json").read_text(encoding="utf-8"))
    old_de.update(rest_de)
    (OUTD / "rest_de.json").write_text(json.dumps(old_de, indent=1), encoding="utf-8")
    print(json.dumps(rest_de), flush=True)
    TWt, THt = 300, 225
    rows_img = []
    for lid in layers:
        pref = SS.PREFIX + lid
        Pall = np.concatenate(geo[pref])
        ref = np.asarray(SS.homm3_reference([lid]))
        tiles = []
        for pose in POSES:
            cam = cams[pose]
            px, py, zc = T.project(cam, Pall)
            ok = zc > 0
            x0, x1 = np.percentile(px[ok], [0.5, 99.5])
            y0, y1 = np.percentile(py[ok], [0.5, 99.5])
            cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
            half_w = max((x1 - x0) * 0.65, (y1 - y0) * 0.65 * TWt / THt, 60)
            half_h = half_w * THt / TWt
            box = (int(cx - half_w), int(cy - half_h), int(cx + half_w), int(cy + half_h))
            srcs = ([("painting", ref)] if pose == "default" else []) + [
                (tag, shots[(tag, lid, pose)]) for tag in ("before", "after")]
            for tag, img in srcs:
                t = Image.fromarray(img).crop(box).resize((TWt, THt), Image.LANCZOS)
                ImageDraw.Draw(t).text((4, 4), f"{lid} {pose} {tag}", fill=(255, 255, 0))
                tiles.append(t)
        row = Image.new("RGB", (TWt * len(tiles), THt), "black")
        for i, t in enumerate(tiles):
            row.paste(t, (i * TWt, 0))
        rows_img.append(row)
        print("sheet row", lid, flush=True)
    REVIEW_DIR.mkdir(parents=True, exist_ok=True)
    paths = []
    per = 10
    for k in range(0, len(rows_img), per):
        chunk = rows_img[k:k + per]
        s = Image.new("RGB", (chunk[0].width, THt * len(chunk)), "black")
        for i, r in enumerate(chunk):
            s.paste(r, (0, i * THt))
        p = REVIEW_DIR / f"{FACTION}_t2_buildings_zoom_{k // per + 1}.png"
        s.save(p)
        paths.append(str(p))
    return paths


