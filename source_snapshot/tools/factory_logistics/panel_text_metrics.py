"""Generate Homm3PanelTextMetrics.cs: glyph advances of the game's EN-Regular / EN-Medium / EN-Book TMP fonts.

The mod's panels lay text out in fixed boxes. TMP's own measuring (GetPreferredValues) is not proven to work through the
live interop, so row heights and single-line fits are computed from these tables instead. The advances come from the SDF
font export the mockup tools already use (tools/tower_artificing/picker_mockup.py -> <assets>/EN-*.json); they match the
live game's TMP preferredWidth to 0.1 px (LogOutput.log "text diag" lines, 2026-11-16: 'Fusion Glossary' EN-Medium 16 =
100.6, 'Elemental Fusion' EN-Book 20 = 136.7, 'Cancel' EN-Book 20 = 53.2).

    python tools/factory_logistics/panel_text_metrics.py            # rewrite the C# table
    python tools/factory_logistics/panel_text_metrics.py --check    # fail if the C# table drifted from the font export
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = Path("V:/olden_port_work/factory_logistics/mockups/assets")
OUT = ROOT / "Heroes of Might & Magic Olden Era Playtest" / "OfflineUnlockMod" / "Homm3PanelTextMetrics.g.cs"
FONTS = ("EN-Regular", "EN-Medium", "EN-Book")
DENSE = range(32, 256)


def font_table(assets: Path, name: str) -> dict:
    f = json.loads((assets / f"{name}.json").read_text())
    em = f["pointSize"] / f["scale"]
    glyphs = {int(k): v for k, v in f["glyphs"].items()}
    adv = {}
    for code, g in ((int(k), v) for k, v in f["chars"].items()):
        if g in glyphs:
            adv[code] = round(glyphs[g]["adv"] / em, 4)
    return {
        "name": name,
        "line": round(f["lineHeight"] / em, 4),
        "ascent": round(f["ascent"] / em, 4),
        "descent": round(f["descent"] / em, 4),
        "dense": [adv.get(c, -1.0) for c in DENSE],
        "sparse": sorted((c, a) for c, a in adv.items() if c not in DENSE),
    }


def render(tables: list[dict]) -> str:
    out = [
        "// <auto-generated> tools/factory_logistics/panel_text_metrics.py from the game's SDF font export. Do not edit. </auto-generated>",
        "namespace OfflineUnlockMod;",
        "",
        "internal static partial class Homm3PanelTextMetrics",
        "{",
        "\tprivate static readonly FontMetrics[] Generated =",
        "\t{",
    ]
    for t in tables:
        dense = ", ".join(f"{v:g}f" for v in t["dense"])
        sparse_c = ", ".join(f"'\\u{c:04x}'" for c, _ in t["sparse"])
        sparse_a = ", ".join(f"{a:g}f" for _, a in t["sparse"])
        out += [
            f"\t\tnew FontMetrics(\"{t['name']}\", {t['line']:g}f, {t['ascent']:g}f, {t['descent']:g}f,",
            f"\t\t\tnew float[] {{ {dense} }},",
            f"\t\t\tnew[] {{ {sparse_c} }},",
            f"\t\t\tnew float[] {{ {sparse_a} }}),",
        ]
    out += ["\t};", "}", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--assets", type=Path, default=ASSETS)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render([font_table(args.assets, n) for n in FONTS])
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} drifted from the font export; rerun without --check", file=sys.stderr)
            return 1
        print(f"{OUT.name} matches the font export")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
