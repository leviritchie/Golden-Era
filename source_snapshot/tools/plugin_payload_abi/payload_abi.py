#!/usr/bin/env python3
"""Plugin payload compatibility versions (docs/plugin_payload_abi.md).

Delivery and runtime records pin the version of the plugin surface they depend on (UnitBundle, TownScene),
never the plugin DLL's sha256. The versions are consts in OfflineUnlockMod/PluginPayloadAbi.cs; the build
writes them into a sidecar next to the DLL, together with the sha256 of the DLL it was generated for:

    python tools/plugin_payload_abi/payload_abi.py emit --dll <OutDir>/OfflineUnlockMod.dll
    python tools/plugin_payload_abi/payload_abi.py check-installed [--plugin-dir D] [--surface S=N ...]
    python tools/plugin_payload_abi/payload_abi.py guard [--strict]
    python tools/plugin_payload_abi/payload_abi.py ack <surface> [--note TEXT]

emit             writes <dll dir>/OfflineUnlockMod.payload_abi.json (deployed with the DLL).
check-installed  fails closed unless the installed sidecar exists, is well formed, was generated for the installed
                 DLL (sha256 match: a hand-copied DLL without a regenerated sidecar fails) and, per --surface, carries
                 that version.
guard            the version-bump guard: warns when a surface's reader file changed since its last acknowledgement
                 (or the const moved without one). Warn-only by default; --strict exits 1. It is a prompt to decide,
                 not a proof: see the doc's "Limits".
ack              records the decision "these reader contents are compatible with version N" for one surface.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SURFACES = Path(__file__).resolve().parent / "surfaces.json"
SIDECAR_NAME = "OfflineUnlockMod.payload_abi.json"
SIDECAR_SCHEMA = "plugin_payload_abi_sidecar.v1"
RECORD_KEY = "pluginPayloadAbi"
GOLDEN_PLUGIN = Path("V:/SteamLibrary/steamapps/common/Heroes of Might and Magic Olden Era - Golden Era"
                     "/BepInEx/plugins/OfflineUnlockMod")


class AbiError(Exception):
    pass


def sha_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


# C# tokens that matter to the hash: string/char literals are kept verbatim, comments are dropped, whitespace collapses.
_CS_TOKENS = re.compile(r'@"(?:""|[^"])*"|\$?"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])\'|//[^\n]*|/\*.*?\*/|\s+', re.S)


def _code_only(text: str) -> str:
    def keep(m: re.Match) -> str:
        t = m.group(0)
        if t.startswith("//") or t.startswith("/*"):
            return " "
        return " " if t.isspace() else t
    return re.sub(r" +", " ", _CS_TOKENS.sub(keep, text)).strip()


def reader_sha(p: Path) -> str:
    """Hash of a reader's code with comments and whitespace removed, so a comment or reformatting edit (or a CRLF
    checkout) does not read as a change. String literals are kept: shader/node/key names live there."""
    return hashlib.sha256(_code_only(p.read_text(encoding="utf-8-sig")).encode("utf-8")).hexdigest()


def load_surfaces() -> dict:
    data = json.loads(SURFACES.read_text(encoding="utf-8"))
    if data.get("schema") != "plugin_payload_abi_surfaces.v1" or not isinstance(data.get("surfaces"), dict):
        raise AbiError(f"{SURFACES}: not a plugin_payload_abi_surfaces.v1 manifest")
    return data


def source_versions(manifest: dict | None = None) -> dict[str, int]:
    """{surface: version} parsed from the consts in PluginPayloadAbi.cs (the values the build compiles)."""
    manifest = manifest or load_surfaces()
    text = (ROOT / manifest["source"]).read_text(encoding="utf-8")
    out = {}
    for name, s in manifest["surfaces"].items():
        found = re.findall(rf"\bpublic\s+const\s+int\s+{re.escape(s['const'])}\s*=\s*(\d+)\s*;", text)
        if len(found) != 1:
            raise AbiError(f"{manifest['source']}: expected exactly one 'public const int {s['const']} = N;'")
        out[name] = int(found[0])
    return out


def emit(dll: Path) -> Path:
    if not dll.is_file():
        raise AbiError(f"emit: DLL not found: {dll}")
    manifest = load_surfaces()
    sidecar = dll.with_name(SIDECAR_NAME)
    body = {
        "schema": SIDECAR_SCHEMA,
        "dll": dll.name,
        "dllSha256": sha_file(dll),
        "dllBytes": dll.stat().st_size,
        "surfaces": source_versions(manifest),
        "source": manifest["source"],
        "generatedAt": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "note": "generated by the plugin build for exactly this DLL; never edit by hand (docs/plugin_payload_abi.md)",
    }
    tmp = sidecar.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(body, indent=1) + "\n", encoding="utf-8")
    tmp.replace(sidecar)
    return sidecar


def read_installed(plugin_dir: Path = GOLDEN_PLUGIN) -> dict:
    """The installed sidecar, verified against the installed DLL. Fails closed on any doubt."""
    dll, sidecar = plugin_dir / "OfflineUnlockMod.dll", plugin_dir / SIDECAR_NAME
    if not dll.is_file():
        raise AbiError(f"installed plugin DLL missing: {dll}")
    if not sidecar.is_file():
        raise AbiError(f"installed plugin has no {SIDECAR_NAME}: deploy the plugin through the established build "
                       f"(it emits the sidecar); a hand-copied DLL carries no payload versions")
    try:
        data = json.loads(sidecar.read_text(encoding="utf-8"))
    except ValueError as e:
        raise AbiError(f"{sidecar}: unreadable: {e}") from e
    surfaces = data.get("surfaces")
    if data.get("schema") != SIDECAR_SCHEMA or not isinstance(surfaces, dict) \
            or not all(isinstance(v, int) and not isinstance(v, bool) for v in surfaces.values()):
        raise AbiError(f"{sidecar}: not a {SIDECAR_SCHEMA} sidecar")
    got = sha_file(dll)
    if data.get("dllSha256") != got:
        raise AbiError(f"{sidecar} is stale: generated for DLL {str(data.get('dllSha256'))[:8]}, installed DLL is "
                       f"{got[:8]} (the DLL was replaced without its sidecar; redeploy through the build)")
    return {**data, "plugin_dir": str(plugin_dir)}


def require_installed_surface(surface: str, version: int, plugin_dir: Path = GOLDEN_PLUGIN) -> dict:
    data = read_installed(plugin_dir)
    have = data["surfaces"].get(surface)
    if have != version:
        raise AbiError(f"installed plugin {data['dllSha256'][:8]} carries {surface} v{have}, the record pins v{version}")
    return data


def record_pin(record: dict, surface: str, where: str) -> int:
    """The version a delivery/runtime record pins for `surface`; refuses legacy DLL-hash pins."""
    pin = record.get(RECORD_KEY)
    if not isinstance(pin, dict) or pin.get("surface") != surface or not isinstance(pin.get("version"), int) \
            or isinstance(pin.get("version"), bool):
        raise AbiError(f"{where}: no {RECORD_KEY} {{surface: {surface}, version: N}} pin")
    for legacy in ("dll", "dllSha256", "sources"):
        if legacy in record:
            raise AbiError(f"{where}: carries the retired plugin pin '{legacy}' (pin {RECORD_KEY} instead)")
    return pin["version"]


def require_record_current(record: dict, surface: str, where: str) -> int:
    """Record pin == the version the current source compiles (the plugin a deploy would build supports it)."""
    want = record_pin(record, surface, where)
    have = source_versions()[surface]
    if want != have:
        raise AbiError(f"{where}: pins {surface} v{want}, source PluginPayloadAbi.cs is v{have}; rebuild the record's "
                       f"payload against v{have}")
    return want


def guard(manifest: dict | None = None) -> list[str]:
    manifest = manifest or load_surfaces()
    versions = source_versions(manifest)
    warnings = []
    for name, s in manifest["surfaces"].items():
        ack = s.get("acknowledged") or {}
        if ack.get("version") != versions[name]:
            warnings.append(f"{name}: {s['const']} is v{versions[name]} but the last acknowledgement is "
                            f"v{ack.get('version')}; run payload_abi.py ack {name}")
            continue
        recorded = ack.get("readerSha256") or {}
        for rel in s["readers"]:
            p = ROOT / rel
            if not p.is_file():
                warnings.append(f"{name}: reader {rel} is missing")
            elif recorded.get(rel) != reader_sha(p):
                warnings.append(f"{name}: reader {Path(rel).name} changed since v{versions[name]} was acknowledged. "
                                f"If the change alters what {name} records depend on ({s['dependsOn']}), bump "
                                f"{s['const']}; either way run payload_abi.py ack {name}")
        extra = set(recorded) - set(s["readers"])
        if extra:
            warnings.append(f"{name}: acknowledgement names files that are not readers: {sorted(extra)}")
    return warnings


def ack(surface: str, note: str) -> dict:
    manifest = load_surfaces()
    if surface not in manifest["surfaces"]:
        raise AbiError(f"unknown surface {surface!r}; known: {sorted(manifest['surfaces'])}")
    s = manifest["surfaces"][surface]
    s["acknowledged"] = {
        "version": source_versions(manifest)[surface],
        "readerSha256": {rel: reader_sha(ROOT / rel) for rel in s["readers"]},
        "at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "note": note,
    }
    SURFACES.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return s["acknowledged"]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("emit")
    e.add_argument("--dll", type=Path, required=True)
    c = sub.add_parser("check-installed")
    c.add_argument("--plugin-dir", type=Path, default=GOLDEN_PLUGIN)
    c.add_argument("--surface", action="append", default=[], metavar="NAME=VERSION")
    c.add_argument("--require-source", action="store_true",
                   help="also require every installed surface version to equal the source const")
    g = sub.add_parser("guard")
    g.add_argument("--strict", action="store_true")
    a = sub.add_parser("ack")
    a.add_argument("surface")
    a.add_argument("--note", default="")
    args = ap.parse_args()
    try:
        if args.cmd == "emit":
            p = emit(args.dll)
            d = json.loads(p.read_text(encoding="utf-8"))
            print(f"payload_abi emit: {p} dll {d['dllSha256'][:8]} surfaces {d['surfaces']}")
        elif args.cmd == "check-installed":
            data = read_installed(args.plugin_dir)
            for spec in args.surface:
                name, _, v = spec.partition("=")
                require_installed_surface(name, int(v), args.plugin_dir)
            if args.require_source and data["surfaces"] != source_versions():
                raise AbiError(f"installed sidecar surfaces {data['surfaces']} differ from source {source_versions()}")
            print(f"payload_abi check-installed: OK dll {data['dllSha256'][:8]} surfaces {data['surfaces']}")
        elif args.cmd == "guard":
            warnings = guard()
            for w in warnings:
                print(f"WARNING payload_abi guard: {w}")
            if not warnings:
                print("payload_abi guard: OK (every surface's readers match their acknowledgement)")
            return 1 if warnings and args.strict else 0
        elif args.cmd == "ack":
            r = ack(args.surface, args.note)
            print(f"payload_abi ack: {args.surface} v{r['version']} over {len(r['readerSha256'])} readers")
    except AbiError as e:
        print(f"FAIL payload_abi: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
