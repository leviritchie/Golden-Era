#!/usr/bin/env python3
"""Gate: no placed HoMM3 map object may silently draw nothing on a translated map.

Inputs (tracked):
  tools/homm3_map_building_meshes/map_object_presentation_census.json  (generated by
      map_object_presentation.py census from the raw_translation placement ground truth)
  tools/homm3_map_building_meshes/map_object_presentation_ledger.json  (hand-written causes/fixes)
  tools/homm3_map_building_meshes/map_object_anim_coverage.json        (not_presented lane rows)

Checks:
  1. every census object id that draws nothing has a ledger row with a known cause and status;
  2. a ledger row for a draw-nothing cause is not stale (the census still shows it not drawn),
     unless its status is fix_in_source_pending_regeneration or delivered;
  3. every fix_in_source_pending_regeneration row is really in source: the substitution chooser
     maps the object id to expectedSid under expectedRule (so regeneration will deliver it);
  4. decision_needed rows list options; accepted_not_drawn rows give a reason;
  5. every def of a map_object_anim_coverage row in the not_presented lane is ledgered.

Proof tier: source/static + generated artifact. It does not prove the installed maps.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / "tools" / "homm3_map_building_meshes"
CENSUS = TOOL / "map_object_presentation_census.json"
LEDGER = TOOL / "map_object_presentation_ledger.json"
COVERAGE = TOOL / "map_object_anim_coverage.json"

CAUSES = {"dropped_in_raw_translation", "wrong_native_standin", "partial_standin", "removed_after_substitution"}
NOT_DRAWN_CAUSES = {"dropped_in_raw_translation", "removed_after_substitution"}
STATUSES = {"fix_in_source_pending_regeneration", "delivered", "decision_needed", "accepted_not_drawn"}


def source_mapping(object_id: int) -> tuple[str | None, str | None]:
    sys.path.insert(0, str(ROOT / "experiments" / "campaign_port_poc"))
    import build_homecoming_entity_substitution_map as sub  # noqa: E402

    hit = sub.DIRECT_BLOCKED_TEMPLATE_MAP.get(object_id)
    if object_id in sub.SIGN_OR_SIGNPOST_TEMPLATE_IDS:
        return "signpost", "signpost"
    if not hit:
        return None, None
    return hit[0], hit[1]


def main() -> int:
    errors: list[str] = []
    census = json.loads(CENSUS.read_text(encoding="utf-8"))
    ledger = json.loads(LEDGER.read_text(encoding="utf-8"))
    coverage = json.loads(COVERAGE.read_text(encoding="utf-8"))
    if census.get("schema") != "homm3_map_object_presentation_census.v1":
        errors.append(f"census schema {census.get('schema')!r}")
    if ledger.get("schema") != "homm3_map_object_presentation_ledger.v1":
        errors.append(f"ledger schema {ledger.get('schema')!r}")

    not_drawn = {r["objectId"]: r for r in census["rows"] if r.get("notDrawn")}
    census_by_id = {r["objectId"]: r for r in census["rows"]}
    rows: dict[int, dict] = {}
    for r in ledger["rows"]:
        oid = r.get("objectId")
        if oid in rows:
            errors.append(f"ledger: duplicate row for object {oid}")
        rows[oid] = r
        cause, status = r.get("cause"), r.get("status")
        if cause not in CAUSES:
            errors.append(f"ledger {oid}: unknown cause {cause!r}")
        if status not in STATUSES:
            errors.append(f"ledger {oid}: unknown status {status!r}")
        if status == "decision_needed" and not r.get("options"):
            errors.append(f"ledger {oid}: decision_needed without options")
        if status == "accepted_not_drawn" and not r.get("reason"):
            errors.append(f"ledger {oid}: accepted_not_drawn without reason")
        if status == "fix_in_source_pending_regeneration":
            want = (r.get("expectedSid"), r.get("expectedRule"))
            got = source_mapping(oid)
            if got != want:
                errors.append(f"ledger {oid}: pending fix {want} not in source (substitution map gives {got})")
        if cause in NOT_DRAWN_CAUSES and status not in ("fix_in_source_pending_regeneration", "delivered") \
                and oid not in not_drawn:
            errors.append(f"ledger {oid}: stale - the census no longer shows it not drawn; update the row")
        if status == "delivered" and oid in not_drawn:
            errors.append(f"ledger {oid}: marked delivered but the census still shows {not_drawn[oid]['notDrawnPlacements']} not drawn")
        # Visual-only DEF billboards (raw_translation/object_billboards.py): the ledger's drawn count
        # must be the census's, so a placement regression cannot hide behind a stale row.
        billboard = r.get("visualBillboard")
        census_billboards = census_by_id.get(oid, {}).get("visualBillboardPlacements", 0)
        if billboard is not None and billboard.get("placed") != census_billboards:
            errors.append(f"ledger {oid}: visualBillboard.placed={billboard.get('placed')} but the census draws {census_billboards}")
        if billboard is None and census_billboards:
            errors.append(f"ledger {oid}: census draws {census_billboards} billboard placements but the row has no visualBillboard")

    for oid, r in sorted(not_drawn.items()):
        if oid not in rows:
            errors.append(f"object {oid}: {r['notDrawnPlacements']} placements in {r['notDrawnMissions']} missions draw nothing "
                          f"({r['notDrawn']}; rules {list(r['notDrawnRules'])[:3]}) and it has no ledger row")

    ledgered_defs = {d.lower() for r in ledger["rows"] for d in r.get("defs", [])}
    for c in coverage.get("rows", []):
        if c.get("lane") != "not_presented":
            continue
        missing = [d for d in c.get("defs", []) if d.lower() not in ledgered_defs]
        if missing:
            errors.append(f"coverage {c.get('id')}: not_presented defs {missing} have no presentation ledger row")

    if errors:
        print("map object presentation contract FAILED:")
        for e in errors:
            print("  -", e)
        return 1
    pending = sum(1 for r in ledger["rows"] if r["status"] == "fix_in_source_pending_regeneration")
    decide = sum(1 for r in ledger["rows"] if r["status"] == "decision_needed")
    print(f"map object presentation contract OK: {len(not_drawn)} draw-nothing object ids ledgered "
          f"({census['counts']['notDrawnPlacements']} placements); {pending} fixed in source pending map "
          f"regeneration, {decide} awaiting a decision")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
