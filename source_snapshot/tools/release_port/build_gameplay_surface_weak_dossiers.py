#!/usr/bin/env python3
"""Build focused static dossiers for weak gameplay surface rows.

Input comes from the rerunnable weak dossier plan generated by
enrich_gameplay_surface_evidence_matrix.py. Exact law-surface dossier candidates
are preferred. When no candidate exists, this script extracts only explicit
Type.method or Type-like tokens from decompTargets and builds conservative type
or method dossiers. Rows without an exact target get an unresolved note instead.

This is static evidence generation only. It does not launch the game, patch
runtime methods, or promote gameplay.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PLAN = ROOT / "custom_factions" / "gameplay_surface_weak_dossier_plan.json"
DEFAULT_OUT_DIR = ROOT / "experiments" / "cpp2il_readable_csharp" / "samples" / "latest_refresh" / "gameplay_surface_weak_dossiers"
DEFAULT_INDEX_MD = ROOT / "docs" / "gameplay_surface_weak_dossier_index.md"
DEFAULT_INDEX_JSON = ROOT / "custom_factions" / "gameplay_surface_weak_dossier_index.json"
METHOD_DOSSIER_SCRIPT = ROOT / "experiments" / "cpp2il_readable_csharp" / "build_method_dossier.py"
ADDRESS_MAP = ROOT / "experiments" / "cpp2il_readable_csharp" / "samples" / "latest_refresh" / "address_map.json"

TYPE_MEMBER_RE = re.compile(r"\b(?P<type>[A-Z][A-Za-z0-9_.]*|[a-z]{2,4})\.(?P<member>[A-Za-z_][A-Za-z0-9_]*)\b")
TYPE_ONLY_RE = re.compile(r"^\s*(?P<type>(?:Building|Obj)[A-Za-z0-9_]*|[A-Z][A-Za-z0-9_.]*(?:Config|EventArgs|View|Data|Set|Rows?|Info|Params|Laws?|Object|Unit|Hero|Resource|Building|Tavern|Prison|Hex))\b")


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8-sig") as handle:
        return json.load(handle)


def dump_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def safe_stem(value: str) -> str:
    text = re.sub(r"[^A-Za-z0-9_.+-]+", "_", value).strip("_")
    return text[:120].rstrip("_") or "surface"


def split_dossier_target(target: str) -> tuple[str, str | None] | None:
    if "::" not in target:
        return None
    type_name, method = target.split("::", 1)
    type_name = type_name.strip()
    method = method.strip() or None
    if not type_name:
        return None
    return type_name, method


def explicit_targets(row: dict[str, Any]) -> list[dict[str, Any]]:
    targets: list[dict[str, Any]] = []
    seen: set[tuple[str, str | None]] = set()

    for candidate in row.get("runtimeSymbolCandidates", []):
        if not isinstance(candidate, dict):
            continue
        parsed = split_dossier_target(str(candidate.get("dossierTarget", "")))
        if not parsed:
            continue
        if parsed in seen:
            continue
        seen.add(parsed)
        targets.append(
            {
                "type": parsed[0],
                "method": parsed[1],
                "source": "runtimeSymbolCandidates.dossierTarget",
                "symbolId": candidate.get("symbolId"),
                "candidateBoundary": candidate.get("evidenceBoundary"),
            }
        )

    for raw_target in row.get("decompTargets", []):
        if not isinstance(raw_target, str):
            continue
        for match in TYPE_MEMBER_RE.finditer(raw_target):
            type_name = match.group("type")
            member = match.group("member")
            suffix = raw_target[match.end() : match.end() + 1]
            is_method = suffix == "("
            if member.startswith("Method_"):
                # Generated runtime names are not Cpp2IL method names. Keep the row unresolved
                # until a decomp method is explicitly mapped.
                continue
            parsed = (type_name, member if is_method else None)
            if parsed in seen:
                continue
            seen.add(parsed)
            targets.append(
                {
                    "type": type_name,
                    "method": member if is_method else None,
                    "source": f"decompTargets:{raw_target}",
                    "candidateBoundary": (
                        "Parsed exact Type.method token from decompTargets; still requires dossier and runtime reconciliation."
                        if is_method
                        else "Parsed exact Type.member token from decompTargets as type-level evidence only; member may be a field/property."
                    ),
                }
            )
        if TYPE_MEMBER_RE.search(raw_target):
            continue
        match = TYPE_ONLY_RE.match(raw_target)
        if not match:
            continue
        parsed = (match.group("type"), None)
        if parsed in seen:
            continue
        seen.add(parsed)
        targets.append(
            {
                "type": parsed[0],
                "method": None,
                "source": f"decompTargets:{raw_target}",
                "candidateBoundary": "Parsed explicit type token from decompTargets; type-level dossier only.",
            }
        )
    return targets


def build_one_dossier(row: dict[str, Any], target: dict[str, Any], out_dir: Path, timeout: int) -> dict[str, Any]:
    surface_id = row["surfaceId"]
    target_label = target["type"] if not target.get("method") else f"{target['type']}::{target['method']}"
    stem = safe_stem(f"{surface_id}__{target_label}")
    out_md = out_dir / f"{stem}.md"
    out_json = out_dir / f"{stem}.json"
    cmd = [
        sys.executable,
        str(METHOD_DOSSIER_SCRIPT),
        "--type",
        target["type"],
        "--out",
        str(out_md),
        "--out-json",
        str(out_json),
        "--summary-only",
        "--include-static-initializers",
        "--timeout-seconds",
        str(timeout),
    ]
    if target.get("method"):
        cmd.extend(["--method", target["method"]])
    if ADDRESS_MAP.exists():
        cmd.extend(["--address-map", str(ADDRESS_MAP)])
    completed = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if completed.returncode != 0 and "No .txt file found" in completed.stderr:
        declaration = build_declaration_only_dossier(row, target, out_dir, completed.stderr)
        if declaration is not None:
            return declaration
    return {
        "target": target_label,
        "targetType": target["type"],
        "targetMethod": target.get("method"),
        "source": target.get("source"),
        "symbolId": target.get("symbolId"),
        "candidateBoundary": target.get("candidateBoundary"),
        "status": "built" if completed.returncode == 0 else "failed",
        "markdown": str(out_md.relative_to(ROOT)),
        "manifest": str(out_json.relative_to(ROOT)),
        "returnCode": completed.returncode,
        "stderr": completed.stderr.strip(),
        "stdout": completed.stdout.strip(),
    }


def find_diffable_type_file(type_name: str) -> Path | None:
    short_name = type_name.split(".")[-1].split("+")[0]
    root = ROOT / "tmp" / "cpp2il_experiment" / "out_dev_diffable_cs" / "DiffableCs" / "Hex"
    for path in root.rglob(f"{short_name}.cs"):
        return path
    return None


def build_declaration_only_dossier(
    row: dict[str, Any],
    target: dict[str, Any],
    out_dir: Path,
    original_error: str,
) -> dict[str, Any] | None:
    csharp = find_diffable_type_file(target["type"])
    if csharp is None:
        return None
    surface_id = row["surfaceId"]
    target_label = target["type"] if not target.get("method") else f"{target['type']}::{target['method']}"
    stem = safe_stem(f"{surface_id}__{target_label}__DECLARATION_ONLY")
    out_md = out_dir / f"{stem}.md"
    out_json = out_dir / f"{stem}.json"
    text = csharp.read_text(encoding="utf-8", errors="replace").splitlines()
    declarations = [
        line.strip()
        for line in text
        if line.strip()
        and (
            line.lstrip().startswith("public ")
            or "//Field offset:" in line
            or line.lstrip().startswith("internal ")
            or line.lstrip().startswith("private ")
        )
    ][:160]
    lines = [
        f"# {surface_id}: {target_label}",
        "",
        "Status: declaration-only static dossier.",
        "",
        "Boundary: DiffableCs declaration exists, but the current ISIL dump has no matching type file. This proves type/field declaration only, not method body behavior, call sites, runtime symbol identity, or hook safety.",
        "",
        f"DiffableCs: `{csharp.relative_to(ROOT)}`",
        "",
        "Original method-dossier error:",
        "",
        "```text",
        original_error.strip(),
        "```",
        "",
        "## Declarations",
        "",
        "```csharp",
        *declarations,
        "```",
        "",
    ]
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text("\n".join(lines), encoding="utf-8")
    manifest = {
        "schemaVersion": 1,
        "surfaceId": surface_id,
        "target": target_label,
        "status": "declaration-only",
        "csharpPath": str(csharp.relative_to(ROOT)),
        "originalError": original_error.strip(),
        "evidenceBoundary": "Declaration-only; no ISIL body/call evidence.",
    }
    out_json.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return {
        "target": target_label,
        "targetType": target["type"],
        "targetMethod": target.get("method"),
        "source": target.get("source"),
        "symbolId": target.get("symbolId"),
        "candidateBoundary": target.get("candidateBoundary"),
        "status": "declaration-only",
        "markdown": str(out_md.relative_to(ROOT)),
        "manifest": str(out_json.relative_to(ROOT)),
        "returnCode": 0,
        "stderr": original_error.strip(),
        "stdout": "",
    }


def unresolved_entry(row: dict[str, Any]) -> dict[str, Any]:
    return {
        "status": "unresolved-target",
        "reason": "No exact runtime candidate, Type.method token, or explicit type token was available.",
        "decompTargets": row.get("decompTargets", []),
        "nextProofAction": row.get("nextProofAction"),
    }


def write_unresolved_note(row: dict[str, Any], out_dir: Path) -> dict[str, Any]:
    surface_id = row["surfaceId"]
    out_md = out_dir / f"{safe_stem(surface_id)}__UNRESOLVED.md"
    lines = [
        f"# {surface_id}",
        "",
        "Status: unresolved dossier target.",
        "",
        "Boundary: no exact method/type target was inferred. Do not runtime-probe this surface until the row names an exact decomp target.",
        "",
        "## Decomp Targets",
        "",
    ]
    for target in row.get("decompTargets", []):
        lines.append(f"- `{target}`")
    lines.extend(["", "## Next Proof Action", "", str(row.get("nextProofAction") or "Add exact decomp target identity.")])
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    entry = unresolved_entry(row)
    entry["markdown"] = str(out_md.relative_to(ROOT))
    return entry


def build_index(plan: dict[str, Any], out_dir: Path, *, timeout: int, max_targets_per_surface: int) -> dict[str, Any]:
    out_dir.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, Any]] = []
    for row in plan.get("weakSurfaces", []):
        if not isinstance(row, dict):
            continue
        targets = explicit_targets(row)[:max_targets_per_surface]
        builds = [build_one_dossier(row, target, out_dir, timeout) for target in targets]
        if not builds:
            builds = [write_unresolved_note(row, out_dir)]
        rows.append(
            {
                "surfaceId": row.get("surfaceId"),
                "domain": row.get("domain"),
                "status": row.get("status"),
                "packets": row.get("packets", []),
                "dossiers": builds,
            }
        )
    return {
        "schemaVersion": 1,
        "purpose": "Focused static dossier index for weak gameplay surface rows.",
        "generationBoundary": "Static decomp evidence only; build failures and unresolved targets are explicit blockers, not fallbacks.",
        "sourcePlanWeakSurfaceCount": plan.get("weakSurfaceCount"),
        "surfaceCount": len(rows),
        "builtDossierCount": sum(1 for row in rows for dossier in row["dossiers"] if dossier["status"] == "built"),
        "declarationOnlyDossierCount": sum(1 for row in rows for dossier in row["dossiers"] if dossier["status"] == "declaration-only"),
        "failedDossierCount": sum(1 for row in rows for dossier in row["dossiers"] if dossier["status"] == "failed"),
        "unresolvedSurfaceCount": sum(1 for row in rows if any(d["status"] == "unresolved-target" for d in row["dossiers"])),
        "surfaces": rows,
    }


def write_index_md(path: Path, index: dict[str, Any]) -> None:
    lines = [
        "# Gameplay Surface Weak Dossier Index",
        "",
        "Boundary: static decomp evidence only. Built dossiers do not prove runtime ordering, generated symbol identity, or hook safety.",
        "",
        f"Surface count: `{index['surfaceCount']}`",
        f"Built dossier count: `{index['builtDossierCount']}`",
        f"Declaration-only dossier count: `{index['declarationOnlyDossierCount']}`",
        f"Failed dossier count: `{index['failedDossierCount']}`",
        f"Unresolved surface count: `{index['unresolvedSurfaceCount']}`",
        "",
        "| Surface | Domain | Status | Dossier status | Target / note | Artifact |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in index["surfaces"]:
        for dossier in row["dossiers"]:
            target = dossier.get("target") or dossier.get("reason", "")
            artifact = dossier.get("markdown", "")
            lines.append(
                f"| `{row['surfaceId']}` | {row.get('domain')} | {row.get('status')} | "
                f"{dossier.get('status')} | `{str(target).replace('|', '/')}` | `{artifact}` |"
            )
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", type=Path, default=DEFAULT_PLAN)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--out-index-json", type=Path, default=DEFAULT_INDEX_JSON)
    parser.add_argument("--out-index-md", type=Path, default=DEFAULT_INDEX_MD)
    parser.add_argument("--timeout-seconds-per-dossier", type=int, default=120)
    parser.add_argument("--max-targets-per-surface", type=int, default=6)
    args = parser.parse_args()

    plan = load_json(args.plan)
    index = build_index(
        plan,
        args.out_dir,
        timeout=args.timeout_seconds_per_dossier,
        max_targets_per_surface=args.max_targets_per_surface,
    )
    dump_json(args.out_index_json, index)
    write_index_md(args.out_index_md, index)
    print(
        "weak gameplay surface dossier build complete "
        f"({index['builtDossierCount']} built, {index['declarationOnlyDossierCount']} declaration-only, {index['failedDossierCount']} failed, "
        f"{index['unresolvedSurfaceCount']} unresolved surface(s))"
    )
    return 1 if index["failedDossierCount"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
