#!/usr/bin/env python3
"""Scan the game's sprite assets and write custom_factions/unit_designs/card_icons/card_icon_pools.json.

The pools are the vanilla unit-card sprites a custom card may use (see homm3_unit_card_icons.py):
  glyph   - passive glyphs: `*_passive_*_name`, `base_passive_*_name` (gold on navy)
  painted - active paintings: `*_ability_*_name`, `common_attack_*_name` and the battle/neutral spell paintings
Needs UnityPy. Run again after a game update that adds unit cards:
  python tools/release_port/scan_unit_card_icon_pools.py --game-data "<game>/HeroesOldenEra_Data"
"""

from __future__ import annotations

import argparse
import glob
import json
import pathlib
import re

OUT = pathlib.Path(__file__).resolve().parents[2] / "custom_factions" / "unit_designs" / "card_icons" / "card_icon_pools.json"
GLYPH = re.compile(r"(_passive_\w*_name(_upg\w*)?|^base_passive_.*_name)$")
PAINTED = re.compile(r"(_ability_\d+_name\w*|^common_attack_\d+_name)$|^(primal|space|night|day|neutral)_\d*_?magic_\w+$")
# Placeholders and adventure-map spells: not unit-card art. (neutral_1_magic_mana_restore stays: its painting is
# the mana-drain/transfer card art.)
EXCLUDE = {
    "neutral_1_magic_back_to_garrison", "neutral_1_magic_mana_transfer", "neutral_1_magic_back_to_city",
    "neutral_magic_town_portal", "neutral_1_magic_change_use_necromancy",
    "neutral_1_magic_units_replace",
}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--game-data", required=True)
    args = parser.parse_args()
    import UnityPy  # noqa: PLC0415

    names: set[str] = set()
    for path in sorted(glob.glob(args.game_data + "/resources.assets") + glob.glob(args.game_data + "/sharedassets*.assets")):
        for obj in UnityPy.load(path).objects:
            if obj.type.name == "Sprite":
                names.add(obj.peek_name())
    doc = {
        "note": "Generated by tools/release_port/scan_unit_card_icon_pools.py from the game's sprite assets; do not edit.",
        "glyph": sorted(n for n in names if GLYPH.search(n)),
        "painted": sorted(n for n in names if PAINTED.search(n) and " " not in n and n not in EXCLUDE),
    }
    OUT.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")
    print(f"{OUT}: glyph {len(doc['glyph'])}, painted {len(doc['painted'])}")


if __name__ == "__main__":
    main()
