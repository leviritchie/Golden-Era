#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_TARGETS_PATH = ROOT / "custom_factions" / "custom_law_targets.json"
DEFAULT_PROOFS_PATH = ROOT / "custom_factions" / "custom_law_packet_proofs.json"
DEFAULT_OUTPUT = ROOT / "Heroes of Might & Magic Olden Era Playtest" / "OfflineUnlockMod" / "Homm3CustomLawPacketGate.cs"


INDEX_CONSTANT_BY_TARGET_INDEX = {
    2: "HeroSightRadiusIndex",
    6: "HeroPrimaryStatTrainingIndex",
    13: "CounterstrokeDoctrineIndex",
    15: "SpellSchoolAccessLowIndex",
    18: "MeleeFormationIndex",
    19: "RangedFormationIndex",
    21: "GoldIncomePercentIndex",
    22: "MoraleFlatIndex",
    25: "MoraleTriggerIndex",
    27: "SpellSchoolAccessHighIndex",
    28: "ExtraConstructionIndex",
    33: "AstrologyCalendarIncomeIndex",
    34: "SpellCooldownModifierIndex",
}


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8-sig") as f:
        return json.load(f)


def packet_const_name(packet: str) -> str:
    words = re.split(r"[^A-Za-z0-9]+", packet)
    return "".join(word[:1].upper() + word[1:] for word in words if word)


def csharp_string(value: str | None) -> str:
    if value is None:
        return "null"
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def packet_order(targets_doc: dict[str, Any]) -> list[str]:
    families = targets_doc.get("families") if isinstance(targets_doc.get("families"), dict) else {}
    ordered: list[str] = []
    for key in sorted(families, key=lambda k: int(k) if str(k).isdigit() else 9999):
        entry = families.get(key)
        if not isinstance(entry, dict):
            continue
        packet = entry.get("packet")
        if isinstance(packet, str) and packet and packet not in ordered:
            ordered.append(packet)
    return ordered


def law_index_cases(targets_doc: dict[str, Any]) -> dict[str, list[int]]:
    families = targets_doc.get("families") if isinstance(targets_doc.get("families"), dict) else {}
    result: dict[str, list[int]] = {}
    for key, entry in sorted(families.items(), key=lambda item: int(item[0]) if str(item[0]).isdigit() else 9999):
        if not isinstance(entry, dict):
            continue
        packet = entry.get("packet")
        try:
            index = int(key)
        except ValueError:
            continue
        if isinstance(packet, str) and packet:
            result.setdefault(packet, []).append(index)
    return result


def emit_gate(targets_doc: dict[str, Any], proofs_doc: dict[str, Any]) -> str:
    packets = packet_order(targets_doc)
    proofs = proofs_doc.get("packets") if isinstance(proofs_doc.get("packets"), dict) else {}
    cases_by_packet = law_index_cases(targets_doc)
    missing_constant_indices = sorted(
        {
            index
            for indices in cases_by_packet.values()
            for index in indices
            if index not in INDEX_CONSTANT_BY_TARGET_INDEX
        }
    )
    if missing_constant_indices:
        joined = ", ".join(str(index) for index in missing_constant_indices)
        raise ValueError(f"missing INDEX_CONSTANT_BY_TARGET_INDEX mapping for target law index/indices: {joined}")

    lines: list[str] = []
    lines.append("using System;")
    lines.append("using System.Text;")
    lines.append("")
    lines.append("namespace OfflineUnlockMod;")
    lines.append("")
    lines.append("/// <summary>")
    lines.append("/// Runtime-side proof gate for no-compromise custom law packets.")
    lines.append("/// This file is generated by tools/release_port/generate_custom_law_packet_gate.py.")
    lines.append("/// Do not hand-edit packet proof states; update custom_law_packet_proofs.json and regenerate.")
    lines.append("/// </summary>")
    lines.append("internal static class Homm3CustomLawPacketGate")
    lines.append("{")
    for packet in packets:
        lines.append(f'\tinternal const string {packet_const_name(packet)} = "{packet}";')
    lines.append("")
    lines.append("\t// Temporary high-risk implementation switch: enables source-prepared packet hooks for runtime testing without marking packet proofs as gameplay-proven.")
    lines.append("\tinternal const bool BruteForceSourcePreparedGameplay = true;")
    lines.append("")
    lines.append("\tinternal static readonly string[] KnownPackets =")
    lines.append("\t{")
    for packet in packets:
        lines.append(f"\t\t{packet_const_name(packet)},")
    lines.append("\t};")
    lines.append("")
    lines.append("\tinternal struct PacketProofState")
    lines.append("\t{")
    lines.append("\t\tinternal string Packet;")
    lines.append("\t\tinternal string ProofStatus;")
    lines.append("\t\tinternal bool GameplayAllowed;")
    lines.append("\t\tinternal string EvidenceSummary;")
    lines.append("\t\tinternal string LastEvidenceArtifact;")
    lines.append("")
    lines.append("\t\tpublic override string ToString()")
    lines.append("\t\t{")
    lines.append("\t\t\treturn \"packet='\" + Packet")
    lines.append("\t\t\t       + \"' proofStatus='\" + ProofStatus")
    lines.append("\t\t\t       + \"' gameplayAllowed=\" + GameplayAllowed")
    lines.append("\t\t\t       + \" evidence='\" + EvidenceSummary")
    lines.append("\t\t\t       + \"' artifact='\" + (LastEvidenceArtifact ?? \"none\") + \"'\";")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("")
    lines.append("\tinternal static bool TryGetPacketForLawIndex(int lawIndex, out string packet)")
    lines.append("\t{")
    lines.append("\t\tswitch (lawIndex)")
    lines.append("\t\t{")
    for packet in packets:
        for index in cases_by_packet.get(packet, []):
            constant = INDEX_CONSTANT_BY_TARGET_INDEX[index]
            lines.append(f"\t\t\tcase Homm3CustomFactionLawRuntime.{constant}:")
        lines.append(f"\t\t\t\tpacket = {packet_const_name(packet)};")
        lines.append("\t\t\t\treturn true;")
    lines.append("\t\t\tdefault:")
    lines.append("\t\t\t\tpacket = null;")
    lines.append("\t\t\t\treturn false;")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("")
    lines.append("\tinternal static bool TryGetProofState(string packet, out PacketProofState state)")
    lines.append("\t{")
    lines.append("\t\tstate = default;")
    lines.append("\t\tif (string.IsNullOrWhiteSpace(packet))")
    lines.append("\t\t\treturn false;")
    lines.append("\t\tswitch (packet)")
    lines.append("\t\t{")
    for packet in packets:
        proof = proofs.get(packet) if isinstance(proofs.get(packet), dict) else {}
        proof_status = str(proof.get("proofStatus") or "runtime-unproven")
        gameplay_allowed = bool(proof.get("gameplayAllowed"))
        summary = str(proof.get("evidenceSummary") or "No evidence summary recorded.")
        artifact = proof.get("lastEvidenceArtifact")
        if artifact is not None:
            artifact = str(artifact)
        lines.append(f"\t\t\tcase {packet_const_name(packet)}:")
        lines.append("\t\t\t\tstate = new PacketProofState")
        lines.append("\t\t\t\t{")
        lines.append(f"\t\t\t\t\tPacket = {packet_const_name(packet)},")
        lines.append(f"\t\t\t\t\tProofStatus = {csharp_string(proof_status)},")
        lines.append(f"\t\t\t\t\tGameplayAllowed = {'true' if gameplay_allowed else 'false'},")
        lines.append(f"\t\t\t\t\tEvidenceSummary = {csharp_string(summary)},")
        lines.append(f"\t\t\t\t\tLastEvidenceArtifact = {csharp_string(artifact)},")
        lines.append("\t\t\t\t};")
        lines.append("\t\t\t\treturn true;")
    lines.append("\t\t\tdefault:")
    lines.append("\t\t\t\treturn false;")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("")
    lines.append("\tinternal static bool IsGameplayAllowed(string packet, out string failReason)")
    lines.append("\t{")
    lines.append("\t\tif (!TryGetProofState(packet, out var state))")
    lines.append("\t\t{")
    lines.append("\t\t\tfailReason = \"unknown custom law packet '\" + (packet ?? \"null\") + \"'\";")
    lines.append("\t\t\treturn false;")
    lines.append("\t\t}")
    lines.append("\t\tif (BruteForceSourcePreparedGameplay && IsBruteForcePacketAllowed(state.Packet))")
    lines.append("\t\t{")
    lines.append("\t\t\tfailReason = null;")
    lines.append("\t\t\treturn true;")
    lines.append("\t\t}")
    lines.append("\t\tif (!state.GameplayAllowed)")
    lines.append("\t\t{")
    lines.append("\t\t\tfailReason = \"packet '\" + state.Packet + \"' is \" + state.ProofStatus + \"; \" + state.EvidenceSummary;")
    lines.append("\t\t\treturn false;")
    lines.append("\t\t}")
    lines.append("\t\tfailReason = null;")
    lines.append("\t\treturn true;")
    lines.append("\t}")
    lines.append("")
    lines.append("")
    lines.append("\tinternal static bool IsBruteForcePacketAllowed(string packet)")
    lines.append("\t{")
    lines.append("\t\tswitch (packet)")
    lines.append("\t\t{")
    lines.append("\t\t\tcase CommittedDamage:")
    lines.append("\t\t\tcase Counterattack:")
    lines.append("\t\t\tcase SpellCooldown:")
    lines.append("\t\t\tcase BattleAction:")
    lines.append("\t\t\tcase RewardResult:")
    lines.append("\t\t\tcase Morale:")
    lines.append("\t\t\t\treturn true;")
    lines.append("\t\t\tcase Vision:")
    lines.append("\t\t\tcase Construction:")
    lines.append("\t\t\tdefault:")
    lines.append("\t\t\t\treturn false;")
    lines.append("\t\t}")
    lines.append("\t}")
    lines.append("")
    lines.append("\tinternal static bool IsLawIndexGameplayAllowed(int lawIndex, out string packet, out string failReason)")
    lines.append("\t{")
    lines.append("\t\tif (!TryGetPacketForLawIndex(lawIndex, out packet))")
    lines.append("\t\t{")
    lines.append("\t\t\tfailReason = \"law index \" + lawIndex.ToString(System.Globalization.CultureInfo.InvariantCulture) + \" has no no-compromise packet mapping\";")
    lines.append("\t\t\treturn false;")
    lines.append("\t\t}")
    lines.append("\t\treturn IsGameplayAllowed(packet, out failReason);")
    lines.append("\t}")
    lines.append("")
    lines.append("\tinternal static string DescribeKnownProofStates()")
    lines.append("\t{")
    lines.append("\t\tvar sb = new StringBuilder();")
    lines.append("\t\tfor (var i = 0; i < KnownPackets.Length; i++)")
    lines.append("\t\t{")
    lines.append("\t\t\tif (i > 0)")
    lines.append("\t\t\t\tsb.Append(\"; \");")
    lines.append("\t\t\tif (TryGetProofState(KnownPackets[i], out var state))")
    lines.append("\t\t\t\tsb.Append(state);")
    lines.append("\t\t\telse")
    lines.append("\t\t\t\tsb.Append(\"packet='\").Append(KnownPackets[i]).Append(\"' proofState=missing\");")
    lines.append("\t\t}")
    lines.append("\t\treturn sb.ToString();")
    lines.append("\t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Homm3CustomLawPacketGate.cs from target/proof JSON.")
    parser.add_argument("--targets", type=Path, default=DEFAULT_TARGETS_PATH)
    parser.add_argument("--proofs", type=Path, default=DEFAULT_PROOFS_PATH)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="Compare generated output to --out without writing.")
    args = parser.parse_args()

    targets_doc = load_json(args.targets)
    proofs_doc = load_json(args.proofs)
    if not isinstance(targets_doc, dict) or not isinstance(proofs_doc, dict):
        print("error: targets and proofs must be JSON objects", file=sys.stderr)
        return 1
    try:
        generated = emit_gate(targets_doc, proofs_doc)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if not args.out.exists():
            print(f"error: missing output file {args.out}", file=sys.stderr)
            return 1
        actual = args.out.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
        if actual != generated:
            print(f"error: {args.out} is stale; run tools/release_port/generate_custom_law_packet_gate.py", file=sys.stderr)
            return 1
        print(f"{args.out} is in sync with packet proof JSON")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generated, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
