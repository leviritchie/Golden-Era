#!/usr/bin/env bash
# Homecoming campaign-batch regression + Golden Era deploy helper.
#
# Usage:
#   ./tools/test_homecoming_campaign_batch_regression.sh regression
#   ./tools/test_homecoming_campaign_batch_regression.sh regression-quick
#   ./tools/test_homecoming_campaign_batch_regression.sh deploy
#   ./tools/test_homecoming_campaign_batch_regression.sh all
#
# Environment overrides:
#   GAME_ROOT   Golden Era install root (default: Steam Golden Era path)
#   REPO_ROOT   Repository root (default: parent of tools/)

set -euo pipefail

REPO_ROOT="${REPO_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
GAME_ROOT="${GAME_ROOT:-V:/SteamLibrary/steamapps/common/Heroes of Might and Magic Olden Era - Golden Era}"
MODE="${1:-regression}"
MAP_SID="h3_roe_castle_homecoming_raw_translation"
CSPROJ="$REPO_ROOT/Heroes of Might & Magic Olden Era Playtest/OfflineUnlockMod/OfflineUnlockMod.csproj"

run_regression() {
  local batch_flags=()
  if [[ "${1:-}" == "quick" ]]; then
    batch_flags=(--skip-alignment-refresh)
    echo "==> Homecoming raw_translation regression (quick: reuse on-disk alignment story)"
  else
    echo "==> Homecoming raw_translation regression (regenerate profile + alignment + map)"
  fi
  # raw_translation is the only campaign map generation lane, so the regression regenerates
  # and validates exactly the artifact the StoryHub continuity installer ships.
  ( cd "$REPO_ROOT/experiments/campaign_port_poc" \
    && python build_campaign_raw_translation_batch.py \
      --manifest "$REPO_ROOT/scenarios/roe_castle_campaign/batch_manifest.json" \
      --mission homecoming "${batch_flags[@]}" )
  python "$REPO_ROOT/tools/validate_homecoming_raw_translation_map_contract.py" \
    --repo-root "$REPO_ROOT" \
    --skip-generate
  python "$REPO_ROOT/tools/validate_raw_translation_profile_generation_contract.py"
}

run_deploy() {
  echo "==> Build + deploy OfflineUnlockMod and Homecoming maps to Golden Era"
  echo "    GameRoot: $GAME_ROOT"
  if [[ ! -d "$GAME_ROOT/BepInEx" ]]; then
    echo "ERROR: Golden Era install not found at GAME_ROOT=$GAME_ROOT" >&2
    exit 1
  fi
  dotnet build "$CSPROJ" -c Release \
    "-p:GameRoot=$GAME_ROOT" \
    -p:OfficialDeobfBuild=true \
    -p:RunExpensiveHomecomingArtifactAudits=true \
    -t:DeployPluginToGame
  echo "==> Install raw_translation map payload + Core.zip overlay"
  python "$REPO_ROOT/tools/install_homecoming_raw_translation_map.py" \
    --repo-root "$REPO_ROOT" \
    --game-root "$GAME_ROOT"
  cat <<EOF

Deploy complete.

In Golden Era, start a custom scenario using map sid:
  $MAP_SID

Artifacts were generated by the central campaign batch generator:
  scenarios/roe_castle_campaign/batch_manifest.json  (missionId: homecoming)

raw_translation is the only campaign map generation lane; there is no parallel
layered-atlas / approach-cell / zone-atlas / single-layer payload to install.

EOF
}

case "$MODE" in
  regression)
    run_regression
    ;;
  regression-quick)
    run_regression quick
    ;;
  deploy)
    run_deploy
    ;;
  all)
    run_regression
    run_deploy
    ;;
  *)
    echo "Unknown mode: $MODE" >&2
    echo "Modes: regression | regression-quick | deploy | all" >&2
    exit 2
    ;;
esac
