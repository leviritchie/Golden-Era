"""Rampart: articulated winged horse + rider (pegasus line), hand-keyed per DEF frame.

Why: the pegasus builds (rampart_quadruped with a static capture) moved as a rigid toy: a per-frame
silhouette search pitched, rolled and bounced the whole body, the wings were rigid planks, the
neck/head never moved outside a 3 deg idle nod, the legs moved only in Move, and the rider (rigid on
Spine1) never lifted the sword the DEF swings in every action clip. This module keeps the quadruped
module's static capture and tail chain, and adds

after_skin (list AFTER rampart_quadruped, so the tail chain exists; wing_chain re-weights the wings)
  * "riderBones": bones for the rider cut from the horse's Spine1 (the rider/arm/sword props are bound
    100% to Spine1 by the core `props` cut, so they move rigidly with the horse). Each entry
    {"name", "head", "tail", "parent", "region": <box|segments+radius|sphere, optional exclude>}
    takes every vertex inside its region whose weights are all on bones of `from` (default
    ["Spine1"]: the rider prop cut) and moves it wholly to the new bone; the first matching entry
    wins, so list the sword and arms before the torso. A limb thicker than its prop capsule has an
    outer skin heat-weighted to the horse's spine, so an arm entry may widen `from` to the spine
    bones (the horse's own surface carries leg or neck weight there and stays out).
    "afterPaint": true cuts the entry after riderPaint (rider legs only become wholly Spine1 there).
  * "riderPaint": {"rules": [{"to": bone, "region": <region>}], "skipOn": [bones], "minRedMinusBlue",
    "minSat"}: rider-coloured (warm texture) vertices that bone heat put on the horse's legs or neck
    move wholly to `to` (see _rider_paint), and the surface is split along that boundary.
  * "legGate": {"center": x0, "band": b, "front": [bones], "hind": [bones], "frontBody": "Spine2",
    "hindBody": "Hips"}: bone heat bleeds each leg into the other leg and the belly/chest between them
    (LH+RH 149 verts, LF+RF 58 on h3_pegasus), which tears when the legs move in opposite phase. A
    Left* leg bone keeps its weight only on the +X side of x0 (smoothstep over +-b), a Right* bone
    only on the -X side; the removed share goes to the body bone.
  * "tailClean": true: vertices on the tail chain (QTail_*) lose any leg-bone weight to Hips (the
    dock was 277 verts shared between the tail and the right hind leg).

after_pose (all motion; runs after rampart_quadruped's re-chain, which leaves every bone at rest)
  "pegasusKeys": {clip: [{"f": i, "rot": {bone: [x, y, z]}, "body": {...}, "plant": {leg: w}}, ...]}
  * rot: degrees about the WORLD rest axes (X lateral/left, Y tailward, Z up; the unit faces -Y), XYZ
    order, applied to the bone relative to its parent (so a child's axis turns with its parent).
    +X on a hanging leg swings the hoof back (tailward); +X on the neck lowers the nose.
  * body: whole-body "rear" (deg, + nose up about the hind hooves, or about the pelvis with "rearHip" 1
    (0..1 blends the pivot from the hind hooves to the Hips joint: the forehand lifts while the hips stay
    put and the planted hind legs flex), - nose down about the front
    hooves), "roll" (deg, onto the +X flank about a ground line `sideOffset` to that side, - onto -X),
    "x" / "y" / "z" (scene units: toward the +X flank / tailward / up; x keeps a roll from sliding the
    body off its hex: the roll pivots about a ground line, so the raised body swings ~1.2 m sideways).
  * plant: per leg name (see "legs") a weight 0..1: two-bone IK about the body's lateral axis brings
    the leg's `end` joint back to its rest (ground) position and puts the `flat` bones back to their
    rest world attitude, so a rearing horse stands on bent hind legs instead of tilting them.
  Each bone / body param / plant interpolates linearly between the keys that mention it and holds
  outside them. Keys are dense (one per DEF frame) and are generated by
  handoffs/rampart_tools/pegasus_keys.py.
  "legs": {"LH": {"ik": [upper, mid], "end": bone, "flat": [bones]}, ...}

Wings: `wing_chain` (fan) poses them in before_keys from the posed parent, so they follow the body.
Prints "PEGASUS ...".
"""
import json, math
import numpy as np
from mathutils import Matrix, Vector

_STATE = {}


def _cfg(g):
    return g["cfg"].get("pegasus", {})


def _region(reg):
    from rampart_quadruped import _region_test
    return _region_test(reg)


def after_skin(g):
    P = _cfg(g)
    if not P:
        return
    import bpy
    body, rig = g["body"], g["rig"]
    vg = body.vertex_groups
    names = {x.index: x.name for x in vg}
    RB = P.get("riderBones", [])
    if RB:
        bpy.context.view_layer.objects.active = rig
        bpy.ops.object.mode_set(mode='EDIT')
        eb = rig.data.edit_bones
        for r in RB:
            b = eb.new(r["name"]); b.head, b.tail = Vector(r["head"]), Vector(r["tail"]); b.roll = 0
        for r in RB:                         # parents after all exist (the list is in match order)
            eb[r["name"]].parent = eb[r.get("parent", "Spine1")]
        bpy.ops.object.mode_set(mode='OBJECT')
        mine = {r["name"] for r in RB}
        done, todo = set(), list(RB)
        while todo:                          # bone_names in parent-first order (after_pose walks it)
            r = next(x for x in todo if x.get("parent", "Spine1") not in mine or x.get("parent", "Spine1") in done)
            todo.remove(r); done.add(r["name"])
            g["bone_names"].append(r["name"]); g["parent_of"][r["name"]] = r.get("parent", "Spine1")
            g["STATIC"].add(r["name"])       # follows its parent until after_pose keys it
        tests = {False: [], True: []}
        for r in RB:
            vg.new(name=r["name"])
            tests[bool(r.get("afterPaint"))].append((r["name"], _region(r["region"]), set(r.get("from", ["Spine1"]))))

        def cut(tl, tag):
            names = {x.index: x.name for x in vg}
            cnt = {}
            for v in body.data.vertices:
                gs = [(names[x.group], x.weight) for x in v.groups if x.weight > 1e-4]
                if not gs:
                    continue
                for nm, test, src in tl:
                    if all(n in src for n, _ in gs) and test(v.co):
                        for n, _ in gs:
                            vg[n].remove([v.index])
                        vg[nm].add([v.index], 1.0, 'REPLACE')
                        cnt[nm] = cnt.get(nm, 0) + 1
                        break
            print("PEGASUS rider bones" + tag, cnt)
        cut(tests[False], "")
        RP = P.get("riderPaint")
        if RP:
            _rider_paint(body, RP)
        # "afterPaint": true bones cut after riderPaint, which is what makes the rider's lower legs wholly
        # Spine1 (h3_pegasus RiderLegL: only 29 of the far shin's ~98 verts were Spine1-only before it)
        if tests[True]:
            cut(tests[True], " afterPaint")
        names = {x.index: x.name for x in vg}
        RW = P.get("ripWeld")
        RW = [RW] if isinstance(RW, dict) else RW or []   # one pass or a list of passes
        for rw in [x for x in RW if not x.get("afterSmooth")]:
            _rip_weld(body, set(rw["bones"]), set(rw.get("keep", [])), rw.get("claim"))
            names = {x.index: x.name for x in vg}
        RS = P.get("riderSmooth")
        if RS:
            _smooth_rider(body, vg, (set(RS.get("bones", [])) | {r["name"] for r in RB}) - set(RS.get("exclude", [])),
                          RS.get("iters", 8))
        # "afterSmooth": true passes run after riderSmooth: the smoothing blends the claimed grip rows back toward
        # RiderSpine ({RiderArmR .73, RiderSpine .27} next to a wholly-Spine1 withers vertex: a 14x wrist sliver in
        # h3_pegasus AttackFront/Defence/Hitted), so the claim + split has to see the smoothed rows.
        for rw in [x for x in RW if x.get("afterSmooth")]:
            _rip_weld(body, set(rw["bones"]), set(rw.get("keep", [])), rw.get("claim"))
            names = {x.index: x.name for x in vg}
    LG = P.get("legGate")
    if LG:
        c0, band = LG.get("center", 0.0), LG.get("band", 0.05)
        front, hind = set(LG.get("front", [])), set(LG.get("hind", []))
        fb, hb = LG.get("frontBody", "Spine2"), LG.get("hindBody", "Hips")
        moved = 0
        for v in body.data.vertices:
            row = {names[x.group]: x.weight for x in v.groups if x.weight > 0}
            gain = {}
            for n, w in list(row.items()):
                if n not in front and n not in hind:
                    continue
                s = 1.0 if n.startswith("Left") else -1.0
                u = max(0.0, min(1.0, (s * (v.co.x - c0) + band) / (2 * band)))
                keep = u * u * (3 - 2 * u)
                if keep < 1.0:
                    tb = fb if n in front else hb
                    gain[tb] = gain.get(tb, 0.0) + w * (1 - keep)
                    row[n] = w * keep
            if not gain:
                continue
            for n, w in gain.items():
                row[n] = row.get(n, 0.0) + w
            _write_row(vg, v, row)
            moved += 1
        print("PEGASUS legGate verts re-weighted", moved)
    if P.get("tailClean"):
        legs = set(LG.get("front", []) + LG.get("hind", [])) if LG else set()
        moved = 0
        for v in body.data.vertices:
            row = {names[x.group]: x.weight for x in v.groups if x.weight > 0}
            if not any(n.startswith("QTail_") for n in row):
                continue
            lw = sum(w for n, w in row.items() if n in legs)
            if lw <= 0:
                continue
            row = {n: w for n, w in row.items() if n not in legs}
            row["Hips"] = row.get("Hips", 0.0) + lw
            _write_row(vg, v, row)
            moved += 1
        print("PEGASUS tailClean verts", moved)


def _texture_colour(body):
    """Mean base-colour texel per vertex (over its loops), or None when the body has no image."""
    img = None
    for m in body.data.materials:
        if m and m.use_nodes:
            img = next((n.image for n in m.node_tree.nodes if n.type == 'TEX_IMAGE' and n.image), None)
            if img:
                break
    if img is None:
        return None
    W, H = img.size
    px = np.array(img.pixels[:], dtype=np.float32).reshape(H, W, img.channels)[..., :3]
    me = body.data; uv = me.uv_layers.active.data
    acc = np.zeros((len(me.vertices), 3)); cnt = np.zeros(len(me.vertices))
    for l in me.loops:
        u, v = uv[l.index].uv
        acc[l.vertex_index] += px[int((v % 1) * (H - 1)), int((u % 1) * (W - 1))]; cnt[l.vertex_index] += 1
    return acc / np.maximum(cnt, 1)[:, None]


def _rider_paint(body, RP):
    """The rider's shins hang against the horse's shoulders and her rein hand lies on its neck, and
    bone heat put them on the horse's leg and neck bones (h3_pegasus: 221 rider-coloured vertices on
    Left/RightShoulder, 105 on Neck), so every stride and every head toss pulled her feet and hand
    into strips. The rider is the only warm-coloured (skin/leather) surface there, so the texture
    separates her from the white horse where the geometry cannot. Each rule {"to": bone, "region":
    <region>} moves every warm vertex (red - blue >= `minRedMinusBlue`, max - min channel >= `minSat`)
    inside its region wholly to `to`, then the surface is split along the boundary between painted
    and unpainted faces, each split copy taking its own side's mean row (as ripWeld does). Vertices
    with any weight on a `skipOn` bone (the rider bones already cut) are left alone. With "ripRegion"
    the split instead runs along the whole rider/horse boundary inside that region (rider = warm or
    wholly on `skipOn` bones): Meshy welded her chest into the mane and her sword hand into her thigh
    (h3_pegasus: 130 + 85 edges past 2x in Hitted without corrective smooth)."""
    import bmesh
    col = _texture_colour(body)
    if col is None:
        raise RuntimeError("PEGASUS riderPaint: body has no base-colour image")
    warm = ((col[:, 0] - col[:, 2]) >= RP.get("minRedMinusBlue", 0.08)) & \
           ((col.max(1) - col.min(1)) >= RP.get("minSat", 0.1))
    vg = body.vertex_groups
    rules = [(r["to"], _region(r["region"])) for r in RP["rules"]]
    skip = {vg[n].index for n in RP.get("skipOn", []) if n in vg}
    painted, cnt = set(), {}
    for v in body.data.vertices:
        if not warm[v.index] or any(x.group in skip and x.weight > 1e-4 for x in v.groups):
            continue
        for to, test in rules:
            if test(v.co):
                _write_row(vg, v, {to: 1.0}); painted.add(v.index); cnt[to] = cnt.get(to, 0) + 1
                break
    print("PEGASUS riderPaint verts", cnt)
    bm = bmesh.new(); bm.from_mesh(body.data)
    dl = bm.verts.layers.deform.active
    pl = bm.verts.layers.int.new("_painted")
    bm.verts.ensure_lookup_table()
    for i in painted:
        bm.verts[i][pl] = 1
    rip = _region(RP["ripRegion"]) if RP.get("ripRegion") else None
    if rip:                              # the whole rider, not only the painted parts, leaves the horse
        rb = {vg[n].index for n in RP.get("skipOn", []) if n in vg}
        for v in bm.verts:
            ks = [k for k, w in v[dl].items() if w > 1e-4]
            if rip(v.co) and (warm[v.index] or (ks and set(ks) <= rb)):
                v[pl] = 1
    side = {f: (2 * sum(v[pl] for v in f.verts) > len(f.verts)) for f in bm.faces}
    cut = [e for e in bm.edges if len({side[f] for f in e.link_faces}) == 2
           and (rip is None or rip((e.verts[0].co + e.verts[1].co) * 0.5))]
    bmesh.ops.split_edges(bm, edges=cut)
    corners = _separate_corners(bm, dl, side, True, False, lambda u: bool(u[pl]))
    fixed = 0
    for v in bm.verts:
        ss = {side.get(f) for f in v.link_faces}
        if len(ss) != 1:
            continue
        want = next(iter(ss))
        if bool(v[pl]) == want:
            continue
        acc, nacc = {}, 0
        for f in v.link_faces:
            for u in f.verts:
                if u is not v and bool(u[pl]) == want:
                    for k, w in u[dl].items():
                        acc[k] = acc.get(k, 0.0) + w
                    nacc += 1
        if nacc:
            tot = sum(acc.values()); d = v[dl]; d.clear()
            for k, w in acc.items():
                d[k] = w / tot
            v[pl] = int(want); fixed += 1
    bm.verts.layers.int.remove(pl)
    bm.to_mesh(body.data); bm.free()
    print("PEGASUS riderPaint edges split", len(cut), "corners", corners, "vertex rows re-sided", fixed)


def _separate_corners(bm, dl, side, a_val, b_val, is_a):
    """split_edges only cuts along edges; faces of the two sides that meet at a single vertex stay
    joined there. Give every `b_val` face its own copy of such a vertex, all copies carrying the mean
    row of the b-side vertices around it, and leave the original to the a side (its row becomes the
    mean a-side row when it is not an a vertex itself). Returns the number of corners separated."""
    import bmesh

    def mean(vs):
        acc = {}
        for u in vs:
            for k, w in u[dl].items():
                acc[k] = acc.get(k, 0.0) + w
        tot = sum(acc.values())
        return {k: w / tot for k, w in acc.items()} if tot > 0 else None

    def put(v, r):
        d = v[dl]; d.clear()
        for k, w in r.items():
            d[k] = w

    n = 0
    for v in list(bm.verts):
        fa = [f for f in v.link_faces if side.get(f) == a_val]
        fb = [f for f in v.link_faces if side.get(f) == b_val]
        if not fa or not fb:
            continue
        rb = mean([u for f in fb for u in f.verts if u is not v and not is_a(u)]) or dict(v[dl].items())
        if not is_a(v):
            ra = mean([u for f in fa for u in f.verts if u is not v and is_a(u)])
            if ra:
                put(v, ra)
        for f in fb:
            nv = bmesh.utils.face_vert_separate(f, v)
            if nv is not v:
                put(nv, rb)
        n += 1
    return n


def _rip_weld(body, bones, keep, claim=None):
    """Meshy welded the rider's sword hand into the horse's back and her thigh, so a raised sword arm
    drags a sheet of horse and thigh up with it (edges to 4.9x on h3_pegasus Defence). Split the
    surface along the boundary between the faces of `bones` (a face belongs to them when most of its
    vertices are wholly on them) and every other face, except faces wholly on `keep` (the rider's own
    torso, where the shoulder must stay attached). A split vertex copy takes the mean weight row of the
    same-side vertices it shares a face with, so the hand keeps only hand weights and the horse only
    horse weights.

    `claim` {"region": <region>, "minShare": 0.5} (opt-in): first, inside the region, a vertex whose share
    on `bones` is >= minShare goes wholly to its dominant one of them, and a smaller share is dropped
    (the rest renormalised). riderPaint's re-sided rows leave the sword grip blended with the horse
    (h3_pegasus: {Spine1 .75, RiderSword .25}, an elbow {RiderArmR .5, RightWing .5}); such a vertex is
    neither arm nor horse here, so the split missed it and a raised sword arm pulled a 30x sheet off
    the thigh and wing root (numpy sim of the claim + split: 31x -> 4x in AttackFront/Defence/Hitted)."""
    import bmesh
    bm = bmesh.new(); bm.from_mesh(body.data)
    dl = bm.verts.layers.deform.active
    vg = body.vertex_groups
    names = {x.index: x.name for x in vg}
    gidx = {x.name: x.index for x in vg}
    if claim:
        test, ms = _region(claim["region"]), claim.get("minShare", 0.5)
        bidx = {gidx[n] for n in bones if n in gidx}
        nc = nd = 0
        for v in bm.verts:
            d = v[dl]
            r = {k: w for k, w in d.items() if w > 1e-4}
            tot = sum(r.values())
            if not tot or not test(v.co):
                continue
            sh = sum(w for k, w in r.items() if k in bidx) / tot
            if sh <= 1e-4 or sh >= 0.999:
                continue
            if sh >= ms:
                k = max((k for k in r if k in bidx), key=lambda k: r[k]); d.clear(); d[k] = 1.0; nc += 1
            else:
                rest = {k: w for k, w in r.items() if k not in bidx}; rt = sum(rest.values()); d.clear()
                for k, w in rest.items():
                    d[k] = w / rt
                nd += 1
        print("PEGASUS ripWeld claim verts", nc, "dropped", nd)

    def row(v):
        return {names[k]: w for k, w in v[dl].items() if w > 1e-4}

    def is_arm(v):
        r = row(v)
        return bool(r) and set(r) <= bones

    def is_keep(v):
        r = row(v)
        return bool(r) and set(r) <= (bones | keep)

    side = {}
    for f in bm.faces:
        na = sum(is_arm(v) for v in f.verts)
        side[f.index] = "arm" if 2 * na > len(f.verts) else ("keep" if all(is_keep(v) for v in f.verts) else "other")
    cut = []
    for e in bm.edges:
        s = {side[f.index] for f in e.link_faces}
        if "arm" in s and "other" in s:
            cut.append(e)
    bm.faces.ensure_lookup_table()
    fside = {f: side[f.index] for f in bm.faces}
    bmesh.ops.split_edges(bm, edges=cut)
    corners = _separate_corners(bm, dl, fside, "arm", "other", is_arm)
    fixed = 0
    for v in bm.verts:
        ss = {fside.get(f) for f in v.link_faces}
        if "arm" in ss and not is_arm(v):
            want_arm = True
        elif "other" in ss and "arm" not in ss and is_arm(v):
            want_arm = False
        else:
            continue
        acc, nacc = {}, 0
        for f in v.link_faces:
            for u in f.verts:
                if u is not v and is_arm(u) == want_arm:
                    for n, w in row(u).items():
                        acc[n] = acc.get(n, 0.0) + w
                    nacc += 1
        if not nacc:
            continue
        tot = sum(acc.values())
        d = v[dl]; d.clear()
        for n, w in acc.items():
            d[gidx[n]] = w / tot
        fixed += 1
    bm.to_mesh(body.data); bm.free()
    print("PEGASUS ripWeld edges split", len(cut), "corners", corners, "vertex rows re-sided", fixed)


def _smooth_rider(body, vg, bones, iters):
    """The rider cut is hard (a vertex is 100% on one rider bone), so a raised sword arm or a rider
    thrown back tears at the shoulder and hip seams. Average the weight rows of the rider's own
    vertices (rows made only of `bones`) over the welded edge graph for `iters` passes, so every seam
    between two rider bones (and the rider's Spine1 legs) becomes a short blend. Vertices of the horse
    (rows with any other bone) are never touched and do not contribute. `exclude` bones (the sword)
    stay rigid: a blended blade bends at the hilt, and corrective smooth then carries that bend
    down the whole blade (h3_silver_pegasus: 18 cm off rigid). Rip them free with a second ripWeld
    pass so the blade is its own surface piece, which corrective smooth leaves exact."""
    me = body.data
    names = {x.index: x.name for x in vg}
    key, rep = {}, []
    for v in me.vertices:
        rep.append(key.setdefault(tuple(round(c, 5) for c in v.co), v.index))
    rows = {}
    for v in me.vertices:
        r = {names[x.group]: x.weight for x in v.groups if x.weight > 1e-4}
        if r and set(r) <= bones:
            rows.setdefault(rep[v.index], r)
    nb = {k: set() for k in rows}
    for e in me.edges:
        a, b = rep[e.vertices[0]], rep[e.vertices[1]]
        if a != b and a in rows and b in rows:
            nb[a].add(b); nb[b].add(a)
    cur = rows
    for _ in range(iters):
        nxt = {}
        for k, r in cur.items():
            acc = dict(r)
            for j in nb[k]:
                for n, w in cur[j].items():
                    acc[n] = acc.get(n, 0.0) + w
            tot = sum(acc.values())
            nxt[k] = {n: w / tot for n, w in acc.items()}
        cur = nxt
    moved = 0
    for v in me.vertices:
        k = rep[v.index]
        own = {names[x.group] for x in v.groups if x.weight > 1e-4}
        if k in cur and len(nb[k]) and own and own <= bones:   # not a ripped copy of another side
            _write_row(vg, v, cur[k]); moved += 1
    print("PEGASUS riderSmooth verts", moved, "iters", iters)


def _write_row(vg, v, row):
    top = sorted(((w, n) for n, w in row.items() if w > 1e-4), reverse=True)[:4]
    tot = sum(w for w, _ in top)
    for x in list(v.groups):
        vg[x.group].remove([v.index])
    for w, n in top:
        vg[n].add([v.index], w / tot, 'REPLACE')


def _clip_tab(master):
    tab = {}
    for s in json.load(open(master))["segments"]:
        for i, t in enumerate(range(s["globalStart"], s["globalEnd"])):
            tab[t] = (s["contractSuffix"], i, s["frameCount"])
    return tab


def _interp(ks, i):
    """ks: sorted [(f, value)]; linear, held outside."""
    if i <= ks[0][0]:
        return ks[0][1]
    if i >= ks[-1][0]:
        return ks[-1][1]
    for (f0, a), (f1, b) in zip(ks, ks[1:]):
        if f0 <= i <= f1:
            u = (i - f0) / max(f1 - f0, 1)
            if isinstance(a, (list, tuple)):
                return [x + (y - x) * u for x, y in zip(a, b)]
            return a + (b - a) * u
    return ks[-1][1]


def _sample(clip_keys, i):
    rot, body, plant = {}, {}, {}
    for field, out in (("rot", rot), ("body", body), ("plant", plant)):
        names = {n for k in clip_keys for n in k.get(field, {})}
        for n in names:
            ks = sorted((k["f"], k[field][n]) for k in clip_keys if n in k.get(field, {}))
            out[n] = _interp(ks, i)
    return rot, body, plant


def after_pose(g):
    P = _cfg(g)
    keys = g["cfg"].get("pegasusKeys")
    for r in P.get("riderBones", []):
        g["STATIC"].discard(r["name"])
    if not keys:
        return
    rest, parent_of, posed = g["rest"], g["parent_of"], g["posed_world"]
    order = [b for b in g["bone_names"] if b in parent_of]
    tab = _clip_tab(g["MASTER"])
    legs = P.get("legs", {})
    side_off = P.get("sideOffset", 0.3)
    rest3 = {b: rest[b].to_3x3() for b in rest}
    rest3i = {b: m.inverted() for b, m in rest3.items()}

    def joint(A, b):
        return A[b].translation.copy()

    def rest_joint(b):
        return rest[b].translation.copy()

    def subtree_rot(A, b, M3):
        piv = A[b].translation.copy()
        M = Matrix.Translation(piv) @ M3.to_4x4() @ Matrix.Translation(-piv)
        todo = [b]
        while todo:
            c = todo.pop()
            A[c] = M @ A[c]
            todo += [k for k, p in parent_of.items() if p == c and k in A]

    n_posed = 0
    for t, A in enumerate(posed):
        clip, i, n = tab.get(t, ("Idle", 0, 1))
        ck = keys.get(clip)
        if not ck:
            continue
        rot, bodyp, plant = _sample(ck, i)
        B = {"Root": A["Root"].copy()}
        for b in order:
            par = parent_of[b]
            if par not in B:
                continue
            L = rest[par].inverted() @ rest[b]
            e = rot.get(b)
            if e:
                Rw = (Matrix.Rotation(math.radians(e[2]), 3, 'Z') @ Matrix.Rotation(math.radians(e[1]), 3, 'Y')
                      @ Matrix.Rotation(math.radians(e[0]), 3, 'X'))
                L = L @ (rest3i[b] @ Rw @ rest3[b]).to_4x4()
            B[b] = B[par] @ L
        # whole body: rear about the hooves, roll onto a flank, offset
        feet = {nm: rest_joint(lg["end"]) for nm, lg in legs.items()}
        M = Matrix.Identity(4)
        rear = bodyp.get("rear", 0.0)
        if rear:
            grp = [f for nm, f in feet.items() if nm.endswith("H")] if rear > 0 else [f for nm, f in feet.items() if nm.endswith("F")]
            piv = sum(grp, Vector()) / max(len(grp), 1); piv.x = 0.0
            rh = bodyp.get("rearHip", 0.0)
            if rh and rear > 0:              # rearHip 0..1 moves the pivot from the hind hooves to the pelvis
                hp = rest_joint("Hips"); hp.x = 0.0
                piv = piv + rh * (hp - piv)
            M = Matrix.Translation(piv) @ Matrix.Rotation(math.radians(-rear), 4, 'X') @ Matrix.Translation(-piv)
        roll = bodyp.get("roll", 0.0)
        if roll:
            h = B["Hips"].translation
            piv = Vector((h.x + math.copysign(side_off, roll), 0.0, 0.0))
            M = Matrix.Translation(piv) @ Matrix.Rotation(math.radians(roll), 4, 'Y') @ Matrix.Translation(-piv) @ M
        off = Vector((bodyp.get("x", 0.0), bodyp.get("y", 0.0), bodyp.get("z", 0.0)))
        M = Matrix.Translation(off) @ M
        for b in B:
            if b != "Root":
                B[b] = M @ B[b]
        # planted legs: two-bone IK about the body's lateral axis, then flat hooves
        lat = (M.to_3x3() @ Vector((1, 0, 0))).normalized()
        for nm, lg in legs.items():
            w = max(0.0, min(1.0, plant.get(nm, 0.0)))
            if w <= 1e-3:
                continue
            u, m = lg["ik"]
            tgt = rest_joint(lg["end"])
            tgt = tgt + (Vector(lg.get("targetOffset", (0, 0, 0))))

            def endp(a, b_):
                C = {k: B[k].copy() for k in B}
                subtree_rot(C, u, Matrix.Rotation(a, 3, lat))
                subtree_rot(C, m, Matrix.Rotation(b_, 3, lat))
                return joint(C, lg["end"])
            a, b_ = 0.0, 0.0
            for _ in range(25):
                e0 = endp(a, b_) - tgt
                if e0.length < 1e-4:
                    break
                h = 1e-3
                ja = (endp(a + h, b_) - tgt - e0) / h
                jb = (endp(a, b_ + h) - tgt - e0) / h
                Jm = np.array([ja[:], jb[:]]).T
                step, *_ = np.linalg.lstsq(Jm, -np.array(e0[:]), rcond=None)
                step = np.clip(step, -0.3, 0.3)
                a += float(step[0]); b_ += float(step[1])
            best = (a * w, b_ * w)
            subtree_rot(B, u, Matrix.Rotation(best[0], 3, lat))
            subtree_rot(B, m, Matrix.Rotation(best[1], 3, lat))
            for fb in lg.get("flat", []):
                cur = B[fb].to_3x3(); want = rest3[fb]
                q = cur.to_quaternion().slerp(want.to_quaternion(), w)
                D = q.to_matrix() @ cur.inverted()
                subtree_rot(B, fb, D)
        A.update(B)
        n_posed += 1
    print("PEGASUS keyed frames", n_posed, "clips", sorted(keys))
