def _patch_unit_sid(kpt_path: Path) -> None:
    doc = json.loads(kpt_path.read_text(encoding="utf-8"))
    doc["unitSid"] = "h3_lizardman"
    kpt_path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    results = []
    for clip_id, frames_dir, out_dir, frames_xy, notes in CLIPS:
        result = write_authored_clip(
            clip_id=clip_id,
            frames_dir=frames_dir,
            out_dir=out_dir,
            frames_xy=frames_xy,
            notes=(
                f"{notes}; R*=nearer viewer; Nose=snout tip; "
                "re-eyed all NN sprites; not LK track"
            ),
        )
        _patch_unit_sid(Path(result["keypoints"]))
        result["unitSid"] = "h3_lizardman"
        results.append(result)
    print(json.dumps(results, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
