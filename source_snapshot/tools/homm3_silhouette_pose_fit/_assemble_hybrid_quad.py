#!/usr/bin/env python3
"""Assemble run_hybrid_method_quad.py from _api_pin.json (no hand-typed API names)."""

from __future__ import annotations

import importlib
import importlib.util
import inspect
import json
import sys
from pathlib import Path

PIN_PATH = Path(
    r"V:/Games/Olden Era Playtest Tweak/artifacts/pose_picker_runs/hybrid_method_quad/_api_pin.json"
)
pin = json.loads(PIN_PATH.read_text(encoding="utf-8"))
TOOL = Path(r"V:/Games/Olden Era Playtest Tweak/tools") / pin["tool_dir_name"]
OUT = TOOL / "run_hybrid_method_quad.py"
sys.path.insert(0, str(TOOL))

MOD = pin["mods"]
FN = pin["fn"]
F = pin["fields"]
MESH = pin["meshes"]
NB = pin["notebook"]

# Live checks
for mod_key, names in {
    "mat": ["anim", "choice", "inv"],
    "wid": ["discover", "runtime"],
    "gpu": ["fit"],
    "cmp": ["compose", "prepare", "sprite"],
    "cru": ["nbkwargs", "release"],
    "lock": ["acq", "glock", "relock"],
}.items():
    mod = importlib.import_module(MOD[mod_key])
    for key in names:
        if not hasattr(mod, FN[key]):
            raise RuntimeError(f"missing {MOD[mod_key]}.{FN[key]}")

gpu = importlib.import_module(MOD["gpu"])
fit_sig = set(inspect.signature(getattr(gpu, FN["fit"])).parameters)

lines: list[str] = []


def add(line: str = "") -> None:
    lines.append(line)


add("#!/usr/bin/env python3")
add('"""Hybrid pose method trials for Roc Move, Crusader AttackFront, Behemoth Move, Medusa Hit.')
add("")
add("v2 compound (frugal, <=5 min/clip):")
add("  - silhouette profile init + discrete root search")
add("  - DINOv3-dense joint score (geometry terms zeroed; chain-space off)")
add("  - one articulated round + light physics smooth")
add("  - flyers: pitch+yaw root freedom WITHOUT camera_forward roll")
add("    (v1 DINOv3 preferred ~71 deg roll and banked the roc into a dive)")
add("")
add("Does not overwrite idle keep. Does not apply CURRENT_CASCADE_KEEP (refuses dinov3).")
add("Same knobs for all four clips; only flyer rotation allowances differ by unit class.")
add('"""')
add("")
add("from __future__ import annotations")
add("")
add("import argparse")
add("import json")
add("import os")
add("import sys")
add("import time")
add("from dataclasses import replace")
add("from pathlib import Path")
add("from typing import Any")
add("")
add('ROOT = Path(r"V:/Games/Olden Era Playtest Tweak")')
add(f'TOOL = ROOT / "tools/{pin["tool_dir_name"]}"')
add(f'NOTEBOOK = TOOL / "{NB}"')
add('OUT_ROOT = ROOT / "artifacts/pose_picker_runs/hybrid_method_quad"')
add("BUDGET_SEC = 300.0")
add('METHOD_ID = "hybrid_v3_dinov3_flyer_side_profile"')
add("")
add("if str(TOOL) not in sys.path:")
add("    sys.path.insert(0, str(TOOL))")
add("")
add(f"from {MOD['lock']} import (  # noqa: E402")
add(f"    {FN['acq']},")
add(f"    {FN['glock']},")
add(f"    {FN['relock']},")
add(")")
add(f"from {MOD['cmp']} import (  # noqa: E402")
add(f"    {FN['prepare']},")
add(f"    {FN['sprite']},")
add(f"    {FN['compose']},")
add(")")
add(f"from {MOD['cru']} import (  # noqa: E402")
add(f"    {FN['release']},")
add(f"    {FN['nbkwargs']},")
add(")")
add("")
add("CLIPS: dict[str, dict[str, Any]] = {")
for label, sid, groups, mesh_key, uclass, title in (
    ("roc_move", "h3_roc", "(0,)", "roc", "flyer", "Roc Move (DEF 0)"),
    ("crusader_attack_front", "h3_crusader", "(12,)", "crusader", "ground", "Crusader AttackFront (DEF 12)"),
    ("behemoth_move", "h3_behemoth", "(0,)", "behemoth", "ground", "Behemoth Move (DEF 0)"),
    ("medusa_hitted", "h3_medusa", "(3,)", "medusa", "ground", "Medusa Hit (DEF 3)"),
):
    add(f'    "{label}": {{')
    add(f'        "unit_sid": "{sid}",')
    add(f'        "def_groups": {groups},')
    add(f'        "mesh": ROOT / "artifacts/meshy_downloads" / "{MESH[mesh_key]}",')
    add(f'        "unit_class": "{uclass}",')
    add(f'        "title": "{title}",')
    add("    },")
add("}")
add("")
add("")
add("def _build_isolated_def_choice(widgets, *, unit_sid: str, def_groups: tuple[int, ...]):")
add('    """Build a single-group authentic DEF choice with no idle prefix/postfix."""')
add(f"    from {MOD['mat']} import (")
add(f"        {FN['anim']},")
add(f"        {FN['choice']},")
add(f"        {FN['inv']},")
add("    )")
add("")
add("    if not def_groups:")
add('        raise ValueError("def_groups must be non-empty")')
add("    need = int(def_groups[0])")
add("    donors = [")
add("        choice")
add(f"        for choice in widgets.{FN['discover']}(ROOT)")
add("        if choice.unit_sid == unit_sid")
add(f'        and choice.{F["source_kind"]} == "authentic_def"')
add(f"        and need in (choice.{F['present']} or ())")
add(f"        and choice.{F['lab_dir']} is not None")
add("    ]")
add("    if not donors:")
add('        raise RuntimeError(f"{unit_sid}: no authentic DEF inventory contains group {need}")')
add("    donor = donors[0]")
add(f'    inventory = {FN["inv"]}(Path(donor.{F["lab_dir"]}))')
add("    frames: list[Any] = []")
add("    counts: list[int] = []")
add("    for group in def_groups:")
add("        if int(group) not in inventory or not inventory[int(group)]:")
add("            raise RuntimeError(")
add(f'                f"{{unit_sid}}: DEF group {{group}} missing from {{donor.{F["lab_dir"]}}}"')
add("            )")
add("        group_frames = tuple(inventory[int(group)])")
add("        frames.extend(group_frames)")
add("        counts.append(len(group_frames))")
add(f'    animation = {FN["anim"]}(tuple(int(g) for g in def_groups))')
add(f'    runtime_dir, camera_fit = widgets.{FN["runtime"]}(ROOT, unit_sid, animation)')
add("    return replace(")
add("        donor,")
add(f'        {F["anim"]}=animation,')
add(f'        {F["choice"]}={FN["choice"]}(unit_sid, tuple(int(g) for g in def_groups)),')
add(f'        {F["pilot"]}=runtime_dir,')
add(f'        {F["camera"]}=camera_fit,')
add(f'        {F["frames"]}=tuple(range(len(frames))),')
add(f'        {F["source_frames"]}=tuple(frames),')
add(f'        {F["lab_groups"]}=tuple(int(g) for g in def_groups),')
add(f'        {F["counts"]}=tuple(counts),')
add(f'        {F["seq"]}="isolated_def",')
add("    )")
add("")
add("")
add("def hybrid_kwargs(*, unit_class: str) -> dict[str, Any]:")
add('    """Shared hybrid knobs. Flyer class gets pitch/yaw freedom without dive-roll."""')
add('    flyer = str(unit_class) == "flyer"')
add("    return {")
add('        "score_mode": "dinov3_dense",')
add('        "chain_space_enabled": False,')
add('        "gradient_ladder_enabled": False,')
add('        "ik_enabled": False,')
add('        "collision_enabled": False,')
add('        "collision_weight": 0.0,')
add('        "depth_weight": 0.0,')
add('        "silhouette_weight": 0.0,')
add('        "chroma_weight": 0.0,')
add('        "motion_weight": 0.0,')
add('        "joint_unique_gain_weight": 0.0,')
add('        "fine_unique_gain_weight": 0.0,')
add('        "root_search_enabled": True,')
add('        "root_rotation_axes": (')
add('            ("camera_right", "camera_up")')
add("            if flyer")
add('            else ("camera_forward", "camera_right", "camera_up")')
add("        ),")
add('        "root_rotation_camera_up_limit_deg": 120.0 if flyer else 45.0,')
add('        "root_rotation_first_frame_limit_deg": 90.0 if flyer else 30.0,')
add('        "root_rotation_per_frame_limit_deg": 45.0 if flyer else 30.0,')
add('        "root_rotation_defer_camera_up": True,')
add('        "profile_init_enabled": True,')
add('        "profile_init_camera_basis_mode": (')
add('            "upright_turntable" if flyer else "upright_turntable"')
add("        ),")
add('        "profile_init_yaw_step_deg": 10.0 if flyer else 15.0,')
add('        "profile_init_roll_range_deg": 16.0 if flyer else 8.0,')
add('        "profile_init_roll_step_deg": 8.0,')
add('        "physics_smooth_enabled": True,')
add('        "physics_smooth_stiffness": 90.0,')
add('        "physics_smooth_gravity": 0.81,')
add('        "physics_smooth_gravity_weight": 0.3,')
add('        "articulated_iterations": 1,')
add('        "fine_iterations": 0,')
add('        "base_pose_enabled": False,')
add('        "mid_pose_enabled": False,')
add('        "branch_rescue_enabled": False,')
add("    }")
add("")
add("")
add("def fit_clip(label: str) -> dict[str, Any]:")
add(f"    import {MOD['wid']} as widgets")
add(f"    from {MOD['gpu']} import {FN['fit']}")
add("")
add("    spec = CLIPS[label]")
add('    mesh = Path(spec["mesh"])')
add("    if not mesh.is_file():")
add("        raise FileNotFoundError(mesh)")
add("    out = OUT_ROOT / METHOD_ID / label")
add("    arm_dir = out / METHOD_ID")
add("    arm_dir.mkdir(parents=True, exist_ok=True)")
add("    started = time.perf_counter()")
add("    choice = _build_isolated_def_choice(")
add("        widgets,")
add('        unit_sid=str(spec["unit_sid"]),')
add('        def_groups=tuple(int(g) for g in spec["def_groups"]),')
add("    )")
add(f"    config = {FN['prepare']}(choice, mesh, NOTEBOOK)")
add(f"    gpu_kwargs = {FN['nbkwargs']}(NOTEBOOK)")
add('    gpu_kwargs.update(hybrid_kwargs(unit_class=str(spec["unit_class"])))')
add("    notes = {")
add('        "schema": "hybrid_method_quad.v3",')
add('        "methodId": METHOD_ID,')
add('        "label": label,')
add('        "title": spec["title"],')
add('        "unitClass": spec["unit_class"],')
add('        "budgetSec": BUDGET_SEC,')
add('        "knobs": hybrid_kwargs(unit_class=str(spec["unit_class"])),')
add('        "not": "CURRENT_CASCADE_KEEP; idle keep untouched",')
add('        "v2Failure": "dinov3 preferred ~71deg camera_forward roll -> dive bank",')
add("    }")
add('    (out / "notes.json").write_text(json.dumps(notes, indent=2) + "\\n", encoding="utf-8")')
add("    frame_count = len(config.frame_indices)")
add("""    print(f"fit {label} frames={frame_count} class={spec['unit_class']}", flush=True)""")
add(f"    solved = {FN['fit']}(config, output_dir=arm_dir, **gpu_kwargs)")
add("    elapsed = time.perf_counter() - started")
add('    result_path = Path(solved.pose_result["clipResultPath"])')
add('    payload = json.loads(result_path.read_text(encoding="utf-8"))')
add('    config_out = payload.get("config") or {}')
add('    if str(config_out.get("score_mode")) != "dinov3_dense":')
add("""        raise RuntimeError(f"{label}: expected dinov3_dense, got {config_out.get('score_mode')}")""")
add('    if not bool(config_out.get("physics_smooth_enabled")):')
add("""        raise RuntimeError(f"{label}: physics_smooth_enabled did not stay on")""")
add('    if bool(config_out.get("chain_space_enabled")):')
add("""        raise RuntimeError(f"{label}: chain_space must stay off for dinov3_dense")""")
add('    if not bool(config_out.get("root_search_enabled")):')
add("""        raise RuntimeError(f"{label}: root_search_enabled must stay on for hybrid")""")
add('    root_axes = tuple(config_out.get("root_rotation_axes") or ())')
add('    if str(spec["unit_class"]) == "flyer" and "camera_forward" in root_axes:')
add("        raise RuntimeError(")
add('            f"{label}: flyer hybrid must exclude camera_forward roll, got {root_axes}"')
add("        )")
add(f"    gif = {FN['compose']}(")
add("        clip_root=out,")
add(f"        sprite_dir={FN['sprite']}(choice),")
add("        frame_count=frame_count,")
add('        arms=({"id": METHOD_ID},),')
add("    )")
add('    root0 = (payload.get("poses") or {}).get("0", {}).get("__motion_root_rotation__") or {}')
add("    report = {")
add('        "label": label,')
add('        "title": spec["title"],')
add('        "gif": str(gif).replace("\\\\", "/"),')
add('        "clipResult": str(result_path).replace("\\\\", "/"),')
add('        "score": payload.get("score"),')
add('        "elapsedSec": round(elapsed, 1),')
add('        "budgetSec": BUDGET_SEC,')
add('        "withinBudget": elapsed <= BUDGET_SEC,')
add('        "frameCount": frame_count,')
add('        "unitClass": spec["unit_class"],')
add('        "score_mode": config_out.get("score_mode"),')
add('        "root_search_enabled": config_out.get("root_search_enabled"),')
add('        "root_rotation_axes": list(root_axes),')
add('        "root_rotation_camera_up_limit_deg": config_out.get(')
add('            "root_rotation_camera_up_limit_deg"')
add("        ),")
add('        "root0": root0,')
add('        "physics_smooth_enabled": config_out.get("physics_smooth_enabled"),')
add('        "profile": payload.get("initialization") or payload.get("profile"),')
add('        "proof": "generated-artifact; hybrid trial; not CURRENT_CASCADE_KEEP; not OE runtime",')
add("    }")
add('    (out / "run_report.json").write_text(json.dumps(report, indent=2) + "\\n", encoding="utf-8")')
add("    print(json.dumps(report, indent=2), flush=True)")
add("    if elapsed > BUDGET_SEC:")
add("        raise RuntimeError(")
add('            f"{label}: exceeded {BUDGET_SEC:.0f}s budget ({elapsed:.1f}s); "')
add('            "hybrid knobs must get cheaper before retrying this clip"')
add("        )")
add("    return report")
add("")
add("")
add("def main() -> int:")
add("    parser = argparse.ArgumentParser(description=__doc__)")
add("    parser.add_argument(")
add('        "--clips",')
add('        default="roc_move",')
add('        help=f"comma-separated labels from {sorted(CLIPS)}",')
add("    )")
add("    args = parser.parse_args()")
add('    wanted = [part.strip() for part in str(args.clips).split(",") if part.strip()]')
add("    unknown = sorted(set(wanted) - set(CLIPS))")
add("    if unknown:")
add('        raise SystemExit(f"unknown clips: {unknown}; known={sorted(CLIPS)}")')
add(f"    lock = {FN['acq']}({FN['glock']}(ROOT))")
add("    reports: list[dict[str, Any]] = []")
add("    try:")
add("        for label in wanted:")
add("            reports.append(fit_clip(label))")
add(f"            {FN['release']}()")
add("    finally:")
add(f"        {FN['release']}()")
add(f"        {FN['relock']}(lock, pid=os.getpid())")
add("    summary = {")
add('        "methodId": METHOD_ID,')
add('        "budgetSec": BUDGET_SEC,')
add('        "reports": reports,')
add('        "allWithinBudget": all(bool(row.get("withinBudget")) for row in reports),')
add("    }")
add("    out_dir = OUT_ROOT / METHOD_ID")
add("    out_dir.mkdir(parents=True, exist_ok=True)")
add('    (out_dir / "summary.json").write_text(')
add('        json.dumps(summary, indent=2) + "\\n", encoding="utf-8"')
add("    )")
add('    print(json.dumps({"summary": str(out_dir / "summary.json"), "n": len(reports)}, indent=2))')
add("    return 0")
add("")
add("")
add('if __name__ == "__main__":')
add("    raise SystemExit(main())")
add("")

OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print("WROTE", OUT, "lines", len(lines))

spec = importlib.util.spec_from_file_location("hybrid_v2_check", OUT)
mod = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(mod)
print("IMPORT_OK", mod.METHOD_ID)
for cls in ("flyer", "ground"):
    kw = mod.hybrid_kwargs(unit_class=cls)
    bad = sorted(set(kw) - fit_sig)
    print(cls, kw["root_rotation_axes"], "bad", bad)
    if bad:
        raise SystemExit(f"bad kwargs for {cls}: {bad}")
