def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def loads_jsonc(data: bytes) -> Any:
    return json.loads(re.sub(r"//.*", "", data.decode("utf-8-sig")))


def write(path: Path, data: bytes) -> None:
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def write_json(path: Path, value: Any) -> None:
    write(path, (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode())


def save_png(path: Path, image: Image.Image) -> None:
    out = io.BytesIO()
    image.save(out, "PNG", optimize=True)
    write(path, out.getvalue())


def index_zip(zf: zipfile.ZipFile) -> dict[str, str]:
    return {name.replace("\\", "/").lower(): name for name in zf.namelist()}


def real_member(index: dict[str, str], member: str) -> str:
    hit = index.get(member.replace("\\", "/").lower())
    if not hit:
        raise FileNotFoundError(member)
    return hit


def read(zf: zipfile.ZipFile, index: dict[str, str], member: str) -> bytes:
    return zf.read(real_member(index, member))


def extract_def_frames(zf: zipfile.ZipFile, index: dict[str, str], member: str, temp: Path) -> list[Image.Image]:
    sys.path.insert(0, str(ROOT / "tools"))
    from defextract_py3 import extract_def
    temp.mkdir(parents=True, exist_ok=True)
    source = temp / PurePosixPath(real_member(index, member)).name
    source.write_bytes(read(zf, index, member))
    dest = temp / "out"
    dest.mkdir()
    if not extract_def(str(source), str(dest)):
        raise RuntimeError(f"DEF extraction failed: {member}")
    manifest = load_json(dest / f"{source.stem}.json")
    frame_paths = [
        dest / PurePosixPath(frame.replace("\\", "/"))
        for sequence in manifest.get("sequences") or []
        for frame in sequence.get("frames") or []
    ]
    frames = [Image.open(path).convert("RGBA") for path in frame_paths]
    if not frames:
        raise RuntimeError(f"no frames: {member}")
    return frames


def animation_frames(zf: zipfile.ZipFile, index: dict[str, str], animation: str, temp: Path) -> tuple[list[Image.Image], str]:
    stem = f"sprites/{animation.strip('/')}"
    for suffix in (".def", ".json"):
        member = index.get((stem + suffix).lower())
        if not member:
            continue
        if suffix == ".def":
            return extract_def_frames(zf, index, member, temp), member
        doc = loads_jsonc(read(zf, index, member))
        rows = sorted(doc["images"], key=lambda row: (row.get("group", 0), row.get("frame", 0)))
        base = doc["basepath"].strip("/")
        return [Image.open(io.BytesIO(read(zf, index, f"sprites/{base}/{row['file']}"))).convert("RGBA") for row in rows], member
    raise FileNotFoundError(animation)


def transparent(image: Image.Image) -> Image.Image:
    rgba = image.convert("RGBA")
    bg = rgba.getpixel((0, 0))[:3]
    px = rgba.load()
    for y in range(rgba.height):
        for x in range(rgba.width):
            r, g, b, a = px[x, y]
            if a == 0 or (r, g, b) == bg:
                px[x, y] = (r, g, b, 0)
    return rgba


def fit_icon(image: Image.Image, size: int = 256) -> Image.Image:
    source = image.convert("RGBA")
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    scale = min((size - 24) / source.width, (size - 24) / source.height)
    fitted = source.resize((round(source.width * scale), round(source.height * scale)), Image.Resampling.LANCZOS)
    canvas.alpha_composite(fitted, ((size - fitted.width) // 2, (size - fitted.height) // 2))
    return canvas


def circular(image: Image.Image, size: int) -> Image.Image:
    source = image.convert("RGBA")
    side = max(source.size)
    canvas = Image.new("RGBA", (side, side))
    canvas.alpha_composite(source, ((side - source.width) // 2, (side - source.height) // 2))
    mask = Image.new("L", (side * 4, side * 4))
    ImageDraw.Draw(mask).ellipse((4, 4, side * 4 - 5, side * 4 - 5), fill=255)
    mask = mask.resize((side, side), Image.Resampling.LANCZOS)
    canvas.putalpha(Image.composite(canvas.getchannel("A"), Image.new("L", (side, side)), mask))
    return canvas.resize((size, size), Image.Resampling.LANCZOS)


def flatten(value: Any) -> list[str]:
    if isinstance(value, str):
        return [value]
    if not isinstance(value, list):
        raise TypeError(f"expected nested string list, got {type(value).__name__}")
    return [item for part in value for item in flatten(part)]


def town_docs(spec: FactionSpec, zf: zipfile.ZipFile, index: dict[str, str]) -> tuple[dict, dict]:
    town = loads_jsonc(read(zf, index, spec.town))[spec.key]["town"]
    structures = (loads_jsonc(read(zf, index, spec.structures))[spec.key]["town"]["structures"]
                  if spec.structures else town["structures"])
    return town, structures


def build_town(spec: FactionSpec, zf: zipfile.ZipFile, index: dict[str, str], temp: Path) -> list[Path]:
    root = RUNTIME / "town_scene_refs" / spec.sid
    if root.exists():
        shutil.rmtree(root)
    layers = root / "layers"
    anims = layers / "anims"
    anims.mkdir(parents=True)
    town, structures = town_docs(spec, zf, index)
    background = Image.open(io.BytesIO(read(zf, index, spec.background))).convert("RGBA")
    if background.size != SOURCE_SIZE:
        raise RuntimeError(f"{spec.sid}: background size {background.size}")
    card = root / f"{spec.key.title()}-in-background.png"
    save_png(card, background)
    prebake_mockup(card, root / "mockups" / f"{spec.sid}_background_mock_1920x1080.png")
    positions, animations = [], []
    for order, (structure, row) in enumerate(structures.items()):
        animation = row.get("animation") if isinstance(row, dict) else None
        if not isinstance(animation, str) or f"hota/{spec.key}/town/buildings/" not in animation.lower():
            continue
        frames, member = animation_frames(zf, index, animation, temp / str(order))
        frames = [transparent(frame) for frame in frames]
        layer_id = PurePosixPath(animation).name.lower()
        save_png(layers / f"{layer_id}.png", frames[0])
        if len(frames) > 1:
            names = []
            for number, frame in enumerate(frames):
                name = f"frame_{number:02d}.png"
                save_png(anims / layer_id / name, frame)
                names.append(name)
            animations.append({"id": layer_id, "frameRateMs": 100, "frames": names})
        positions.append({"id": layer_id, "structure": structure, "x": int(row.get("x", 0)),
                          "y": int(row.get("y", 0)), "z": int(row.get("z", 0)), "order": order,
                          "sprite": f"{layer_id}.png",
                          "source": f"{spec.archive.relative_to(ROOT).as_posix()}!{member}",
                          "hidden": bool(row.get("hidden", False))})
    positions_path = layers / "positions.json"
    write_json(positions_path, {"source": f"{spec.archive.relative_to(ROOT).as_posix()}!{spec.structures or spec.town}",
                                "canvas_w": 800, "canvas_h": 374,
                                "layers": sorted(positions, key=lambda row: (row["z"], row["order"]))})
    prebake_positions_file(positions_path)
    write_json(anims / "metadata.json", animations)
    source_slot_map = slot_map(spec)
    mapped, unmapped = {}, []
    for source_slot, row in structures.items():
        target, animation = source_slot_map.get(source_slot), row.get("animation")
        if not target or not isinstance(animation, str):
            if source_slot in flatten(town.get("hallSlots", [])):
                unmapped.append(source_slot)
            continue
        sid, level = target
        mapped.setdefault(sid, {})[level] = PurePosixPath(animation).name.lower()
    native_levels = {}
    for sid, native_to_source in NATIVE_LEVEL_SOURCE_BY_SID.items():
        if sid not in mapped:
            continue
        native_levels[sid] = {}
        for native_level, source_level in native_to_source.items():
            if source_level not in mapped[sid]:
                raise RuntimeError(
                    f"{spec.sid}: native {sid} level {native_level} requires missing source level {source_level}"
                )
            native_levels[sid][native_level] = mapped[sid][source_level]
    write_json(layers / "building_layer_map.json", {
        "buildingLayerIds": {sid: levels[min(levels)] for sid, levels in sorted(mapped.items())},
        "levels": {sid: {str(level): layer for level, layer in sorted(levels.items())} for sid, levels in sorted(mapped.items())},
        "nativeLevels": {sid: {str(level): layer for level, layer in sorted(levels.items())} for sid, levels in sorted(native_levels.items())},
        "sourceOnlyUnmappedHallSlots": sorted(unmapped),
        "runtimeStatus": "source/static validated; native donor-level translation is explicit; town interaction remains runtime unproven",
    })
    icons = {}
    if spec.townhall_kind == "def":
        icons = {i: frame for i, frame in enumerate(extract_def_frames(zf, index, spec.townhall, temp / "townhall"))}
    else:
        doc = loads_jsonc(read(zf, index, spec.townhall))
        base = PurePosixPath(spec.townhall).parent
        icons = {int(row["frame"]): Image.open(io.BytesIO(read(zf, index, f"{base}/townhall/{row['file']}"))).convert("RGBA")
                 for row in doc["images"]}
    icon_dir = root / "building_icons" / "townhall.dir"
    for frame, image in icons.items():
        save_png(icon_dir / f"00_{frame:02d}.png", image)
    icon_map = {}
    source_icon_frames = icon_frames(spec)
    for slot in flatten(town["hallSlots"]):
        if slot in source_slot_map and slot in source_icon_frames:
            frame = source_icon_frames[slot]
            if frame not in icons:
                raise RuntimeError(f"{spec.sid}: missing townhall frame {frame} for {slot}")
            sid, level = source_slot_map[slot]
            icon_map.setdefault(sid, {})[str(level)] = f"00_{frame:02d}.png"
    write_json(root / "building_icons" / "townhall_source_map.json",
               {"source": f"{spec.archive.relative_to(ROOT).as_posix()}!{spec.townhall}",
                "folder": "townhall.dir", "map": icon_map})
    return [path for path in root.rglob("*") if path.is_file()]


def extract_map_def(zf, index, member, dest, temp) -> list[Path]:
    frames = extract_def_frames(zf, index, member, temp)
    folder = dest / (PurePosixPath(real_member(index, member)).stem + ".dir")
    for number, frame in enumerate(frames):
        save_png(folder / f"00_{number:02d}.png", transparent(frame))
    return list(folder.glob("*.png"))


def build_map_objects(spec, zf, index, temp) -> list[Path]:
    city = RUNTIME / "map_object_refs" / f"{spec.sid}_city"
    dwellings = RUNTIME / "map_object_refs" / f"{spec.sid}_dwellings"
    for path in (city, dwellings):
        if path.exists():
            shutil.rmtree(path)
        path.mkdir(parents=True)
    result = extract_map_def(zf, index, spec.city, city, temp / "city")
    for number, member in enumerate(spec.dwellings):
        result += extract_map_def(zf, index, member, dwellings, temp / f"dwelling_{number}")
    from strip_crop_map_building_billboards import process_paths

    pngs = [path for path in result if path.suffix.lower() == ".png"]
    process_paths(pngs, dry_run=False)
    return result


def build_heroes(spec, zf, index, temp) -> tuple[list[Path], dict]:
    result, entries = [], {}
    classes = {source: class_type for class_type, source, _ in spec.hero_classes}
    for number, hero in enumerate(spec.active_heroes, 1):
        config = loads_jsonc(read(zf, index, f"config/hota/{spec.key}/heroes/{hero}.json"))
        row = next(iter(config.values()))
        class_type = classes[row["class"]]
        portrait_dir = "icons/" if spec.key == "factory" else ""
        member = f"sprites/hota/{spec.key}/heroes/{hero}/{portrait_dir}portraitLarge.png"
        source = Image.open(io.BytesIO(read(zf, index, member)))
        sid = f"{spec.sid}_hero_{number}"
        normal, upscaled = PORTRAITS / f"{sid}.png", UPSCALED_PORTRAITS / f"{sid}.png"
        save_png(normal, circular(source, 64))
        save_png(upscaled, circular(source, 1254))
        result += [normal, upscaled]
        entries[sid] = {"source": {"kind": "zip_png", "archive": spec.archive.relative_to(ROOT).as_posix(), "path": member},
                        "name": hero.replace("_", " ").title(), "classType": class_type,
                        "sourceClass": row["class"], "size": [64, 64], "circularAlpha": True}
    for class_type, _source_class, member in spec.hero_classes:
        dest = HERO_MAP / f"{spec.sid}_{class_type}"
        if dest.exists():
            shutil.rmtree(dest)
        dest.mkdir(parents=True)
        frames = extract_def_frames(zf, index, member, temp / class_type)
        if len(frames) != 45:
            raise RuntimeError(f"{dest}: expected 45 frames, got {len(frames)}")
        cursor = 0
        for group in range(10):
            for frame in range(1 if group < 5 else 8):
                save_png(dest / f"{group:02d}_{frame:02d}.png", transparent(frames[cursor]))
                cursor += 1
        write_json(dest / "source.json", {"archive": spec.archive.relative_to(ROOT).as_posix(), "member": member,
                                          "classType": class_type,
                                          "runtimeStatus": "source/static validated; runtime replacement not proven"})
        result += list(dest.glob("*"))
    return result, entries


def merge_portrait_manifest(path: Path, entries: dict, source_key: str, source_value: str) -> None:
    doc = load_json(path)
    target = doc.setdefault("entries", {})
    for prefix in ("homm3_factory_hero_", "homm3_bulwark_hero_"):
        for key in [key for key in target if key.startswith(prefix)]:
            del target[key]
    target.update(entries)
    doc.setdefault("sources", {})[source_key] = source_value
    write_json(path, doc)


EXTERNAL_SOURCE_STATS = {
    ("factory", "h3_halfling", ""): {
        "hp": 4, "offence": 4, "defence": 2, "damageMin": 1, "damageMax": 3,
        "initiative": 5, "speed": 5, "shots": 24, "squadValue": 75, "cost": {"gold": 40},
    },
}
RESOURCE_NAMES = {"crystal": "crystals", "gems": "gemstones"}


def active_unit_lines(manifest: dict) -> list[dict]:
    return list(manifest.get("unitLines") or []) + list(manifest.get("additionalRecruitmentLines") or [])


def normalized_manifest_stats(row: dict) -> dict:
    return {key: value for key, value in row.items() if key != "source"}


def source_stats(config: dict) -> dict:
    cost = {RESOURCE_NAMES.get(key, key): value for key, value in (config.get("cost") or {}).items()}
    result = {
        "hp": config["hitPoints"],
        "offence": config["attack"],
        "defence": config["defense"],
        "damageMin": config["damage"]["min"],
        "damageMax": config["damage"]["max"],
        "initiative": config["speed"],
        "speed": config["speed"],
        "squadValue": config["aiValue"],
        "cost": cost,
    }
    if "shots" in config:
        result["shots"] = config["shots"]
    return result


def validate_active_manifest_contract(spec: FactionSpec) -> dict:
    manifest = load_json(spec.manifest)

    def exact(label: str, actual: Any, expected: Any) -> None:
        if actual != expected:
            raise ValueError(f"{spec.sid}: {label} mismatch: {actual!r} != {expected!r}")

    exact("identity faction SID", (manifest.get("identity") or {}).get("factionSid"), spec.sid)
    exact("unit variants", manifest.get("unitVariants"), ["", "_upg", "_upg_alt"])
    exact("active hero source order", (manifest.get("heroes") or {}).get("sourceHeroConfigs"), list(spec.active_heroes))
    exact("active hero display order", (manifest.get("heroes") or {}).get("names"),
          [hero.replace("_", " ").title() for hero in spec.active_heroes])

    source_assets = manifest.get("sourceAssets") or {}
    archive_rel = spec.archive.relative_to(ROOT).as_posix()
    exact("source archive", source_assets.get("primaryHotAArchive"), archive_rel)
    exact("source archive hash", source_assets.get("primaryHotAArchiveSha256"),
          hashlib.sha256(spec.archive.read_bytes()).hexdigest().upper())
    exact("town backdrop source", source_assets.get("townBackdrop"), spec.background)
    exact("dwelling source order", source_assets.get("dwellingMapObjectOrder"),
          [PurePosixPath(member).name for member in spec.dwellings])

    plugin_rel = PLUGIN.relative_to(ROOT).as_posix()
    city_stem = PurePosixPath(spec.city).stem
    expected_assets = {
        "factionIcon": f"{plugin_rel}/homm3_runtime_assets/faction_icons/{spec.sid}/Icon_Faction_{spec.key.title()}.png",
        "factionCard": f"{plugin_rel}/homm3_runtime_assets/town_scene_refs/{spec.sid}/{spec.key.title()}-in-background.png",
        "cityIcon": f"{plugin_rel}/homm3_runtime_assets/town_hud_icons/{spec.sid}/fort_available.png",
        "cityBillboard": f"{plugin_rel}/homm3_runtime_assets/map_object_refs/{spec.sid}_city/{city_stem}.dir/00_00.png",
        "townSceneFolder": f"{plugin_rel}/homm3_runtime_assets/town_scene_refs/{spec.sid}/",
        "buildingIconFolder": f"{plugin_rel}/homm3_runtime_assets/town_scene_refs/{spec.sid}/building_icons/",
        "cityBillboardFolder": f"{plugin_rel}/homm3_runtime_assets/map_object_refs/{spec.sid}_city/",
        "dwellingBillboardFolder": f"{plugin_rel}/homm3_runtime_assets/map_object_refs/{spec.sid}_dwellings/",
    }
    exact("generated asset paths", manifest.get("assets"), expected_assets)
    expected_primary_billboards = [f"{PurePosixPath(member).stem}.dir/00_00.png" for member in spec.dwellings[:7]]
    exact("primary dwelling billboard order", (manifest.get("runtime") or {}).get("dwellingBillboardImages"),
          expected_primary_billboards)
    additional = list(manifest.get("additionalRecruitmentLines") or [])
    expected_additional = [f"{PurePosixPath(member).stem}.dir/00_00.png" for member in spec.dwellings[7:]]
    exact("additional dwelling count", len(additional), len(expected_additional))
    for row, billboard in zip(additional, expected_additional):
        exact(f"additional dwelling billboard {row.get('baseSid')}", row.get("dwellingBillboardImage"), billboard)

    lines = active_unit_lines(manifest)
    with zipfile.ZipFile(spec.archive) as zf:
        index = index_zip(zf)
        for line in lines:
            base_sid = line.get("baseSid")
            configs = line.get("sourceConfig")
            exact(f"{base_sid} source config count", len(configs or []), 2)
            stats_by_variant = line.get("sourceStats") or {}
            for position, variant in enumerate(("", "_upg")):
                stats_row = stats_by_variant.get(variant) or {}
                declared = normalized_manifest_stats(stats_row)
                external = EXTERNAL_SOURCE_STATS.get((spec.key, base_sid, variant))
                if external is not None:
                    exact(f"{base_sid}{variant} external source label", stats_row.get("source"),
                          "HotA Halfling CRTRAITS row inherited by config/hota/factory/creatures/halfling.json")
                    exact(f"{base_sid}{variant} external source stats", declared, external)
                    continue
                member = f"config/hota/{spec.key}/creatures/{configs[position]}.json"
                exact(f"{base_sid}{variant} source label", stats_row.get("source"), member)
                config_doc = loads_jsonc(read(zf, index, member))
                exact(f"{base_sid}{variant} pinned source stats", declared, source_stats(next(iter(config_doc.values()))))
            exact(f"{base_sid} alternate source label", (stats_by_variant.get("_upg_alt") or {}).get("source"),
                  f"Material-class {line['names'][2]} deliberately inherits {line['names'][1]} source stats")
            exact(f"{base_sid} alternate stats inheritance",
                  normalized_manifest_stats(stats_by_variant.get("_upg_alt") or {}),
                  normalized_manifest_stats(stats_by_variant.get("_upg") or {}))
    return manifest

def expected_import_rows() -> list[dict]:
    rows = []
    for spec in SPECS:
        manifest = load_json(spec.manifest)
        concept = load_json(spec.concept)
        lines = active_unit_lines(manifest)
        concept_lines = concept.get("unitLines") or []
        if [line.get("baseSid") for line in lines] != [line.get("baseSid") for line in concept_lines]:
            raise ValueError(f"{spec.sid}: active/concept unit ownership order mismatch")
        if concept.get("unitVariants") != ["", "_upg", "_upg_alt"]:
            raise ValueError(f"{spec.sid}: concept unit variants drifted")
        for line, concept_line in zip(lines, concept_lines):
            base = line["baseSid"]
            if concept_line.get("variantSids") != line.get("variantSids"):
                raise ValueError(f"{spec.sid}: active/concept variant ownership mismatch for {base}")
            for variant in manifest["unitVariants"]:
                game_sid = line["variantSids"][variant]
                if variant == "_upg_alt":
                    lab_sid = game_sid
                else:
                    lab_sids = concept_line.get("labSids") or {}
                    if variant not in lab_sids:
                        raise ValueError(f"{spec.sid}: explicit lab SID missing for {base}{variant}")
                    lab_sid = lab_sids[variant]
                shell = battle_shell(base, variant)
                rows.append({"battleResPath": f"units/homm3_import/{spec.key}/{game_sid}",
                             "mapResPath": f"units/homm3_import/{spec.key}/{game_sid}_map",
                             "battlePresentationResPath": shell, "mapShellResPath": MAP_SHELL,
                             "swapAdventureMap": True, "bundleName": f"custom_units_{spec.key}_{lab_sid}",
                             "battlePrefabAssetPath": f"Assets/CustomUnits/homm3_lab/{lab_sid}/OwnedSkinned/owned_skinned.prefab",
                             "mapPrefabAssetPath": f"Assets/CustomUnits/homm3_lab/{lab_sid}/OwnedSkinned/owned_skinned.prefab",
                             "audioStemPrefix": f"HOMM3_{lab_sid}_", "gameUnitSids": [game_sid],
                             "xHomm3FactoryBulwarkOwned": OWNER_NOTE})
    # No h3_sandworm_larva row (retired 2026-09-29): the Core overlay defines no h3_sandworm_larva unit (logic or
    # view) and nothing summons one - h3_olgoi_khorkhoi_l.json records "larva support is deferred". An owned-skinned
    # bundle bound to a SID without a Core view is never drawn and fails the attack-clip gate
    # (validate_homm3_owned_skinned_attack_clip_contract.py: "has no units_views row"), so the larva bundle does not
    # ship. Re-add the row together with the Core unit rows when the larva mechanic is implemented.
    return rows


def update_import_and_contract(rows: list[dict]) -> None:
    table = load_json(IMPORT_TABLE)
    owned = {row["gameUnitSids"][0] for row in rows}
    table["entries"] = [row for row in table["entries"]
                        if not owned.intersection(row.get("gameUnitSids") or [])
                        and "xHomm3FactoryBulwarkOwned" not in row] + rows
    write_json(IMPORT_TABLE, table)
    contract = load_json(CONTRACT)
    bundles = contract["bundles"]
    for name in [name for name in bundles if name.startswith(("custom_units_factory_", "custom_units_bulwark_"))]:
        del bundles[name]
    for name in sorted(row["bundleName"] for row in rows):
        data = (BUILD_OUT / name).read_bytes()
        bundles[name] = {"length": len(data), "sha256": hashlib.sha256(data).hexdigest().upper()}
    contract["source"] = "tools/homm3_import/build_out plus existing authoritative release-candidate payload rows"
    write_json(CONTRACT, contract)


def build_faction_icon_and_skill(spec, zf, index) -> list[Path]:
    source = Image.open(io.BytesIO(read(zf, index, spec.icon)))
    icon = fit_icon(source)
    faction = RUNTIME / "faction_icons" / spec.sid / f"Icon_Faction_{spec.key.title()}.png"
    hud = RUNTIME / "town_hud_icons" / spec.sid / "fort_available.png"
    save_png(faction, icon)
    save_png(hud, icon.resize((128, 128), Image.Resampling.LANCZOS))
    skills = []
    for rank, skill_member in enumerate(spec.skill_icons, 1):
        suffix = "" if rank == 1 else f"_{rank}"
        skill = SKILL_ICONS / f"skill_faction_{spec.sid}{suffix}.png"
        skill_source = Image.open(io.BytesIO(read(zf, index, skill_member)))
        save_png(skill, fit_icon(skill_source, 128))
        skills.append(skill)
    return [faction, hud, *skills]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-sources", action="store_true")
    args = parser.parse_args()
    for spec in SPECS:
        if not spec.archive.is_file() or not spec.concept.is_file() or not spec.manifest.is_file():
            raise FileNotFoundError(spec.archive)
        validate_active_manifest_contract(spec)
    rows = expected_import_rows()
    for row in rows:
        if not (BUILD_OUT / row["bundleName"]).is_file():
            raise FileNotFoundError(BUILD_OUT / row["bundleName"])
    if args.check_sources:
        print(f"Factory/Bulwark sources and {len(rows)} built bundles are present.")
        return 0
    files, portrait_entries = [], {}
    with tempfile.TemporaryDirectory(prefix="hota-factory-bulwark-", dir=ROOT / "tools") as temp:
        temp = Path(temp)
        for spec in SPECS:
            with zipfile.ZipFile(spec.archive) as zf:
                index = index_zip(zf)
                files += build_faction_icon_and_skill(spec, zf, index)
                files += build_town(spec, zf, index, temp / spec.key / "town")
                files += build_map_objects(spec, zf, index, temp / spec.key / "map")
                generated, entries = build_heroes(spec, zf, index, temp / spec.key / "heroes")
                files += generated
                portrait_entries.update(entries)
    source = ", ".join(spec.archive.relative_to(ROOT).as_posix() for spec in SPECS)
    merge_portrait_manifest(PORTRAITS / "manifest.json", portrait_entries, "hotaFactoryBulwark", source)
    upscaled_entries = {
        sid: {**entry, "size": [1254, 1254], "generation": "deterministic Lanczos resize from source"}
        for sid, entry in portrait_entries.items()
    }
    merge_portrait_manifest(UPSCALED_PORTRAITS / "manifest.json", upscaled_entries,
                            "hotaFactoryBulwarkDeterministicResize", source)
    update_import_and_contract(rows)
    file_rows = []
    for path in sorted(set(files)):
        data = path.read_bytes()
        file_rows.append({"path": path.relative_to(ROOT).as_posix(), "length": len(data),
                          "sha256": hashlib.sha256(data).hexdigest().upper()})
    write_json(ASSET_MANIFEST, {
        "schemaVersion": 1, "generator": "tools/build_hota_factory_bulwark_runtime_assets.py",
        "sources": [{"factionSid": spec.sid, "archive": spec.archive.relative_to(ROOT).as_posix(),
                     "sha256": hashlib.sha256(spec.archive.read_bytes()).hexdigest().upper(),
                     "factionIconSource": spec.icon,
                     "skillIconSources": list(spec.skill_icons),
                     "activeHeroes": list(spec.active_heroes),
                     "excludedHeroes": [{"id": hero, "reason": reason} for hero, reason in spec.excluded_heroes]}
                    for spec in SPECS],
        "importGameUnitSids": sorted(row["gameUnitSids"][0] for row in rows), "files": file_rows,
        "proofBoundary": {"sourceAssets": "generated artifact validated",
                          "unitBundles": "existing UnityFS bundles hash-owned; deploy and runtime behavior unvalidated",
                          "townAndHeroPresentation": "source/static validated; startup and user-visible runtime unvalidated",
                          "mechanics": "not owned by this generator and unvalidated"},
    })
    print(f"Generated Factory/Bulwark assets, {len(portrait_entries)} heroes, and {len(rows)} import/bundle rows.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
