"""Apply accepted/proposed renames into rename_map artifacts and recovered C#."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from olden_cs_recovery.paths import PACKAGE_ROOT, REPO_ROOT
from olden_cs_recovery.queue_store import method_id_to_filename, to_iso, utc_now
from olden_cs_recovery.renamer.collisions import RENAME_MAP_ENTRIES_DIR
from olden_cs_recovery.schema_validate import validate_instance

RECOVERED_ROOT = PACKAGE_ROOT / "recovered"

_RENAME_MARKER = "// [olden_cs_recovery:rename]"


def rename_entry_path(current_type_name: str) -> Path:
    safe = method_id_to_filename(current_type_name)
    return RENAME_MAP_ENTRIES_DIR / safe


def write_rename_entry(entry: dict[str, Any]) -> Path:
    validate_instance("rename_map_entry.schema.json", entry, entry.get("current_type_name", "<rename>"))
    RENAME_MAP_ENTRIES_DIR.mkdir(parents=True, exist_ok=True)
    path = rename_entry_path(entry["current_type_name"])
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(entry, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(path)
    return path


def find_recovered_paths(current_type_name: str, domain: str | None = None) -> list[Path]:
    """Locate recovered C# files for a type. Fail closed with empty list if none."""
    short = current_type_name.rsplit(".", 1)[-1]
    candidates: list[Path] = []
    if domain == "edb" or current_type_name == "edb":
        edb_dir = RECOVERED_ROOT / "edb"
        if edb_dir.is_dir():
            candidates.extend(sorted(edb_dir.glob("*.cs")))
        # Phase 1 also emitted some edb partials under Hex.Session.Battle by mistake path —
        # only include files whose stem starts with edb_.
        battle_dir = RECOVERED_ROOT / "Hex.Session.Battle"
        if battle_dir.is_dir():
            candidates.extend(sorted(battle_dir.glob("edb_*.cs")))
    else:
        # Prefer namespace folder Hex.Session.Battle/Type.cs
        ns = current_type_name.rsplit(".", 1)[0] if "." in current_type_name else ""
        if ns:
            typed = RECOVERED_ROOT / ns / f"{short}.cs"
            if typed.is_file():
                candidates.append(typed)
        # Fallback: search recovered tree for exact short name file.
        if not candidates and RECOVERED_ROOT.is_dir():
            for path in sorted(RECOVERED_ROOT.rglob(f"{short}.cs")):
                if path.name.startswith("edb_"):
                    continue
                candidates.append(path)
    # Dedup
    seen: set[Path] = set()
    out: list[Path] = []
    for path in candidates:
        resolved = path.resolve()
        if resolved in seen:
            continue
        seen.add(resolved)
        out.append(path)
    return out


def _rel_repo(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO_ROOT.resolve()).as_posix()
    except ValueError:
        return str(path.resolve())


def apply_to_recovered(
    *,
    current_type_name: str,
    proposed_mono_full: str | None,
    decision: str,
    confidence: str | None,
    evidence_classes: list[str],
    domain: str | None = None,
) -> list[str]:
    """
    Annotate recovered C# with rename decision.

    For accepted renames where Mono simple name differs from current short name,
    rename the class declaration. Identity renames only get an evidence marker.
    Does not invent Mono names — proposed_mono_full must already be decided.
    """
    paths = find_recovered_paths(current_type_name, domain=domain)
    if not paths:
        return []

    current_short = current_type_name.rsplit(".", 1)[-1]
    mono_short = (
        proposed_mono_full.rsplit(".", 1)[-1] if proposed_mono_full else None
    )
    updated_rels: list[str] = []

    for path in paths:
        text = path.read_text(encoding="utf-8-sig")
        # Strip prior rename marker block if re-running.
        text = _strip_prior_marker(text)
        marker_lines = [
            _RENAME_MARKER,
            f"// decision={decision} confidence={confidence or 'none'}",
            f"// current_type={current_type_name}",
            f"// mono_type={proposed_mono_full or '(none)'}",
            f"// evidence_classes={','.join(evidence_classes) if evidence_classes else '(none)'}",
            "// Phase 2 rename oracle only — not bar-C promotion.",
        ]
        # Insert after auto-generated header if present, else at top.
        if text.startswith("// <auto-generated>"):
            end = text.find("// </auto-generated>")
            if end != -1:
                end_line = text.find("\n", end)
                insert_at = end_line + 1 if end_line != -1 else len(text)
                text = text[:insert_at] + "\n".join(marker_lines) + "\n" + text[insert_at:]
            else:
                text = "\n".join(marker_lines) + "\n" + text
        else:
            text = "\n".join(marker_lines) + "\n" + text

        if (
            decision == "renamed-accepted"
            and mono_short
            and mono_short != current_short
            and re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", mono_short)
        ):
            # Rename class / partial class declaration only.
            text = re.sub(
                rf"\b(partial\s+)?(class|struct|interface|enum|record)\s+{re.escape(current_short)}\b",
                rf"\1\2 {mono_short}",
                text,
                count=1,
            )

        path.write_text(text, encoding="utf-8", newline="\n")
        updated_rels.append(_rel_repo(path))

    return updated_rels


def _strip_prior_marker(text: str) -> str:
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    i = 0
    while i < len(lines):
        if lines[i].startswith(_RENAME_MARKER):
            i += 1
            while i < len(lines) and lines[i].startswith("//") and (
                lines[i].startswith("// decision=")
                or lines[i].startswith("// current_type=")
                or lines[i].startswith("// mono_type=")
                or lines[i].startswith("// evidence_classes=")
                or lines[i].startswith("// Phase 2 rename")
            ):
                i += 1
            # drop one optional blank line after marker
            if i < len(lines) and lines[i].strip() == "":
                i += 1
            continue
        out.append(lines[i])
        i += 1
    return "".join(out)


def build_member_renames(candidate: dict[str, Any] | None) -> list[dict[str, Any]]:
    if not candidate:
        return []
    out: list[dict[str, Any]] = []
    alignment = candidate.get("memberAlignment") or {}
    for row in alignment.get("exactMethodNameAlignment") or []:
        mono = row.get("mono") or {}
        deobf = row.get("deobf") or {}
        out.append(
            {
                "kind": "method",
                "current_name": str(deobf.get("name") or row.get("name") or ""),
                "mono_name": str(mono.get("name") or row.get("name") or ""),
                "confidence": row.get("confidence"),
            }
        )
    for row in alignment.get("exactFieldNameAlignment") or []:
        mono = row.get("mono") or {}
        deobf = row.get("deobf") or {}
        out.append(
            {
                "kind": "field",
                "current_name": str(deobf.get("name") or row.get("name") or ""),
                "mono_name": str(mono.get("name") or row.get("name") or ""),
                "confidence": row.get("confidence"),
            }
        )
    return [m for m in out if m["current_name"] and m["mono_name"]]


def make_rename_entry(
    *,
    current_type_name: str,
    proposed_mono_full: str | None,
    mono_namespace: str | None,
    mono_simple: str | None,
    decision: str,
    confidence: str | None,
    evidence_classes: list[str],
    second_evidence_present: bool,
    map_score: float | None,
    map_reasons: list[str],
    method_id: str,
    member_renames: list[dict[str, Any]],
    collision_reason: str | None,
    skip_reason: str | None,
    applied_to_recovered: bool,
    recovered_paths: list[str],
    mono_map_path: str,
    notes: str,
) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "current_type_name": current_type_name,
        "proposed_mono_type_name": proposed_mono_full,
        "proposed_mono_namespace": mono_namespace,
        "proposed_mono_simple_name": mono_simple,
        "decision": decision,
        "confidence": confidence,
        "evidence_classes": sorted(evidence_classes),
        "second_evidence_present": second_evidence_present,
        "map_score": map_score,
        "map_reasons": map_reasons,
        "method_id": method_id,
        "member_renames": member_renames,
        "collision_reason": collision_reason,
        "skip_reason": skip_reason,
        "applied_to_recovered": applied_to_recovered,
        "recovered_paths": recovered_paths,
        "mono_map_path": mono_map_path,
        "updated_at": to_iso(utc_now()),
        "notes": notes,
    }
